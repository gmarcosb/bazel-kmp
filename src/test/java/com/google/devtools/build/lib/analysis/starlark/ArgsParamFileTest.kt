package com.google.devtools.build.lib.analysis.starlark

/**
 * Each test method checks the intermediate argument string list generated from the same [ ] with a different param file format. The param file would be generated by writing one
 * argument per line, possibly after filtering out the positional args.
 */
@RunWith(JUnit4::class)
class ArgsParamFileTest : BuildViewTestCase() {
    private var args: Args? = null

    /** Initializes args with a mix of "flags" and "positional arguments.  */ // TODO(bazel-team): Consider rewriting this setup as Starlark code
    @Before
    @Throws(java.lang.Exception::class)
    fun initArgs() {
        args = Args.newArgs(Mutability.create(), getStarlarkSemantics())
        val thread: StarlarkThread? =
            StarlarkThread.createTransient(Mutability.create(), getStarlarkSemantics())
        args.addJoined(
            "--a",
            StarlarkList.of<T?>( /* mutability= */null, "b", "c"),  /* joinWith= */
            ",",
            Starlark.NONE,
            Starlark.NONE,
            Starlark.NONE,
            false,
            false,
            false,
            false,
            thread
        )
        args.addArgument("--nod", Starlark.UNBOUND,  /* format= */Starlark.NONE, thread)
        args.addArgument("pos1", Starlark.UNBOUND,  /* format= */Starlark.NONE, thread)
        args.addAll(
            "--foo",
            StarlarkList.of<T?>( /* mutability= */null, "bar1", "bar2", "bar3"),
            Starlark.NONE,
            Starlark.NONE,
            Starlark.NONE,
            false,
            false,
            false,
            Starlark.NONE,
            false,
            thread
        )
        args.addArgument("--e", "'f'",  /* format= */Starlark.NONE, thread)
        args.addArgument("pos2", Starlark.UNBOUND,  /* format= */Starlark.NONE, thread)
        // Ensure a ParamFileInfo will be returned
        args.useParamsFile("%s", true)
    }

    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun badParamFileFormat() {
        org.junit.Assert.assertThrows<net.starlark.java.eval.EvalException?>(
            net.starlark.java.eval.EvalException::class.java,
            org.junit.function.ThrowingRunnable { args.setParamFileFormat("punch_cards") })
    }

    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun setParamFileFormatTwice() {
        args.setParamFileFormat("shell")
        org.junit.Assert.assertThrows<net.starlark.java.eval.EvalException?>(
            net.starlark.java.eval.EvalException::class.java,
            org.junit.function.ThrowingRunnable { args.setParamFileFormat("shell") })
    }

    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun shell() {
        args.setParamFileFormat("shell")
        Truth.assertThat(toParamFile(args))
            .containsExactly(
                "--a",
                "b,c",
                "--nod",
                "pos1",
                "--foo",
                "bar1",
                "bar2",
                "bar3",
                "--e",
                ShellEscaper.escapeString("'f'"),
                "pos2"
            )
            .inOrder()
        assertThat(args.paramFileInfo.flagsOnly()).isFalse()
    }

    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun multiline() {
        args.setParamFileFormat("multiline")
        Truth.assertThat(toParamFile(args))
            .containsExactly(
                "--a", "b,c", "--nod", "pos1", "--foo", "bar1", "bar2", "bar3", "--e", "'f'", "pos2"
            )
            .inOrder()
        assertThat(args.paramFileInfo.flagsOnly()).isFalse()
    }

    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun flagPerLine() {
        args.setParamFileFormat("flag_per_line")
        Truth.assertThat(toParamFile(args))
            .containsExactly("--a=b,c", "--nod", "pos1", "--foo=bar1 bar2 bar3", "--e='f'", "pos2")
            .inOrder()
        assertThat(args.paramFileInfo.flagsOnly()).isTrue()
    }

    companion object {
        /**
         * Writes out the Args using ParameterFile, returns the output broken down as lines. Note, this
         * does not respect [ParamFileInfo.flagsOnly].
         */
        @Throws(java.lang.Exception::class)
        private fun toParamFile(args: Args): com.google.common.collect.ImmutableList<String?> {
            val bytes: ByteArray
            java.io.ByteArrayOutputStream().use { outputStream ->
                ParameterFile.writeParameterFile(
                    outputStream,
                    args.build({ RepositoryMapping.EMPTY }).arguments(),
                    args.parameterFileType
                )
                bytes = outputStream.toByteArray()
            }
            ByteArrayInputStream(bytes).use { inputStream ->
                java.io.InputStreamReader(inputStream, java.nio.charset.StandardCharsets.UTF_8).use { reader ->
                    return com.google.common.collect.ImmutableList.copyOf<String?>(
                        com.google.common.io.CharStreams.readLines(
                            reader
                        )
                    )
                }
            }
        }
    }
}
