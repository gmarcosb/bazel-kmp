/**
 * Black box tests for git_repository. On Windows, runs without MSYS [ ][WorkspaceTestUtils.bazel]
 * 
 * 
 * General approach to testing:
 * 
 * 
 * We use [GitRepositoryHelper] and [RepoWithRuleWritingTextGenerator] helper
 * classes.
 * 
 * 
 * 1. We are creating some git repository with the preset contents, which will be used for
 * fetching contents for the test. We plan to fetch contents specifying either commit hash, tag,
 * specific branch or default branch. For all test variants, we are creating the same repository, as
 * the same HEAD commit is marked with a tag, and can be addressed with commit hash, main branch,
 * and tag name.
 * 
 * 
 * 2. The contents of the git repository working tree is generated by [ ]. We pass some certain text to that generator; that exact text
 * should appear as a result of the build of the generated target "call_write_text" in the file
 * "out.txt".
 * 
 * 
 * 3. We generate the git_repository repository rule, which refers to the git repository, created
 * in #1, specifying different git repository attributes in each test. We call 'bazel build' for the
 * "call_write_text" target of the external repository, and asserting the contents in the "out.txt"
 * file.
 */
class GitRepositoryBlackBoxTest : AbstractBlackBoxTest() {
    /**
     * Tests usage of git_repository workspace rule with the "tag" attribute. Please see the general
     * approach description in the class javadoc comment.
     */
    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun testCloneAtTag() {
        val repo: Path = context().getTmpDir().resolve("ext_repo")
        setupGitRepository(context(), repo)

        val buildFileContent: String? = String.format(
            "%s\n%s",
            RepoWithRuleWritingTextGenerator.loadRule(""),
            RepoWithRuleWritingTextGenerator.callRule("call_write_text", "out.txt", HELLO_FROM_EXTERNAL_REPOSITORY)
        )
        context()
            .write(
                "MODULE.bazel",
                "git_repository = use_repo_rule(\"@bazel_tools//tools/build_defs/repo:git.bzl\","
                        + " \"git_repository\")",
                "git_repository(",
                "  name='ext',",
                String.format(
                    "  remote='%s',",
                    com.google.devtools.build.lib.blackbox.framework.PathUtils.pathToFileURI(repo.resolve(".git"))
                ),
                "  tag='first',",
                String.format("  build_file_content=\"\"\"%s\"\"\",", buildFileContent),
                ")"
            )

        // This creates Bazel without MSYS, see implementation for details.
        val bazel: BuilderRunner = WorkspaceTestUtils.bazel(context())
        bazel.build("@ext//:call_write_text")
        val outPath: Path? = context().resolveBinPath(bazel, "external/+git_repository+ext/out.txt")
        WorkspaceTestUtils.assertLinesExactly(outPath, HELLO_FROM_EXTERNAL_REPOSITORY)
    }

