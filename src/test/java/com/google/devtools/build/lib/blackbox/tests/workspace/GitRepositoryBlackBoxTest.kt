    /**
     * Tests usage of git_repository workspace rule in the particular use case, when only the commit
     * hash is specified, and the commit is not in the HEAD-reachable subtree, on a separate branch.
     */
    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun testCheckoutOfCommitFromBranch() {
        val repo: Path = context().getTmpDir().resolve("branch_repo")
        val gitRepository: GitRepositoryHelper = initGitRepository(context(), repo)

        context().write(repo.resolve("main.marker").toString())
        gitRepository.addAll()
        gitRepository.commit("Initial commit")

        gitRepository.createNewBranch("demonstrate_branch")

        val generator: RepoWithRuleWritingTextGenerator = RepoWithRuleWritingTextGenerator(repo)
        generator.withOutputText(HELLO_FROM_BRANCH).setupRepository()

        gitRepository.addAll()
        gitRepository.commit("Commit in branch")
        val branchCommitHash: String? = gitRepository.getHead()

        gitRepository.checkout("main")
        generator.withOutputText(HELLO_FROM_EXTERNAL_REPOSITORY).setupRepository()
        gitRepository.addAll()
        gitRepository.commit("Commit in main")

        context()
            .write(
                "MODULE.bazel",
                "git_repository = use_repo_rule(\"@bazel_tools//tools/build_defs/repo:git.bzl\","
                        + " \"git_repository\")",
                "git_repository(",
                "  name='ext',",
                String.format(
                    "  remote='%s',",
                    com.google.devtools.build.lib.blackbox.framework.PathUtils.pathToFileURI(repo.resolve(".git"))
                ),
                String.format("  commit='%s',", branchCommitHash),
                ")"
            )

        // This creates Bazel without MSYS, see implementation for details.
        val bazel: BuilderRunner = WorkspaceTestUtils.bazel(context())
        bazel.build("@ext//:write_text")
        val outPath: Path? = context().resolveBinPath(bazel, "external/+git_repository+ext/out")
        WorkspaceTestUtils.assertLinesExactly(outPath, HELLO_FROM_BRANCH)
    }

    /**
     * Tests usage of git_repository workspace rule in the particular use case, when only the commit
     * hash is specified, and the commit is not in the HEAD-reachable subtree, on a separate tag and
     * not on any branch.
     */
    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun testCheckoutOfCommitFromTag() {
        val repo: Path = context().getTmpDir().resolve("tag_repo")
        val gitRepository: GitRepositoryHelper = initGitRepository(context(), repo)

        context().write(repo.resolve("main.marker").toString())
        gitRepository.addAll()
        gitRepository.commit("Initial commit")

        gitRepository.createNewBranch("demonstrate_branch")

        val generator: RepoWithRuleWritingTextGenerator = RepoWithRuleWritingTextGenerator(repo)
