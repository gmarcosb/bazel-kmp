    }

    /** Tests that the error message is produced if the git repository does not exist.  */
    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun testGitRepositoryErrorMessage() {
        context()
            .write(
                "MODULE.bazel",
                "git_repository = use_repo_rule(\"@bazel_tools//tools/build_defs/repo:git.bzl\","
                        + " \"git_repository\")",
                "git_repository(",
                "  name='ext',",
                "  remote='file:///some_path',",
                "  commit='some_hash',",
                ")"
            )

        // This creates Bazel without MSYS, see implementation for details.
        val bazel: BuilderRunner = WorkspaceTestUtils.bazel(context())
        val result: ProcessResult = bazel.shouldFail().build("@ext//:write_text")
        Truth.assertThat(result.errString()).contains("error running 'git fetch")
        Truth.assertThat(result.errString()).contains("fatal: Could not read from remote repository.")
    }

    companion object {
        private const val HELLO_FROM_EXTERNAL_REPOSITORY = "Hello from GIT repository!"
        private const val HELLO_FROM_BRANCH = "Hello from branch!"

        @Throws(java.lang.Exception::class)
        private fun setupGitRepository(context: BlackBoxTestContext?, repo: Path?): String? {
            val gitRepository: GitRepositoryHelper = initGitRepository(context, repo)

            val generator: RepoWithRuleWritingTextGenerator = RepoWithRuleWritingTextGenerator(repo)
            generator.skipBuildFile().setupRepository()

            gitRepository.addAll()
            gitRepository.commit("Initial commit")
            gitRepository.tag("first")
            return gitRepository.getHead()
        }

        @Throws(java.lang.Exception::class)
        private fun initGitRepository(context: BlackBoxTestContext?, repo: Path?): GitRepositoryHelper {
            com.google.devtools.build.lib.blackbox.framework.PathUtils.deleteTree(repo)
            java.nio.file.Files.createDirectories(repo)
            val gitRepository: GitRepositoryHelper = GitRepositoryHelper(context, repo)
            gitRepository.init()
            return gitRepository
        }
    }
