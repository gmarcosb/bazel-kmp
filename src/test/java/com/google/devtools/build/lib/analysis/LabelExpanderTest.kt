package com.google.devtools.build.lib.analysis

import com.google.devtools.build.lib.actions.Artifact

/** Tests for [LabelExpander].  */
@RunWith(JUnit4::class)
class LabelExpanderTest : BuildViewTestCase() {
    /**
     * A dummy target that resolves labels and receives errors.
     */
    private var dummyTarget: ConfiguredTarget? = null

    /**
     * Artifacts generated by `dummyTarget` identified by their
     * root-relative paths; to be used for mock label-to-artifact mappings.
     */
    private var artifactsByName: MutableMap<String?, Artifact?>? = null

    // Helper methods -----------------------------------------------------------
    @Throws(java.lang.Exception::class)
    private fun setupDummy() {
        dummyTarget = scratchConfiguredTarget(
            "foo", "foo",
            "filegroup(name = 'foo',",
            "          srcs = ['x1','x2','bar/x3', '" + allowedChars + "', 'xx11', 'x11', 'xx1'])"
        )
        collectArtifacts()
    }

    /**
     * Collects all generated mock artifacts for `dummyTarget` and assigns
     * the result to `artifactsByName`.
     */
    private fun collectArtifacts() {
        val builder: com.google.common.collect.ImmutableMap.Builder<String?, Artifact?> =
            com.google.common.collect.ImmutableMap.builder<String?, Artifact?>()
        for (artifact in BuildViewTestCase.getFilesToBuild(dummyTarget).toList()) {
            builder.put(artifact.getRootRelativePath().toString(), artifact)
        }
        artifactsByName = builder.build()
    }

    /**
     * Gets a generated artifact object for a target in package "foo" from `artifactsByName`.
     */
    private fun artifactFor(targetName: String?): Artifact? {
        return artifactsByName!!.get("foo/" + targetName)
    }

    /**
     * Asserts that an expansion with a given mapping produces the expected
     * results.
     */
    @Throws(java.lang.Exception::class)
    private fun assertExpansion(
        expectedResult: String?, expressionToExpand: String?,
        mapping: MutableMap<Label?, Iterable<Artifact?>?>?
    ) {
        assertThat(LabelExpander.expand(expressionToExpand, mapping, dummyTarget.getLabel()))
            .isEqualTo(expectedResult)
    }

    /**
     * Asserts that an expansion with an empty mapping produces the expected
     * results.
     */
    @Throws(java.lang.Exception::class)
    private fun assertExpansion(expected: String?, original: String?) {
        assertExpansion(expected, original, com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>())
    }

    // Actual tests -------------------------------------------------------------
    /**
     * Tests that if no mapping is specified, then strings expand to themselves.
     */
    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun testStringExpandsToItselfWhenNoMappingSpecified() {
        setupDummy()
        assertExpansion("", null)
        assertExpansion("cmd", "cmd")
        assertExpansion("//x:y,:z,w", "//x:y,:z,w")
        assertExpansion(allowedChars, allowedChars)
    }

    /**
     * Tests that in case of a one-to-one label-to-artifact mapping the expansion
     * produces the expected results.
     */
    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun testExpansion() {
        setupDummy()
        assertExpansion(
            "foo/x1", "x1", com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1"))
            )
        )

        assertExpansion(
            "foo/x1", ":x1", com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1"))
            )
        )

        assertExpansion(
            "foo/x1", "//foo:x1", com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1"))
            )
        )
    }

    /**
     * Tests that label extraction works as expected - disallowed label characters
     * are resolved to themselves.
     */
    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun testLabelExtraction() {
        setupDummy()
        assertExpansion(
            "(foo/" + allowedChars + ")", "(//foo:" + allowedChars + ")",
            com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor(allowedChars), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor(allowedChars))
            )
        )

        assertExpansion(
            "foo/x1,foo/x2=foo/bar/x3", "x1,x2=bar/x3",
            com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1")),
                labelFor("x2"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x2")),
                labelFor("bar/x3"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("bar/x3"))
            )
        )
    }

    /**
     * Tests that an exception is thrown when the mapping is not one-to-one.
     */
    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun testThrowsWhenMappingIsNotOneToOne() {
        setupDummy()
        org.junit.Assert.assertThrows<T?>(
            LabelExpander.NotUniqueExpansionException::class.java,
            org.junit.function.ThrowingRunnable {
                LabelExpander.expand(
                    "x1",
                    com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                        labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>()
                    ),
                    dummyTarget.getLabel()
                )
            })

        org.junit.Assert.assertThrows<T?>(
            LabelExpander.NotUniqueExpansionException::class.java,
            org.junit.function.ThrowingRunnable {
                LabelExpander.expand(
                    "x1",
                    com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                        labelFor("x1"),
                        com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1"), artifactFor("x2"))
                    ),
                    dummyTarget.getLabel()
                )
            })
    }

    /**
     * Tests expanding labels that result in a SyntaxException.
     */
    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun testIllFormedLabels() {
        setupDummy()
        assertExpansion(
            "x1:x2:x3", "x1:x2:x3",
            com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1")),
                labelFor("x2"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x2")),
                labelFor("bar/x3"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("bar/x3"))
            )
        )

        assertExpansion(
            "foo://x1 x1/../x2", "foo://x1 x1/../x2",
            com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1")),
                labelFor("x2"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x2")),
                labelFor("bar/x3"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("bar/x3"))
            )
        )

        assertExpansion(
            "//foo:/x1", "//foo:/x1",
            com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1"))
            )
        )

        assertExpansion(
            "//foo:../x1", "//foo:../x1",
            com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1"))
            )
        )

        assertExpansion(
            "//foo:x1/../x2", "//foo:x1/../x2",
            com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1")),
                labelFor("x2"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x2"))
            )
        )

        assertExpansion(
            "//foo:x1/./x2", "//foo:x1/./x2",
            com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1")),
                labelFor("x2"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x2"))
            )
        )

        assertExpansion(
            "//foo:x1//x2", "//foo:x1//x2",
            com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1")),
                labelFor("x2"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x2"))
            )
        )

        assertExpansion(
            "//foo:x1/..", "//foo:x1/..",
            com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1"))
            )
        )

        assertExpansion(
            "//foo:x1/", "//foo:x1/",
            com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1"))
            )
        )

        assertExpansion(":", ":")
    }

    /**
     * Tests that label parsing is greedy (always extracting the longest
     * possible label). This means that if a label is a substring of another
     * label, it should not be expanded but be treated as part of the longer one.
     */
    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun testLabelIsSubstringOfValidLabel() {
        setupDummy()
        assertExpansion(
            "x3=foo/bar/x3", "x3=bar/x3",
            com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("bar/x3"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("bar/x3"))
            )
        )

        assertExpansion(
            "foo/x1,foo/x11,foo/xx1,foo/xx11", "x1,x11,xx1,xx11",
            com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1")),
                labelFor("x11"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x11")),
                labelFor("xx1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("xx1")),
                labelFor("xx11"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("xx11"))
            )
        )

        assertExpansion(
            "//x1", "//x1",
            com.google.common.collect.ImmutableMap.of<Label?, Iterable<Artifact?>?>(
                labelFor("x1"), com.google.common.collect.ImmutableList.of<Artifact?>(artifactFor("x1"))
            )
        )
    }

    companion object {
        /**
         * All characters that the heuristic considers to be part of a target.
         * This is a subset of the allowed label characters. The ones left out may
         * have a special meaning during expression expansion:
         * 
         * 
         *  * comma (",") - may separate labels
         *  * equals sign ("=") - may separate labels
         *  * colon (":") - can only appear in labels, not in target names
         * 
         */
        private val allowedChars = ("_/.-+" + PathFragment.SEPARATOR_CHAR
                + "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789")

        /**
         * Creates fake label in package "foo".
         */
        @Throws(LabelSyntaxException::class)
        private fun labelFor(targetName: String?): Label {
            return Label.create("@//foo", targetName)
        }
    }
}
