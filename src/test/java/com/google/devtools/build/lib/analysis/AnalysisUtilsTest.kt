package com.google.devtools.build.lib.analysis

import com.google.devtools.build.lib.analysis.AnalysisUtils.checkProvider

@RunWith(JUnit4::class)
class AnalysisUtilsTest : ConfigurationTestCase() {
    @org.junit.Test
    fun checkProviderSucceedsOnClassAnnotatedWithAutoValue() {
        checkProvider(AutoValuedClass::class.java)
    }

    @org.junit.Test
    fun checkProviderFailsOnClassGeneratedByAutoValue() {
        val e: java.lang.IllegalArgumentException? =
            org.junit.Assert.assertThrows<java.lang.IllegalArgumentException?>(
                java.lang.IllegalArgumentException::class.java,
                org.junit.function.ThrowingRunnable { checkProvider(AutoValue_AnalysisUtilsTest_AutoValuedClass::class.java) })
        Truth.assertThat(e).hasMessageThat().contains("generated by @AutoValue")
    }

    // Note: this has to be defined outside of checkProviderFailsOnClassGeneratedByAutoValue() so it
    // can be static, which is required by @AutoValue.
    @AutoValue
    internal abstract class AutoValuedClass : TransitiveInfoProvider {
        abstract fun foo(): Int
    }

    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun stampingEnabled_yesIgnoresNostamp() {
        assertThat(AnalysisUtils.isStampingEnabled(TriState.YES, create("--nostamp"))).isTrue()
    }

    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun stampingEnabled_yesPlusStamp() {
        assertThat(AnalysisUtils.isStampingEnabled(TriState.YES, create("--stamp"))).isTrue()
    }

    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun stampingEnabled_noPlusNostamp() {
        assertThat(AnalysisUtils.isStampingEnabled(TriState.NO, create("--nostamp"))).isFalse()
    }

    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun stampingEnabled_noIgnoresStamp() {
        assertThat(AnalysisUtils.isStampingEnabled(TriState.NO, create("--stamp"))).isFalse()
    }

    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun stampingEnabled_autoUsesNostamp() {
        assertThat(AnalysisUtils.isStampingEnabled(TriState.AUTO, create("--nostamp"))).isFalse()
    }

    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun stampingEnabled_autoUsesStamp() {
        assertThat(AnalysisUtils.isStampingEnabled(TriState.AUTO, create("--stamp"))).isTrue()
    }

    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun stampingEnabled_stampDisabledInToolConfig_attributeYes() {
        assertThat(AnalysisUtils.isStampingEnabled(TriState.YES, createExec("--stamp"))).isFalse()
    }

    @org.junit.Test
    @Throws(java.lang.Exception::class)
    fun stampingEnabled_stampDisabledInToolConfig_attributeAuto() {
        assertThat(AnalysisUtils.isStampingEnabled(TriState.AUTO, createExec("--stamp"))).isFalse()
    }
}
