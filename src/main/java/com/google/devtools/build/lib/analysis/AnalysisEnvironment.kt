package com.google.devtools.build.lib.analysis

import com.google.devtools.build.lib.actions.ActionAnalysisMetadata

/**
 * The set of services that are provided to [ConfiguredTarget] objects during initialization.
 * 
 * 
 * These objects should not outlast the analysis phase. Do not pass them to [ ] objects or other persistent objects. There are
 * internal tests to ensure that AnalysisEnvironment objects are not persisted that check the name
 * of this class, so update those tests you change the names of any implementation of this class.
 */
interface AnalysisEnvironment : ActionRegistry {
    /** Returns a callback to be used in this build for reporting analysis errors.  */
    fun getEventHandler(): ExtendedEventHandler?

    /** Returns whether any errors were reported to this instance.  */
    fun hasErrors(): Boolean

    /**
     * Returns the artifact for the derived file `rootRelativePath`.
     * 
     * 
     * **DO NOT USE** in rule implementations. Use [ ][RuleContext.getPackageRelativeArtifact] or [ ][RuleContext.getUniqueDirectoryArtifact], or, if there is
     * really no other way, [RuleContext.getShareableArtifact]
     * instead.
     * 
     * 
     * Creates the artifact if necessary and sets the root of that artifact to `root`.
     * 
     * 
     * This method can create artifacts anywhere in the output tree, thus making it possible for
     * artifacts generated by two different rules to clash. To avoid this, use the artifact creation
     * method on [RuleContext] mentioned above.
     */
    fun getDerivedArtifact(rootRelativePath: PathFragment?, root: ArtifactRoot?): Artifact.DerivedArtifact?

    /**
     * Returns an artifact for the derived file `rootRelativePath` whose changes do not cause a
     * rebuild.
     * 
     * 
     * Creates the artifact if necessary and sets the root of that artifact to `root`.
     * 
     * 
     * This is useful for files that store data that changes very frequently (e.g. current time)
     * but does not substantially affect the result of the build.
     */
    fun getConstantMetadataArtifact(rootRelativePath: PathFragment?, root: ArtifactRoot?): Artifact?

    /** Returns and artifact that represents a runfiles tree.  */
    fun getRunfilesArtifact(rootRelativePath: PathFragment?, root: ArtifactRoot?): SpecialArtifact?

    /**
     * Returns the artifact for the derived TreeArtifact with directory `rootRelativePath`,
     * creating it if necessary, and setting the root of that artifact to `root`. The artifact
     * will be a TreeArtifact.
     */
    fun getTreeArtifact(rootRelativePath: PathFragment?, root: ArtifactRoot?): SpecialArtifact?

    /** Returns an artifact that represents an un-dereferenced symlinks.  */
    fun getSymlinkArtifact(rootRelativePath: PathFragment?, root: ArtifactRoot?): SpecialArtifact?

    /**
     * Returns the artifact for the derived file `rootRelativePath`, creating it if necessary,
     * and setting the root of that artifact to `root`. The artifact will represent the output
     * directory of a `Fileset`.
     */
    fun getFilesetArtifact(rootRelativePath: PathFragment?, root: ArtifactRoot?): Artifact?

    /**
     * Returns the generating action for the given local artifact.
     * 
     * 
     * If the artifact was created in another analysis environment (e.g. by a different configured
     * target instance) or the artifact is a source artifact, it returns null.
     */
    fun getLocalGeneratingAction(artifact: Artifact?): ActionAnalysisMetadata?

    /**
     * Returns the actions that were registered so far with this analysis environment, that is, all
     * the actions that were created by the current target being analyzed.
     */
    fun getRegisteredActions(): com.google.common.collect.ImmutableList<ActionAnalysisMetadata?>?

    /**
     * Returns the Skyframe SkyFunction.Environment if available. Otherwise, null.
     * 
     * 
     * If you need to use this for something other than genquery, please think long and hard about
     * that.
     */
    fun getSkyframeEnv(): SkyFunction.Environment?

    /**
     * Returns the options that affect the Starlark interpreter used for evaluating Starlark rule
     * implementation functions.
     */
    fun getStarlarkSemantics(): StarlarkSemantics?

    /**
     * Returns the `exported_to_java` map defined by the Starlark `@_builtins`
     * pseudo-repo.
     * 
     * 
     * If builtins injection is disabled, this map is empty.
     * 
     * @see StarlarkBuiltinsFunction
     */
    // TODO(#11437): Update docstring once injection can no longer be disabled.
    @Throws(java.lang.InterruptedException::class)
    fun getStarlarkDefinedBuiltins(): com.google.common.collect.ImmutableMap<String?, Any?>?

    /**
     * Returns the Artifact that is used to hold the non-volatile workspace status for the current
     * build request.
     */
    @Throws(java.lang.InterruptedException::class)
    fun getStableWorkspaceStatusArtifact(): Artifact?

    /**
     * Returns the Artifact that is used to hold the volatile workspace status (e.g. build changelist)
     * for the current build request.
     */
    @Throws(java.lang.InterruptedException::class)
    fun getVolatileWorkspaceStatusArtifact(): Artifact?

    /**
     * Declares a dependency on [ ][com.google.devtools.build.lib.skyframe.PrecomputedValue.STAMP_SETTING_MARKER], to indicate that
     * the evaluating configured target may behave differently because of `--stamp`.
     */
    @Throws(java.lang.InterruptedException::class)
    fun declareStampSettingDep()

    /**
     * Returns the set of orphan Artifacts (i.e. Artifacts without generating action). Should only be
     * called after the ConfiguredTarget is created.
     */
    fun getOrphanArtifacts(): com.google.common.collect.ImmutableSet<Artifact?>?

    /**
     * Returns the set of tree artifacts that have the same exec path as some other artifacts. Should
     * only be called after the ConfiguredTarget is created.
     */
    fun getTreeArtifactsConflictingWithFiles(): com.google.common.collect.ImmutableSet<Artifact?>?

    fun getActionKeyContext(): ActionKeyContext?

    /**
     * Returns and registers a Skyframe dependency on the [RepositoryMapping] of the main repo.
     */
    @Throws(java.lang.InterruptedException::class)
    fun getMainRepoMapping(): RepositoryMapping?
}
