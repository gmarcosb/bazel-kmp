package com.google.devtools.build.lib.actions

import com.google.devtools.build.lib.actions.Artifact.Companion.asExecPaths
import com.google.devtools.build.lib.actions.Artifact.Companion.toRootRelativePaths
import com.google.devtools.build.lib.cmdline.Label

/**
 * An Artifact represents a file used by the build system, whether it's a source file or a derived
 * (output) file. Not all Artifacts have a corresponding FileTarget object in the `
 * build.lib.packages` API: for example, low-level intermediaries internal to a given rule,
 * such as a Java class files or C++ object files. However all FileTargets have a corresponding
 * Artifact.
 * 
 * 
 * In any given call to SkyframeExecutor#buildArtifacts(), no two Artifacts in the action graph
 * may refer to the same path.
 * 
 * 
 * Artifacts generally fall into two classifications, source and derived, but there exist a few
 * other cases that are fuzzy and difficult to classify. The following cases exist:
 * 
 * 
 *  * Well-formed source Artifacts will have null generating Actions and a root that is
 * orthogonal to execRoot. (With the root coming from the package path.)
 *  * Well-formed derived Artifacts will have non-null generating Actions, and a root that is
 * below execRoot.
 *  * Symlinked include source Artifacts under the output/include tree will appear to be derived
 * artifacts with null generating Actions.
 *  * Some derived Artifacts, mostly in the genfiles tree and mostly discovered during include
 * validation, will also have null generating Actions.
 * 
 * 
 * 
 * See [ArtifactRoot] for a detailed example on root, execRoot, and related paths.
 * 
 * 
 * In the usual case, an Artifact represents a single file. However, an Artifact may also
 * represent the following:
 * 
 * 
 *  * A TreeArtifact, which is a directory containing a tree of unknown [Artifact]s. In the
 * future, Actions will be able to examine these files as inputs and declare them as outputs
 * at execution time, but this is not yet implemented. This is used for Actions where the
 * inputs and/or outputs might not be discoverable except during Action execution.
 *  * A directory of unknown contents, but not a TreeArtifact. This is a legacy facility and
 * should not be used by any new rule implementations. In particular, the file system cache
 * integrity checks fail for directories.
 *  * A runfiles tree.
 *  * A 'constant metadata' special Artifact. These represent real files, changes to which are
 * ignored by the build system. They are useful for files which change frequently but do not
 * affect the result of a build, such as timestamp files.
 *  * A 'Fileset' special Artifact. This is a legacy type of Artifact and should not be used by
 * new rule implementations.
 *  * A 'symlink' special Artifact. While a symlink can also be represented by a regular
 * Artifact, using a symlink special Artifact would result in deriving the Artifact's SkyValue
 * from the symlinks themselves (lstat, not stat), and not following the symlinks like in
 * regular Artifacts. The underlying symlink can be unresolved, otherwise known as a dangling
 * symlink.
 * 
 * 
 * 
 * While Artifact implements [SkyKey] for memory-saving purposes, Skyframe requests
 * involving artifacts should always go through [Artifact.key] since ordinary derived
 * artifacts should not be requested directly from Skyframe.
 */
abstract class Artifact
private constructor(root: ArtifactRoot, execPath: PathFragment, hashCodeWithOwner: Int) : FileType.HasFileType,
    ActionInput, FileApi, Comparable<Artifact?>, CommandLineItem, ExecutionPhaseSkyKey, StarlarkEncodable {
    override fun compareTo(o: Artifact?): Int {
        return EXEC_PATH_COMPARATOR.compare(this, o)
    }

    private val root: ArtifactRoot

    private val hashCode: Int
    private val execPath: PathFragment

    /** An artifact corresponding to a file in the output tree, generated by an [Action].  */
    open class DerivedArtifact @VisibleForSerialization internal constructor(
        root: ArtifactRoot,
        execPath: PathFragment,
        owner: Any?
    ) : Artifact(root, execPath, HashCodes.hashObjects(execPath, getOwnerToUseForHashCode(owner))), PathStrippable {
        /**
         * An [ActionLookupKey] until [.setGeneratingActionKey] is set, at which point it is
         * an [ActionLookupData], whose [ActionLookupData.getActionLookupKey] will be the
         * same as the original value of owner.
         * 
         * 
         * We overload this field in order to save memory.
         */
        private var owner: Any?

        init {
            com.google.common.base.Preconditions.checkState(
                !root.getExecPath().isEmpty(), "Derived root has no exec path: %s, %s", root, execPath
            )
            this.owner = com.google.common.base.Preconditions.checkNotNull<Any?>(owner)
        }

        /**
         * Called when a configured target's actions are being collected. `generatingActionKey`
         * must have the same owner as this artifact's current [.getArtifactOwner].
         */
        @com.google.common.annotations.VisibleForTesting
        fun setGeneratingActionKey(generatingActionKey: ActionLookupData?) {
            com.google.common.base.Preconditions.checkState(
                this.owner is ActionLookupKey,
                "Already set generating action key: %s (%s %s)",
                this,
                this.owner,
                generatingActionKey
            )
            com.google.common.base.Preconditions.checkState(
                com.google.common.base.Preconditions.checkNotNull<ActionLookupData?>(generatingActionKey, this)
                    .getActionLookupKey() == owner,
                "Owner of generating action key not same as artifact's owner: %s (%s %s)",
                this,
                this.owner,
                generatingActionKey
            )
            this.owner = generatingActionKey
        }

        @com.google.common.annotations.VisibleForTesting
        fun hasGeneratingActionKey(): Boolean {
            return this.owner is ActionLookupData
        }

        /** Can only be called once [.setGeneratingActionKey] is called.  */
        fun getGeneratingActionKey(): ActionLookupData {
            com.google.common.base.Preconditions.checkState(owner is ActionLookupData, "Bad owner: %s %s", this, owner)
            return owner as ActionLookupData
        }

        override fun getArtifactOwner(): ActionLookupKey? {
            return if (owner is ActionLookupKey)
                owner
            else
                getGeneratingActionKey().getActionLookupKey()
        }

        public override fun getOwnerLabel(): Label? {
            return getArtifactOwner().getLabel()
        }

        override fun toDebugString(): String? {
            if (hasGeneratingActionKey()) {
                return super.toDetailString() + " (" + owner + ")"
            }
            return super.toDebugString()
        }

        override fun getRootRelativePath(): PathFragment {
            return getExecPath().relativeTo(getRoot().getExecPath())
        }

        override fun ownersEqual(other: Artifact?): Boolean {
            val that = other as DerivedArtifact
            if (this.owner !is ActionLookupData || that.owner !is ActionLookupData) {
                // Happens when at least one of these artifacts hasn't had its generating action key set
                // yet, so its configured target is still being analyzed. Tolerate.
                return this.getArtifactOwner() == that.getArtifactOwner()
            }
            return this.owner == that.owner
        }

        public override fun expand(stripPaths: UnaryOperator<PathFragment?>): String {
            return stripPaths.apply(getExecPath()).getPathString()
        }

        companion object {
            /** Standard factory method for derived artifacts.  */
            fun create(
                root: ArtifactRoot, execPath: PathFragment, owner: ActionLookupKey?
            ): DerivedArtifact {
                return DerivedArtifact(root, execPath, owner)
            }

            /**
             * Returns the object to use for the hash code for this artifact's owner, with the goal of being
             * consistent across calls to [.setGeneratingActionKey] and also serialization.
             */
            private fun getOwnerToUseForHashCode(owner: Any?): Any? {
                return if (owner is ActionLookupData)
                    owner.getActionLookupKey()
                else
                    owner
            }
        }
    }

    /** Supplies [SourceArtifact] instances and allows for interning of derived artifacts.  */
    interface ArtifactSerializationContext {
        fun getSourceArtifact(execPath: PathFragment?, root: ArtifactRoot?, owner: ArtifactOwner?): SourceArtifact?

        /**
         * Whether to include the generating action key when serializing the given derived artifact in
         * the given context.
         * 
         * 
         * If `false` is returned, [.getOmittedGeneratingActionKey] should be overridden
         * to provide the generating action key upon deserialization.
         */
        fun includeGeneratingActionKey(
            artifact: DerivedArtifact?, context: SerializationDependencyProvider?
        ): Boolean {
            return true
        }

        /**
         * Returns the generating action key to use when one was not serialized.
         * 
         * 
         * Only called if [.includeGeneratingActionKey] returned `false` at serialization
         * time.
         */
        fun getOmittedGeneratingActionKey(
            context: SerializationDependencyProvider?
        ): ActionLookupData? {
            throw java.lang.UnsupportedOperationException()
        }

        fun intern(
            original: DerivedArtifact?, context: SerializationDependencyProvider?
        ): DerivedArtifact? {
            return original
        }
    }

    fun getPath(): Path {
        return root.getRoot().getRelative(getRootRelativePath())
    }

    open fun hasParent(): Boolean {
        return getParent() != null
    }

    /**
     * Returns the parent Artifact containing this Artifact. Artifacts without parents shall return
     * null.
     */
    open fun getParent(): SpecialArtifact? {
        return null
    }

    /**
     * Returns the directory name of this artifact, similar to dirname(1).
     * 
     * 
     * The directory name is always a relative path to the execution directory.
     */
    fun getDirname(): String? {
        return getDirname(execPath)
    }

    public override fun getDirnameForStarlark(semantics: StarlarkSemantics): String? {
        return getDirname(PathMapper.Companion.loadFrom(semantics).map(execPath))
    }

    /** Returns the base file name of this artifact, similar to basename(1).  */
    public override fun getFilename(): String {
        return execPath.getBaseName()
    }

    public override fun getExtension(): String {
        return execPath.getFileExtension()
    }

    /**
     * Checks whether this artifact is of the supplied file type.
     * 
     * 
     * Prefer this method to pulling out strings from the Artifact and passing to [ ][FileType.apply] manually. This method has been optimized to generate a minimum of
     * garbage.
     */
    fun isFileType(fileType: FileType): Boolean {
        return fileType.matches(this)
    }

    /** Checks whether this artifact is of one of the types in the supplied set.  */
    fun isFileType(fileTypeSet: FileTypeSet): Boolean {
        return fileTypeSet.matches(filePathForFileTypeMatcher())
    }

    public override fun filePathForFileTypeMatcher(): String {
        return execPath.filePathForFileTypeMatcher()
    }

    override fun expandToCommandLine(): String {
        return getExecPathString()
    }

    /** Returns the artifact's owning label. May be null.  */
    fun getOwner(): Label? {
        return getOwnerLabel()
    }

    /**
     * Gets the `ActionLookupKey` of the `ConfiguredTarget` that owns this artifact, if it
     * was set. Otherwise, this should be a dummy value -- either [ArtifactOwner.NULL_OWNER] or
     * a dummy owner set in tests. Such a dummy value should only occur for source artifacts if
     * created without specifying the owner, or for special derived artifacts, such as build info
     * artifacts.
     */
    abstract fun getArtifactOwner(): ArtifactOwner?

    /**
     * Returns the root beneath which this Artifact resides, if any. This may be one of the
     * package-path entries (for source Artifacts), or one of the bin, genfiles or includes dirs (for
     * derived Artifacts). It will always be an ancestor of getPath().
     */
    fun getRoot(): ArtifactRoot {
        return root
    }

    public override fun getRootForStarlark(semantics: StarlarkSemantics): FileRootApi? {
        return PathMapper.Companion.loadFrom(semantics).mapRoot(this)
    }

    override fun getExecPath(): PathFragment {
        return execPath
    }

    public override fun getExecPathStringForStarlark(semantics: StarlarkSemantics): String? {
        return PathMapper.Companion.loadFrom(semantics).getMappedExecPathString(this)
    }

    /**
     * Returns the relative path to this artifact relative to its root. It makes no guarantees as to
     * the semantic meaning or the completeness of the returned path value. In other words, no
     * assumptions should be made in terms of where the root portion of the path ends, and the
     * returned value almost always needs to be used in conjunction with its root.
     * 
     * 
     * {#link Artifact#getOutputDirRelativePath()} is more versatile for general use cases.
     */
    abstract fun getRootRelativePath(): PathFragment

    /**
     * Returns the fully-qualified package path to this artifact. By "fully-qualified", it means the
     * returned path is prefixed with "external/<repository name>" if this artifact is in an external
     * repository.
     * 
     * 
     * Do not call this method just because you need a path prefixed with the "external/<repository name>" fragment for external repository artifacts. [* Artifact#getOutputDirRelativePath][* Artifact.getOutputDirRelativePath]
     * is the right one to use in almost all cases.
     * 
    </repository></repository> */
    @Deprecated(
        """This method is only to be used for $(location) and getOutputDirRelativePath
        implementations."""
    )
    open fun getPathForLocationExpansion(): PathFragment {
        return getRootRelativePath()
    }

    /**
     * Returns the path to this artifact relative to an output directory, e.g. the bin directory. Note
     * that this is available on every Artifact type, including source artifacts. As a matter of fact,
     * one of its most common use cases is to construct a derived artifact's output path out of a
     * sibling source artifact's by replacing the basename in its output-dir-relative path.
     */
    open fun getOutputDirRelativePath(siblingRepositoryLayout: Boolean): PathFragment {
        return getRootRelativePath()
    }

    /**
     * Returns the path to this artifact relative to its repository root. As a result, the returned
     * path always starts with a corresponding package name, if exists.
     */
    open fun getRepositoryRelativePath(): PathFragment {
        var relativePath: PathFragment = getRootRelativePath()
        // External artifacts under legacy roots are still prefixed with "external/<repo name>".
        if (root.isLegacy() && relativePath.startsWith(LabelConstants.EXTERNAL_PATH_PREFIX)) {
            relativePath = relativePath.subFragment(2)
        }
        return relativePath
    }

    /** Returns this.getExecPath().getPathString().  */
    override fun getExecPathString(): String {
        return execPath.getPathString()
    }

    fun getRootRelativePathString(): String {
        return getRootRelativePath().getPathString()
    }

    override fun isSymlink(): Boolean {
        return false
    }

    /**
     * Returns the path of this Artifact relative to this containing Artifact. Since ordinary
     * Artifacts correspond to only one Artifact -- itself -- for ordinary Artifacts, this just
     * returns the empty path. For special Artifacts, returns `null`.
     */
    open fun getParentRelativePath(): PathFragment? {
        return PathFragment.EMPTY_FRAGMENT
    }

    @Throws(EvalException::class)
    public override fun getTreeRelativePathString(): String? {
        throw Starlark.errorf(
            "tree_relative_path not allowed for files that are not tree artifact files."
        )
    }

    /**
     * Returns true iff this is a source Artifact as determined by its path and root relationships.
     * Note that this will report all Artifacts in the output tree, including in the include symlink
     * tree, as non-source.
     * 
     * 
     * An [Artifact] is a [SourceArtifact] iff this returns true, and a [ ] otherwise.
     */
    public override fun isSourceArtifact(): Boolean {
        return root.isSourceRoot()
    }

    /**
     * Returns true iff this artifact has a generating action, and that generating action is known.
     */
    fun hasKnownGeneratingAction(): Boolean {
        return !isSourceArtifact()
    }

    /**
     * Returns true iff this artifact represents a runfiles tree.
     * 
     * 
     * If true, this artifact is necessarily a [DerivedArtifact].
     */
    open fun isRunfilesTree(): Boolean {
        return false
    }

    /**
     * Returns true iff this is a TreeArtifact representing a directory tree containing Artifacts.
     * 
     * 
     * if true, this artifact is necessarily a [SpecialArtifact] with type [ ][SpecialArtifactType.TREE].
     */
    open fun isTreeArtifact(): Boolean {
        return false
    }

    /**
     * Returns true iff this is a TreeArtifact that represents a subtree of another TreeArtifact,
     * which may be obtained by calling [.getParent]. The parent must not itself be an artifact
     * for which [.isSubTreeArtifact] returns true.
     */
    open fun isSubTreeArtifact(): Boolean {
        return false
    }

    /**
     * Returns `true` if this is a [TreeFileArtifact] that was created by an action which
     * declared an output directory, as opposed to an action that was generated by an action template
     * expansion.
     * 
     * 
     * Such artifacts should always be stored within a [ ] representing the declared directory
     * and all children, not individually like other derived artifacts.
     */
    open fun isChildOfDeclaredDirectory(): Boolean {
        return false
    }

    /**
     * Returns whether the artifact represents a Fileset.
     * 
     * 
     * if true, this artifact is necessarily a [SpecialArtifact] with type [ ][SpecialArtifactType.FILESET].
     */
    open fun isFileset(): Boolean {
        return false
    }

    /** The disjunction of [.isTreeArtifact] and [.isFileset].  */
    override fun isDirectory(): Boolean {
        return isTreeArtifact() || isFileset()
    }

    /**
     * Returns true iff metadata cache must return constant metadata for the given artifact.
     * 
     * 
     * If true, this artifact is necessarily a [SpecialArtifact] with type [ ][SpecialArtifactType.CONSTANT_METADATA].
     */
    open fun isConstantMetadata(): Boolean {
        return false
    }

    /**
     * For targets in external repositories, this returns the path the artifact live at in the
     * runfiles tree. For local targets, it returns the rootRelativePath.
     */
    fun getRunfilesPath(): PathFragment {
        var relativePath: PathFragment = getRootRelativePath()
        // Runfile paths for external artifacts should be prefixed with "../<repo name>".
        if (root.isLegacy()) {
            // Root-relative paths of external artifacts under legacy roots are already prefixed with
            // "external/<repo name>". Just replace "external" with "..".
            if (relativePath.startsWith(LabelConstants.EXTERNAL_PATH_PREFIX)) {
                relativePath = relativePath.relativeTo(LabelConstants.EXTERNAL_PATH_PREFIX)
                relativePath = LabelConstants.EXTERNAL_RUNFILES_PATH_PREFIX.getRelative(relativePath)
            }
        } else {
            if (root.isExternal()) {
                // Both external source artifacts and external derived artifacts have their repo name as
                // their 2nd level directory name in their exec paths.
                // i.e. external/<repo name>/... and bazel-out/<repo name>/...
                // This is a pure coincidence, and the below line needs to be updated if any of the
                // directory structures change.
                val repoName: String? = execPath.getSegment(1)
                relativePath =
                    LabelConstants.EXTERNAL_RUNFILES_PATH_PREFIX
                        .getRelative(repoName)
                        .getRelative(relativePath)
            }
        }
        // We can't use root.isExternalSource() here since it needs to handle derived artifacts too.
        return relativePath
    }

    public override fun getRunfilesPathString(): String {
        return getRunfilesPath().getPathString()
    }

    fun prettyPrint(): String {
        // toDetailString would probably be more useful to users, but lots of tests rely on the
        // current values.
        return getRootRelativePath().toString()
    }

    override fun equals(other: Any?): Boolean {
        if (this === other) {
            return true
        }
        if (other !is Artifact) {
            return false
        }
        if (getClass() != other.getClass()) {
            return false
        }
        return equalsWithoutOwner(other) && ownersEqual(other)
    }

    private fun hashCodeWithoutOwner(): Int {
        return HashCodes.hashObjects(execPath, root)
    }

    fun equalsWithoutOwner(other: Artifact): Boolean {
        return execPath.equals(other.execPath) && root == other.root
    }

    abstract fun ownersEqual(other: Artifact?): Boolean

    override fun hashCode(): Int {
        return hashCode
    }

    override fun toString(): String {
        return "File:" + toDetailString()
    }

    public override fun objectForEncoding(semantics: StarlarkSemantics): Structure? {
        return MapWrapperStructure(
            com.google.common.collect.ImmutableMap.of<K?, V?>(
                "path",
                getExecPathStringForStarlark(semantics),
                "root",
                getRootForStarlark(semantics).getExecPathString(),
                "short_path",
                getRunfilesPathString()
            )
        )
    }

    /** Returns a string representing the complete artifact path information.  */
    fun toDetailString(): String {
        if (isSourceArtifact()) {
            // Source Artifact: relPath == execPath, & real path is not under execRoot
            return "[" + root + "]" + getRootRelativePathString()
        } else {
            // Derived Artifact: path and root are under execRoot
            //
            // TODO(blaze-team): this is misleading because execution_root isn't unique. Dig the
            // workspace name out and print that also.
            return "[[<execution_root>]" + root.getExecPath() + "]" + getRootRelativePathString()
        }
    }

    open fun toDebugString(): String? {
        if (getOwner() == null || getOwner().toPathFragment().equals(execPath)) {
            return toDetailString()
        }
        return toDetailString() + " (" + getArtifactOwner() + ")"
    }

    public override fun functionName(): SkyFunctionName? {
        return ARTIFACT
    }

    /** [is true.][Artifact.isSourceArtifact]
     */
    class SourceArtifact @com.google.common.annotations.VisibleForTesting constructor(
        root: ArtifactRoot,
        execPath: PathFragment,
        owner: ArtifactOwner
    ) : Artifact(root, execPath, execPath.hashCode()) {
        private val owner: ArtifactOwner

        init {
            this.owner = owner
        }

        /**
         * Source artifacts do not consider their owners in equality checks, since their owners are
         * purely cosmetic.
         */
        override fun ownersEqual(other: Artifact?): Boolean {
            return true
        }

        override fun getRootRelativePath(): PathFragment? {
            return if (getRoot().isExternal()) getExecPath().subFragment(2) else getExecPath()
        }

        override fun getPathForLocationExpansion(): PathFragment {
            return getExecPath()
        }

        override fun getOutputDirRelativePath(siblingRepositoryLayout: Boolean): PathFragment? {
            return if (siblingRepositoryLayout) getRepositoryRelativePath() else getExecPath()
        }

        override fun getRepositoryRelativePath(): PathFragment? {
            return getRootRelativePath()
        }

        override fun getArtifactOwner(): ArtifactOwner {
            return owner
        }

        public override fun getOwnerLabel(): Label? {
            return owner.getLabel()
        }

        fun differentOwnerOrRoot(owner: ArtifactOwner?, root: ArtifactRoot?): Boolean {
            return this.owner != owner || this.getRoot() != root
        }
    }

    /**
     * Special artifact types.
     * 
     * @see SpecialArtifact
     */
    @com.google.common.annotations.VisibleForTesting
    enum class SpecialArtifactType {
        /** A runfiles tree.  */
        RUNFILES,

        /** Google-specific legacy type.  */
        FILESET,

        /**
         * A symlink. Not chased, can be dangling. All we care about is the return value of `readlink()`.
         */
        UNRESOLVED_SYMLINK,

        /** A subtree containing multiple files and directories.  */
        TREE,

        /** Special artifact type for workspace status information.  */
        CONSTANT_METADATA,
    }

    /**
     * A special kind of artifact that either is a fileset or needs special metadata caching behavior.
     * 
     * 
     * We subclass [DerivedArtifact] instead of storing the special attributes inside in
     * order to save memory. The proportion of artifacts that are special is very small, and by not
     * having to keep around the attribute for the rest we save some memory.
     */
    class SpecialArtifact @VisibleForSerialization internal constructor(
        root: ArtifactRoot,
        execPath: PathFragment,
        owner: Any?,
        private val type: SpecialArtifactType?,
        private val parent: SpecialArtifact?,
        parentRelativePath: PathFragment?
    ) : DerivedArtifact(root, execPath, owner) {
        private val parentRelativePath: PathFragment?

        init {
            this.parentRelativePath = parentRelativePath
        }

        override fun isRunfilesTree(): Boolean {
            return type == SpecialArtifactType.RUNFILES
        }

        override fun isFileset(): Boolean {
            return type == SpecialArtifactType.FILESET
        }

        override fun isConstantMetadata(): Boolean {
            return type == SpecialArtifactType.CONSTANT_METADATA
        }

        override fun isTreeArtifact(): Boolean {
            return type == SpecialArtifactType.TREE
        }

        override fun isSubTreeArtifact(): Boolean {
            return type == SpecialArtifactType.TREE && hasParent()
        }

        override fun isSymlink(): Boolean {
            return type == SpecialArtifactType.UNRESOLVED_SYMLINK
        }

        override fun getParent(): SpecialArtifact? {
            return parent
        }

        override fun hasParent(): Boolean {
            return getParent() != null
        }

        override fun getParentRelativePath(): PathFragment? {
            return parentRelativePath
        }

        public override fun valueIsShareable(): Boolean {
            return !isConstantMetadata()
        }

        @VisibleForSerialization
        fun getSpecialArtifactType(): SpecialArtifactType? {
            return type
        }

        companion object {
            @com.google.common.annotations.VisibleForTesting
            fun create(
                root: ArtifactRoot, execPath: PathFragment, owner: ActionLookupKey?, type: SpecialArtifactType?
            ): SpecialArtifact {
                return SpecialArtifact(
                    root, execPath, owner, type,  /* parent= */null,  /* parentRelativePath= */null
                )
            }

            fun createSubTreeArtifact(
                parent: SpecialArtifact, parentRelativePath: PathFragment, owner: Any?
            ): SpecialArtifact {
                com.google.common.base.Preconditions.checkArgument(
                    parent.isTreeArtifact(),
                    "The parent of a subtree artifact (parent-relative path: %s) is not a"
                            + " TreeArtifact: %s",
                    parentRelativePath,
                    parent
                )
                com.google.common.base.Preconditions.checkArgument(
                    !parentRelativePath.containsUplevelReferences() && !parentRelativePath.isAbsolute(),
                    "%s is not a proper normalized relative path",
                    parentRelativePath
                )
                com.google.common.base.Preconditions.checkArgument(
                    !parent.isSubTreeArtifact(),
                    "The parent of a subtree artifact cannot be another subdirectory: %s",
                    parent
                )
                return SpecialArtifact(
                    parent.getRoot(),
                    parent.getExecPath().getRelative(parentRelativePath),
                    owner,
                    SpecialArtifactType.TREE,
                    parent,
                    parentRelativePath
                )
            }

            /**
             * Casts a non-null Starlark value to a `SpecialArtifact` and returns it.
             * 
             * @throws EvalException if the value is not a `SpecialArtifact`.
             */
            @kotlin.jvm.JvmStatic
            @Throws(EvalException::class)
            fun cast(value: Any?, type: SpecialArtifactType?, what: String?): SpecialArtifact {
                com.google.common.base.Preconditions.checkNotNull<Any?>(value)
                if (value is SpecialArtifact) {
                    if (value.getSpecialArtifactType() != type) {
                        throw Starlark.errorf(
                            "Expected directory artifact for %s, but got a File[%s] instead.",
                            what, value.getSpecialArtifactType()
                        )
                    }

                    return value
                }
                throw Starlark.errorf(
                    "Expected directory artifact for %s, but got a %s", what, Starlark.type(value)
                )
            }
        }
    }

    /**
     * Artifact representing a single-file archive with the filesystem tree belonging to a [ ].
     * 
     * 
     * The archive is equivalent to the entire tree artifact -- it contains all of the [ ] (and nothing else) of the tree artifact with their filesystem
     * structure, relative to the [tree artifact directory][SpecialArtifact.getExecPath].
     */
    class ArchivedTreeArtifact private constructor(
        treeArtifact: SpecialArtifact,
        root: ArtifactRoot,
        execPath: PathFragment,
        generatingActionKey: Any?
    ) : DerivedArtifact(root, execPath, generatingActionKey) {
        private val treeArtifact: SpecialArtifact

        init {
            com.google.common.base.Preconditions.checkArgument(
                treeArtifact.isTreeArtifact(), "Not a tree artifact: %s", treeArtifact
            )
            this.treeArtifact = treeArtifact
        }

        override fun getParent(): SpecialArtifact {
            return treeArtifact
        }

        companion object {
            private val DEFAULT_DERIVED_TREE_ROOT: PathFragment? = PathFragment.create(":archived_tree_artifacts")

            /**
             * Creates an [ArchivedTreeArtifact] for a given tree artifact at the path inferred from
             * the provided tree.
             * 
             * 
             * Returned artifact is stored in a permanent location, therefore can be shared across
             * actions and builds.
             * 
             * 
             * Example: for a tree artifact of `bazel-out/k8-fastbuild/bin/directory` returns an
             * [artifact][ArchivedTreeArtifact] of: `bazel-out/:archived_tree_artifacts/k8-fastbuild/bin/directory.zip`.
             */
            fun createForTree(treeArtifact: SpecialArtifact): ArchivedTreeArtifact {
                return createWithCustomDerivedTreeRoot(
                    treeArtifact,
                    DEFAULT_DERIVED_TREE_ROOT,
                    treeArtifact.getRootRelativePath().replaceName(treeArtifact.getFilename() + ".zip")
                )
            }

            /**
             * Creates an [ArchivedTreeArtifact] for a given tree artifact within provided derived
             * tree directory.
             * 
             * 
             * Example: for a tree artifact with root of `bazel-out/k8-fastbuild/bin` returns an
             * [artifact][ArchivedTreeArtifact] of: `bazel-out/{derivedTreeRoot}/k8-fastbuild/bin/{rootRelativePath}` with root of: `bazel-out/{derivedTreeRoot}/k8-fastbuild/bin`.
             * 
             * 
             * Such artifacts should only be used as outputs of intermediate spawns. Action execution
             * results must come from [.createForTree].
             */
            fun createWithCustomDerivedTreeRoot(
                treeArtifact: SpecialArtifact, derivedTreeRoot: PathFragment?, rootRelativePath: PathFragment?
            ): ArchivedTreeArtifact {
                val treeRoot: ArtifactRoot = treeArtifact.getRoot()
                val archiveRoot: PathFragment = embedDerivedTreeRoot(treeRoot.getExecPath(), derivedTreeRoot)
                return ArchivedTreeArtifact(
                    treeArtifact,
                    ArtifactRoot.Companion.asDerivedRoot(getExecRoot(treeRoot), RootType.OUTPUT, archiveRoot),
                    archiveRoot.getRelative(rootRelativePath),
                    treeArtifact.getGeneratingActionKey()
                )
            }

            /**
             * Returns an exec path within the archived artifacts directory tree corresponding to the
             * provided one.
             * 
             * 
             * Example: `bazel-out/k8-fastbuild/bin -> bazel-out/{customDerivedTreeRoot}/k8-fastbuild/bin`.
             */
            fun getExecPathWithinArchivedArtifactsTree(execPath: PathFragment): PathFragment {
                return embedDerivedTreeRoot(execPath, DEFAULT_DERIVED_TREE_ROOT)
            }

            /**
             * Translates provided output `execPath` to one under provided derived tree root.
             * 
             * 
             * Example: `bazel-out/k8-fastbuild/bin -> bazel-out/{derivedTreeRoot}/k8-fastbuild/bin`.
             */
            private fun embedDerivedTreeRoot(
                execPath: PathFragment, derivedTreeRoot: PathFragment?
            ): PathFragment {
                return execPath
                    .subFragment(0, 1)
                    .getRelative(derivedTreeRoot)
                    .getRelative(execPath.subFragment(1))
            }

            private fun getExecRoot(artifactRoot: ArtifactRoot): Path {
                // /output_base/execroot/bazel-out/k8-fastbuild/bin
                val rootPath: Path = artifactRoot.getRoot().asPath()
                val rootPathFragment: PathFragment = rootPath.asFragment()
                // /output_base/execroot
                val execRootPath: PathFragment? =
                    rootPathFragment.subFragment(
                        0, rootPathFragment.segmentCount() - artifactRoot.getExecPath().segmentCount()
                    )
                return rootPath.getFileSystem().getPath(execRootPath)
            }
        }
    }

    /**
     * A special kind of artifact that represents a concrete file created at execution time under its
     * associated parent TreeArtifact.
     * 
     * 
     * TreeFileArtifacts should be only created during execution time inside some special actions
     * to support action inputs and outputs that are unpredictable at analysis time. TreeFileArtifacts
     * should not be created directly by any rules at analysis time.
     * 
     * 
     * There are two types of TreeFileArtifacts:
     * 
     * 
     *  1. Outputs under a directory created by an action using `declare_directory`. In this
     * case, a single action creates both the parent and all of the children. Instances should
     * be created by calling [.createTreeOutput]. [.isChildOfDeclaredDirectory] will
     * return `true`.
     *  1. Outputs of an action template expansion. In this case, the parent directory is not
     * actually produced by any action, but rather serves as a placeholder for dependant actions
     * to declare a dep on during analysis, before the children are known. The children are
     * created by various actions (from the template expansion). Instances should be created by
     * calling [.createTemplateExpansionOutput]. [.isChildOfDeclaredDirectory] will
     * return `false`.
     * 
     */
    class TreeFileArtifact @VisibleForSerialization internal constructor(
        parent: SpecialArtifact,
        parentRelativePath: PathFragment,
        owner: Any?
    ) : DerivedArtifact(parent.getRoot(), parent.getExecPath().getRelative(parentRelativePath), owner) {
        private val parent: SpecialArtifact

        init {
            com.google.common.base.Preconditions.checkArgument(
                parent.isTreeArtifact(),
                "The parent of TreeFileArtifact (parent-relative path: %s) is not a TreeArtifact: %s",
                parentRelativePath,
                parent
            )
            com.google.common.base.Preconditions.checkArgument(
                !parentRelativePath.containsUplevelReferences() && !parentRelativePath.isAbsolute(),
                "%s is not a proper normalized relative path",
                parentRelativePath
            )
            this.parent = parent
        }

        override fun getParent(): SpecialArtifact {
            return parent
        }

        override fun getParentRelativePath(): PathFragment {
            // getTreeRelativePathString is computed from two PathFragments, so we know it's normalized.
            return PathFragment.createAlreadyNormalized(getTreeRelativePathString())
        }

        override fun getTreeRelativePathString(): String {
            // The constructor concatenates the parent's exec path and the parent-relative path, so we can
            // skip the checks in PathFragment#relativeTo and just take a substring.
            return getExecPathString().substring(parent.getExecPathString().length() + 1)
        }

        override fun isChildOfDeclaredDirectory(): Boolean {
            return !isActionTemplateExpansionKey(getArtifactOwner())
        }

        fun isChildOf(artifact: SpecialArtifact?): Boolean {
            return parent == artifact
                    || (parent.isSubTreeArtifact() && parent.getParent() == artifact)
        }

        companion object {
            /**
             * Creates a [TreeFileArtifact] representing a child of the given parent tree artifact.
             * 
             * 
             * The child should already have been created by the parent's generating action. For this
             * reason, [DerivedArtifact.hasGeneratingActionKey] on the parent must be `true`
             * when this is called. The child is set with the same generating action.
             */
            fun createTreeOutput(
                parent: SpecialArtifact, parentRelativePath: PathFragment
            ): TreeFileArtifact {
                com.google.common.base.Preconditions.checkArgument(
                    parent.hasGeneratingActionKey(),
                    "%s has no generating action key (parent owner: %s, parent relative path: %s)",
                    parent,
                    parent.getArtifactOwner(),
                    parentRelativePath
                )
                val generatingActionKey: ActionLookupData = parent.getGeneratingActionKey()
                // Subtree artifacts may be output by actions generated from action template expansion. This
                // method would then be called to create the TreeFileArtifact(s) under the subtree artifact.
                com.google.common.base.Preconditions.checkArgument(
                    !isActionTemplateExpansionKey(generatingActionKey.getActionLookupKey())
                            || parent.isSubTreeArtifact(),
                    "%s owned by action template expansion %s (parent relative path: %s)",
                    parent,
                    generatingActionKey.getActionLookupKey(),
                    parentRelativePath
                )
                return TreeFileArtifact(parent, parentRelativePath, generatingActionKey)
            }

            /**
             * Convenience method for [.createTreeOutput] with a string
             * relative path.
             */
            @kotlin.jvm.JvmStatic
            fun createTreeOutput(
                parent: SpecialArtifact?, parentRelativePath: String?
            ): TreeFileArtifact? {
                return createTreeOutput(parent, PathFragment.create(parentRelativePath))
            }

            /**
             * Creates a [TreeFileArtifact] representing the output of an action generated dynamically
             * by an [ActionTemplate] during the execution phase.
             * 
             * 
             * The returned artifact does not yet have a generating action set.
             */
            fun createTemplateExpansionOutput(
                parent: SpecialArtifact, parentRelativePath: PathFragment, owner: ActionLookupKey
            ): TreeFileArtifact {
                com.google.common.base.Preconditions.checkArgument(
                    isActionTemplateExpansionKey(owner),
                    "Template expansion outputs must be owned by an action template expansion key, but %s is"
                            + " owned by %s (parent relative path: %s)",
                    parent,
                    owner,
                    parentRelativePath
                )
                return TreeFileArtifact(parent, parentRelativePath, owner)
            }

            /**
             * Convenience method for [.createTemplateExpansionOutput] with a string relative path.
             */
            fun createTemplateExpansionOutput(
                parent: SpecialArtifact?, parentRelativePath: String?, owner: ActionLookupKey?
            ): TreeFileArtifact? {
                return createTemplateExpansionOutput(parent, PathFragment.create(parentRelativePath), owner)
            }

            private fun isActionTemplateExpansionKey(key: ActionLookupKey): Boolean {
                return SkyFunctions.ACTION_TEMPLATE_EXPANSION.equals(key.functionName())
            }
        }
    }

    init {
        com.google.common.base.Preconditions.checkNotNull<ArtifactRoot?>(root)
        // Use a precomputed hashcode since there tends to be massive hash-based collections of
        // artifacts. Importantly, the hashcode ought to incorporate the artifact's owner to prevent a
        // hash collision on the same exec path but a different owner (this is the common case for
        // multiple aspects that produce the same output file).
        this.hashCode = hashCodeWithOwner
        this.root = root
        this.execPath = execPath
    }

    public override fun isImmutable(): Boolean {
        return true
    }

    public override fun repr(printer: Printer, semantics: StarlarkSemantics?) {
        if (isSourceArtifact()) {
            printer.append("<source file " + getRootRelativePathString() + ">")
        } else {
            printer.append("<generated file " + getRootRelativePathString() + ">")
        }
    }

    /**
     * A utility class that compares [Artifact]s without taking their owners into account.
     * Should only be used for detecting action conflicts and merging shared action data.
     */
    class OwnerlessArtifactWrapper(private val artifact: Artifact) {
        private val hashCode: Int

        init {
            this.hashCode = artifact.hashCodeWithoutOwner()
        }

        override fun hashCode(): Int {
            return hashCode
        }

        override fun equals(obj: Any?): Boolean {
            return obj is OwnerlessArtifactWrapper
                    && this.artifact.equalsWithoutOwner(obj.artifact)
        }

        override fun toString(): String {
            return com.google.common.base.MoreObjects.toStringHelper(this).add("artifact", artifact.toDebugString())
                .toString()
        }
    }

    companion object {
        val TYPE: Depset.ElementType? = Depset.ElementType.of(Artifact::class.java)

        /** Compares artifact according to their exec paths. Sorts null values first.  */
        @kotlin.jvm.JvmField
        @SerializationConstant
        // "a == b" is an optimization
        val EXEC_PATH_COMPARATOR: java.util.Comparator<Artifact?> = java.util.Comparator { a: Artifact?, b: Artifact? ->
            if (a === b) {
                return@Comparator 0
            } else if (a == null) {
                return@Comparator -1
            } else if (b == null) {
                return@Comparator 1
            } else {
                return@Comparator a.execPath.compareTo(b.execPath)
            }
        }

        /**
         * [com.google.devtools.build.lib.skyframe.ArtifactFunction] does direct filesystem access
         * without declaring Skyframe dependencies if the artifact is a source directory. However, that
         * filesystem access is not invalidated on incremental builds, and we have no plans to fix it,
         * since general consumption of source directories in this way is unsound. Therefore no new bugs
         * are created by declaring [com.google.devtools.build.lib.skyframe.ArtifactFunction] to be
         * hermetic.
         * 
         * 
         * TODO(janakr): Avoid this issue entirely by giving [SourceArtifact] its own `SkyFunction`. Then we can just declare that function to be non-hermetic. That will also save
         * memory since we can make mandatory source artifacts their own SkyKeys!
         */
        val ARTIFACT: SkyFunctionName? = SkyFunctionName.createHermetic("ARTIFACT")

        /**
         * Returns a [SkyKey] that, when built, will produce this artifact. For source artifacts and
         * generated artifacts that may aggregate other artifacts, returns the artifact itself. For normal
         * generated artifacts, returns the key of the generating action.
         * 
         * 
         * Callers should use this method (or the related ones below) in preference to directly
         * requesting an [Artifact] to be built by Skyframe, since ordinary derived artifacts should
         * never be directly built by Skyframe.
         */
        @ThreadSafety.ThreadSafe
        fun key(artifact: Artifact): SkyKey {
            if (artifact.isTreeArtifact() || !artifact.hasKnownGeneratingAction()) {
                return artifact
            }

            return (artifact as DerivedArtifact).getGeneratingActionKey()
        }

        fun <T : Artifact?> keys(artifacts: Iterable<T?>): Iterable<SkyKey?>? {
            return if (artifacts is MutableCollection<T?>)
                Companion.keys<T?>(artifacts)
            else
                com.google.common.collect.Iterables.transform<T?, SkyKey?>(
                    artifacts,
                    com.google.common.base.Function { artifact: Artifact -> key(artifact) })
        }

        fun <T : Artifact?> keys(artifacts: MutableCollection<T?>): MutableCollection<SkyKey?> {
            return if (artifacts is MutableList<T?>)
                Companion.keys<T?>(artifacts) // Use Collections2 instead of Iterables#transform to ensure O(1) size().
            else
                com.google.common.collect.Collections2.transform<T?, SkyKey?>(
                    artifacts,
                    com.google.common.base.Function { artifact: Artifact -> key(artifact) })
        }

        fun <T : Artifact?> keys(artifacts: MutableList<T?>): MutableList<SkyKey?> {
            return com.google.common.collect.Lists.transform<T?, SkyKey?>(
                artifacts,
                com.google.common.base.Function { artifact: Artifact -> key(artifact) })
        }

        private fun getDirname(execPath: PathFragment): String? {
            val parent: PathFragment? = execPath.getParentDirectory()
            return if (parent == null) "/" else parent.getSafePathString()
        }

        // ---------------------------------------------------------------------------
        // Static methods to assist in working with Artifacts
        /** Formatter for execPath PathFragment output.  */
        val ROOT_RELATIVE_PATH_STRING: com.google.common.base.Function<Artifact?, String?> =
            com.google.common.base.Function { artifact: Artifact? -> artifact!!.getRootRelativePath().getPathString() }

        /**
         * Lazily converts artifacts into root-relative path strings. Runfiles trees are ignored by this
         * method.
         */
        fun toRootRelativePaths(artifacts: NestedSet<Artifact?>): Iterable<String?>? {
            return toRootRelativePaths(artifacts.toList())
        }

        /**
         * Lazily converts artifacts into root-relative path strings. Runfiles trees are ignored by this
         * method.
         */
        fun toRootRelativePaths(artifacts: Iterable<Artifact?>): Iterable<String?> {
            return com.google.common.collect.Iterables.transform<Artifact?, String?>(
                com.google.common.collect.Iterables.filter<Artifact?>(
                    artifacts,
                    com.google.common.base.Predicate { a: Artifact? -> !a!!.isRunfilesTree() }),
                com.google.common.base.Function { artifact: Artifact? ->
                    artifact!!.getRootRelativePath().getPathString()
                })
        }

        /**
         * Lazily converts artifacts into execution-time path strings. Runfiles trees are ignored by this
         * * method.
         */
        fun toExecPaths(artifacts: Iterable<Artifact?>): Iterable<String?> {
            return com.google.common.collect.Iterables.transform<Artifact?, String?>(
                com.google.common.collect.Iterables.filter<Artifact?>(
                    artifacts,
                    com.google.common.base.Predicate { a: Artifact? -> !a!!.isRunfilesTree() }),
                com.google.common.base.Function { obj: ActionInput? -> obj.getExecPathString() })
        }

        /**
         * Converts a collection of artifacts into execution-time path strings, and returns those as an
         * immutable list. Runfiles trees are ignored by this method.
         * 
         * 
         * Avoid this method in production code - it flattens the given nested set unconditionally.
         */
        @com.google.common.annotations.VisibleForTesting
        fun asExecPaths(artifacts: NestedSet<Artifact?>): MutableList<String?>? {
            return asExecPaths(artifacts.toList())
        }

        /**
         * Converts a collection of artifacts into execution-time path strings, and returns those as an
         * immutable list. Runfiles trees are ignored by this method.
         */
        fun asExecPaths(artifacts: Iterable<Artifact?>): MutableList<String?> {
            return com.google.common.collect.ImmutableList.copyOf<String?>(toExecPaths(artifacts))
        }

        /**
         * Renders a collection of artifacts as execution-time paths and joins them into a single string.
         * Runfiles trees are ignored by this method.
         */
        fun joinExecPaths(delimiter: String, artifacts: Iterable<Artifact?>): String {
            return com.google.common.base.Joiner.on(delimiter).join(toExecPaths(artifacts))
        }

        /**
         * Convenience method to filter the files to build for a certain filetype.
         * 
         * @param artifacts the files to filter
         * @param allowedType the allowed filetype
         * @return all members of filesToBuild that are of one of the allowed filetypes
         */
        fun filterFiles(artifacts: Iterable<Artifact>, allowedType: FileType): MutableList<Artifact?> {
            val filesToBuild: MutableList<Artifact?> = java.util.ArrayList<Artifact?>()
            for (artifact in artifacts) {
                if (allowedType.apply(artifact.getFilename())) {
                    filesToBuild.add(artifact)
                }
            }
            return filesToBuild
        }

        /** Converts artifacts into their exec paths. Returns an immutable list.  */
        fun asPathFragments(artifacts: Iterable<out Artifact?>): MutableList<PathFragment?> {
            return com.google.common.collect.Streams.stream(artifacts)
                .map<PathFragment?> { obj: Artifact? -> obj!!.getExecPath() }
                .collect(com.google.common.collect.ImmutableList.toImmutableList<PathFragment?>())
        }

        /** Returns the exec paths of the input artifacts in alphabetical order.  */
        fun asSortedPathFragments(input: Iterable<Artifact?>): com.google.common.collect.ImmutableList<PathFragment?> {
            return com.google.common.collect.Streams.stream<Artifact?>(input)
                .map<PathFragment?>(java.util.function.Function { obj: Artifact? -> obj!!.getExecPath() }).sorted()
                .collect(com.google.common.collect.ImmutableList.toImmutableList<PathFragment?>())
        }
    }
