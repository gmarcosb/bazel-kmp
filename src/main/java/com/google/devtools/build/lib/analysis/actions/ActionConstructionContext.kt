package com.google.devtools.build.lib.analysis.actions

import com.google.devtools.build.lib.actions.ActionKeyContext

/**
 * Contains all API required to construct actions in the context of some target or an aspect applied
 * to a target. Depend on this interface instead of the full RuleContext to avoid accidental data
 * dependency on attribute values.
 * 
 * 
 * This a "native" equivalent of Starlark's `ctx.actions`.
 */
interface ActionConstructionContext : ActionRegistry {
    /** Returns the bin directory for constructed actions.  */
    fun getBinDirectory(): ArtifactRoot?

    /**
     * Returns the action owner that should be used for the default execution group's execution
     * platform.
     */
    fun getActionOwner(): ActionOwner?

    /**
     * Returns the action owner that should be used for actions with the given exec group's execution
     * platform. If an invalid exec group is given, returns null.
     */
    fun getActionOwner(execGroup: String?): ActionOwner?

    /** Returns the action key context.  */
    fun getActionKeyContext(): ActionKeyContext?

    /** Returns the [BuildConfigurationValue] for which the given rule is analyzed.  */
    fun getConfiguration(): BuildConfigurationValue?

    /** The current analysis environment.  */
    fun getAnalysisEnvironment(): AnalysisEnvironment?

    /**
     * Creates an artifact under a given root with the given root-relative path.
     * 
     * 
     * Verifies that it is in the root-relative directory corresponding to the package of the rule,
     * thus ensuring that it doesn't clash with other artifacts generated by other rules using this
     * method.
     */
    fun getDerivedArtifact(rootRelativePath: PathFragment?, root: ArtifactRoot?): Artifact.DerivedArtifact?

    /**
     * Creates a TreeArtifact under a given root with the given root-relative path.
     * 
     * 
     * Verifies that it is in the root-relative directory corresponding to the package of the rule,
     * thus ensuring that it doesn't clash with other artifacts generated by other rules using this
     * method.
     */
    fun getTreeArtifact(rootRelativePath: PathFragment?, root: ArtifactRoot?): SpecialArtifact?

    /**
     * Returns an artifact that can be an output of shared actions. Only use when there is no other
     * option.
     * 
     * 
     * This artifact can be created anywhere in the output tree, which, in addition to making
     * sharing possible, opens up the possibility of action conflicts and makes it impossible to infer
     * the label of the rule creating the artifact from the path of the artifact.
     */
    fun getShareableArtifact(rootRelativePath: PathFragment?, root: ArtifactRoot?): Artifact?

    /**
     * Returns the implicit output artifact for a given template function. If multiple or no artifacts
     * can be found as a result of the template, an exception is thrown.
     */
    @Throws(java.lang.InterruptedException::class)
    fun getImplicitOutputArtifact(function: ImplicitOutputsFunction?): Artifact?

    /**
     * Returns an artifact with a given file extension. All other path components are the same as in
     * `pathFragment`.
     */
    fun getRelatedArtifact(pathFragment: PathFragment?, extension: String?): Artifact.DerivedArtifact?

    /**
     * Creates an artifact in a directory that is unique to the rule, thus guaranteeing that it never
     * clashes with artifacts created by other rules.
     * 
     * @param uniqueDirectorySuffix suffix of the directory - it will be prepended
     */
    fun getUniqueDirectoryArtifact(uniqueDirectorySuffix: String?, relative: String?): Artifact?

    /**
     * Creates an artifact in a directory that is unique to the rule, thus guaranteeing that it never
     * clashes with artifacts created by other rules.
     * 
     * @param uniqueDirectorySuffix suffix of the directory - it will be prepended
     */
    fun getUniqueDirectoryArtifact(uniqueDirectorySuffix: String?, relative: PathFragment?): Artifact?

    /**
     * Creates an artifact in a directory that is unique to the rule, thus guaranteeing that it never
     * clashes with artifacts created by other rules.
     */
    fun getUniqueDirectoryArtifact(
        uniqueDirectory: String?, relative: PathFragment?, root: ArtifactRoot?
    ): Artifact?

    /**
     * Returns a path fragment qualified by the rule name and unique fragment to
     * disambiguate artifacts produced from the source file appearing in
     * multiple rules.
     * 
     * 
     * For example "pkg/dir/name" -> "pkg/&lt;fragment>/rule/dir/name.
     */
    fun getUniqueDirectory(fragment: PathFragment?): PathFragment?

    /**
     * Returns the root of either the "bin" or "genfiles" tree, based on this target and the current
     * configuration. The choice of which tree to use is based on the rule with which this target
     * (which must be an OutputFile or a Rule) is associated.
     */
    fun getBinOrGenfilesDirectory(): ArtifactRoot?

    /**
     * Returns the root-relative path fragment under which output artifacts of this rule should go.
     * 
     * 
     * Note that:
     * 
     * 
     *  * This doesn't guarantee that there are no clashes with rules in the same package.
     *  * If possible, [.getPackageRelativeArtifact] should be
     * used instead of this method.
     * 
     * 
     * Ideally, user-visible artifacts should all have corresponding output file targets, all others
     * should go into a rule-specific directory. [.getUniqueDirectoryArtifact])
     * ensures that this is the case.
     */
    fun getPackageDirectory(): PathFragment?

    /**
     * Creates an artifact in a directory that is unique to the package that contains the rule, thus
     * guaranteeing that it never clashes with artifacts created by rules in other packages.
     */
    fun getPackageRelativeArtifact(relative: PathFragment?, root: ArtifactRoot?): Artifact?

    /** Returns the [PlatformInfo] describing the target's default execution platform.  */
    fun getExecutionPlatform(): PlatformInfo?

    /**
     * Returns the [PlatformInfo] describing the given exec group's execution platform. Returns
     * null if a nonexistent `execGroup` name is given.
     */
    fun getExecutionPlatform(execGroup: String?): PlatformInfo?

    /**
     * Returns the [com.google.devtools.build.lib.analysis.RuleErrorConsumer] for reporting rule
     * errors.
     */
    fun getRuleErrorConsumer(): RuleErrorConsumer?
}
