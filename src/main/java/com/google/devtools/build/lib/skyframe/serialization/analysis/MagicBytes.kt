package com.google.devtools.build.lib.skyframe.serialization.analysis

import java.io.IOException

/**
 * A utility class to handle the magic bytes used to identify different versions of the wire format.
 * 
 * 
 * The magic byte sequence is `0x8000`. This specific sequence is chosen because it can
 * never be produced by a CodedOutputStream when writing a valid varint integer. Varint encoding
 * uses the most significant bit (MSB) of a byte to indicate if more bytes follow. A byte of `0x80` has its MSB set, implying more bytes are coming. However, a following byte of `0x00`
 * as the final byte of a varint is not a canonical representation and is not generated by
 * CodedOutputStream. This makes `0x8000` a safe and unique marker.
 */
internal object MagicBytes {
    /** The magic byte sequence (0x8000) used to identify the new wire format.  */
    private val magicBytes = byteArrayOf(0x80.toByte(), 0x00)

    /**
     * Writes the magic byte sequence to the given CodedOutputStream.
     * 
     * @param stream the CodedOutputStream to write to.
     * @throws IOException if an I/O error occurs.
     */
    @Throws(IOException::class)
    fun writeMagicBytes(stream: java.io.OutputStream) {
        stream.write(magicBytes)
    }

    /**
     * Checks if the beginning of the byte array contains the magic byte sequence.
     * 
     * @param bytes the byte array to read from.
     * @return `true` if the array starts with the magic bytes, `false` otherwise.
     */
    fun hasMagicBytes(bytes: ByteArray): Boolean {
        return bytes.size >= 2 && bytes[0] == magicBytes[0] && bytes[1] == magicBytes[1]
    }

    @com.google.common.annotations.VisibleForTesting
    fun magicBytes(): ByteArray {
        return magicBytes
    }
}
