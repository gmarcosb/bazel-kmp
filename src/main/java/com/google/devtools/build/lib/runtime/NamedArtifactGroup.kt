package com.google.devtools.build.lib.runtime

import com.google.devtools.build.lib.actions.Artifact

/**
 * A [BuildEvent] introducing a set of artifacts to be referred to later by its name. Those
 * events are generated by the [BuildEventStreamer] upon seeing an [ ], if necessary.
 */
internal class NamedArtifactGroup(private val name: String?, completionContext: CompletionContext, set: NestedSet<*>) :
    BuildEvent {
    private val completionContext: CompletionContext
    private val set: NestedSet<*> // of Artifact or ExpandedArtifact

    /**
     * Create a [NamedArtifactGroup]. Although the set may contain a mixture of Artifacts and
     * ExpandedArtifacts, all its leaf successors ("direct elements") are ExpandedArtifacts.
     */
    init {
        this.completionContext = completionContext
        this.set = set
    }

    val eventId: BuildEventId
        get() = BuildEventIdUtil.fromArtifactGroupName(name)

    val childrenEvents: MutableCollection<BuildEventId>
        get() = com.google.common.collect.ImmutableSet.of<BuildEventId?>()

    public override fun referencedLocalFiles(): MutableCollection<LocalFile?> {
        val artifacts: com.google.common.collect.ImmutableList.Builder<LocalFile?> =
            com.google.common.collect.ImmutableList.builder<LocalFile?>()
        for (elem in set.getLeaves()) {
            when (elem as ExpandedArtifact?) {
                -> {
                    artifacts.add(
                        LocalFile(
                            completionContext.pathResolver().toPath(artifact),
                            LocalFileType.forArtifact(artifact, metadata),
                            metadata
                        )
                    )
                }

                -> {
                    artifacts.add(
                        LocalFile(
                            completionContext.pathResolver().toPath(link.target()),
                            LocalFileType.forArtifact(link.target(), link.metadata()),
                            link.metadata()
                        )
                    )
                }
            }
        }
        return artifacts.build()
    }

    public override fun asStreamProto(converters: BuildEventContext): BuildEventStreamProtos.BuildEvent {
        val pathConverter: PathConverter = converters.pathConverter()
        val namer: ArtifactGroupNamer = converters.artifactGroupNamer()

        val builder: BuildEventStreamProtos.NamedSetOfFiles.Builder =
            BuildEventStreamProtos.NamedSetOfFiles.newBuilder()
        for (elem in set.getLeaves()) {
            val file: BuildEventStreamProtos.File =
                when (elem as ExpandedArtifact?) {
                    -> {
                        val uri: String? = pathConverter.apply(completionContext.pathResolver().toPath(artifact))
                        TargetCompleteEvent.newFile(artifact, metadata, uri)
                    }

                    -> {
                        val uri: String? =
                            pathConverter.apply(completionContext.pathResolver().toPath(link.target()))
                        TargetCompleteEvent.newFile(
                            fileset.getRoot(),
                            fileset.getRootRelativePath().getRelative(link.name()),
                            link.metadata(),
                            uri
                        )
                    }
                }
            // Omit files with unknown contents (e.g. if uploading failed).
            if (file.getFileCase() !== BuildEventStreamProtos.File.FileCase.FILE_NOT_SET) {
                builder.addFiles(file)
            }
        }

        for (succ in set.getNonLeaves()) {
            builder.addFileSets(namer.apply(succ.toNode()))
        }
        return GenericBuildEvent.protoChaining(this).setNamedSetOfFiles(builder.build()).build()
    }

    private interface ExpandedArtifact


    private class NormalExpandedArtifact(artifact: Artifact?, metadata: FileArtifactValue?) : ExpandedArtifact {
        val artifact: Artifact?
        val metadata: FileArtifactValue?

        init {
            this.metadata = metadata
            this.artifact = artifact
            com.google.common.base.Preconditions.checkState(
                !artifact.isDirectory(),
                "artifact must be expanded: %s",
                artifact
            )
        }
    }

    private class FilesetExpandedArtifact(fileset: Artifact?, link: FilesetOutputSymlink?) : ExpandedArtifact {
        val fileset: Artifact?
        val link: FilesetOutputSymlink?

        init {
            this.link = link
            this.fileset = fileset
            checkState(fileset.isFileset(), "artifact must be a fileset: %s", fileset)
        }
    }

    companion object {
        /**
         * Given a set whose leaf successors are [Artifact] and [ExpandedArtifact], returns a
         * new NestedSet whose leaf successors are all ExpandedArtifact. Non-leaf successors are
         * unaltered.
         */
        fun expandSet(ctx: CompletionContext, artifacts: NestedSet<*>): NestedSet<*>? {
            val res: NestedSetBuilder<Any?> = NestedSetBuilder.newBuilder(Order.STABLE_ORDER)
            for (elem in artifacts.getLeaves()) {
                when (elem) {
                    -> {
                        res.add(expandedArtifact)
                    }

                    -> {
                        ctx.visitArtifacts(
                            com.google.common.collect.ImmutableList.of<E?>(artifact),
                            object : ArtifactReceiver() {
                                public override fun accept(artifact: Artifact?, metadata: FileArtifactValue?) {
                                    res.add(NormalExpandedArtifact(artifact, metadata))
                                }

                                public override fun acceptFilesetMapping(
                                    fileset: Artifact?,
                                    link: FilesetOutputSymlink?
                                ) {
                                    res.add(FilesetExpandedArtifact(fileset, link))
                                }
                            })
                    }

                    else -> {
                        throw java.lang.IllegalStateException("Unexpected type in artifact set: %s".formatted(elem))
                    }
                }
            }
            val noDirects: Boolean = res.isEmpty()

            val nonLeaves: com.google.common.collect.ImmutableList<out NestedSet<*>?> = artifacts.getNonLeaves()
            for (succ in nonLeaves) {
                res.addTransitive(succ)
            }

            val result: NestedSet<*> = res.build()

            // If we have executed one call to res.addTransitive(x)
            // and none to res.add, then res.build() simply returns x
            // ("inlining"), which may violate our postcondition on elements.
            // (This can happen if 'artifacts' contains one non-leaf successor
            // and one or more leaf successors for which visitArtifacts is a no-op.)
            //
            // In that case we need to recursively apply the expansion. Ugh.
            if (noDirects && nonLeaves.size() == 1) {
                return expandSet(ctx, result)
            }

            return result
        }
    }
}
