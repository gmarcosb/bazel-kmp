package com.google.devtools.build.lib.bazel.bzlmod.modcommand

import com.google.common.base.Ascii
import com.google.common.collect.ImmutableList
import com.google.devtools.build.lib.bazel.bzlmod.ModuleKey
import com.google.devtools.build.lib.bazel.bzlmod.modcommand.ExtensionArg.CommaSeparatedExtensionArgListConverter
import com.google.devtools.build.lib.bazel.bzlmod.modcommand.ModuleArg.*
import com.google.devtools.common.options.*
import java.util.*
import java.util.function.Function
import java.util.stream.Collectors

/** Options for ModCommand  */
@OptionsClass
abstract class ModOptions : OptionsBase() {
    @get:Option(
        name = "from",
        defaultValue = "<root>",
        converter = CommaSeparatedModuleArgListConverter::class,
        documentationCategory = OptionDocumentationCategory.MOD_COMMAND,
        effectTags = [OptionEffectTag.TERMINAL_OUTPUT],
        help = """
          The module(s) starting from which the dependency graph query will be displayed. Check
          each query’s description for the exact semantics. Defaults to `<root>`.
          
          """.trimIndent()
    )
    abstract var modulesFrom: ImmutableList<ModuleArg?>?

    @kotlin.jvm.JvmField
    @get:Option(
        name = "verbose",
        defaultValue = "false",
        documentationCategory = OptionDocumentationCategory.MOD_COMMAND,
        effectTags = [OptionEffectTag.TERMINAL_OUTPUT],
        help = ("The queries will also display the reason why modules were resolved to their current"
                + " version (if changed). Defaults to true only for the explain query.")
    )
    abstract var verbose: Boolean

    @kotlin.jvm.JvmField
    @get:Option(
        name = "include_unused",
        defaultValue = "false",
        documentationCategory = OptionDocumentationCategory.MOD_COMMAND,
        effectTags = [OptionEffectTag.TERMINAL_OUTPUT],
        help = """
          The queries will also take into account and display the unused modules, which are not
          present in the module resolution graph after selection (due to the
          Minimal-Version Selection or override rules). This can have different effects for
          each of the query types i.e. include new paths in the `all_paths` command, or extra
          dependants in the `explain` command.
          
          """.trimIndent()
    )
    abstract var includeUnused: Boolean

    @get:Option(
        name = "extension_filter",
        defaultValue = "null",
        converter = CommaSeparatedExtensionArgListConverter::class,
        documentationCategory = OptionDocumentationCategory.MOD_COMMAND,
        effectTags = [OptionEffectTag.TERMINAL_OUTPUT],
        help = ("Only display the usages of these module extensions and the repos generated by them if"
                + " their respective flags are set. If set, the result graph will only include paths"
                + " that contain modules using the specified extensions. An empty list disables the"
                + " filter, effectively specifying all possible extensions.")
    )
    abstract var extensionFilter: ImmutableList<ExtensionArg?>?

    @kotlin.jvm.JvmField
    @get:Option(
        name = "extension_info",
        defaultValue = "hidden",
        converter = ExtensionShowConverter::class,
        documentationCategory = OptionDocumentationCategory.MOD_COMMAND,
        effectTags = [OptionEffectTag.TERMINAL_OUTPUT],
        help = """
          Specify how much detail about extension usages to include in the query result.
          - `hidden` will not show any extension information.
          - `usages` will only show the extensions names.
          - `repos` will also include repos imported with `use_repo`.
          - `all` will also show the other repositories generated by extensions.
          
          """.trimIndent()
    )
    abstract var extensionInfo: ExtensionShow?

    @get:Option(
        name = "base_module",
        defaultValue = "<root>",
        converter = ModuleArgConverter::class,
        documentationCategory = OptionDocumentationCategory.MOD_COMMAND,
        effectTags = [OptionEffectTag.TERMINAL_OUTPUT],
        help = "Specify a module relative to which the specified target repos will be interpreted."
    )
    abstract var baseModule: ModuleArg?

    @get:Option(
        name = "extension_usages",
        defaultValue = "",
        converter = CommaSeparatedModuleArgListConverter::class,
        documentationCategory = OptionDocumentationCategory.MOD_COMMAND,
        effectTags = [OptionEffectTag.TERMINAL_OUTPUT],
        help = "Specify modules whose extension usages will be displayed in the show_extension query."
    )
    abstract var extensionUsages: ImmutableList<ModuleArg?>?

    @kotlin.jvm.JvmField
    @get:Option(
        name = "depth",
        defaultValue = "-1",
        documentationCategory = OptionDocumentationCategory.MOD_COMMAND,
        effectTags = [OptionEffectTag.TERMINAL_OUTPUT],
        help = """
          Maximum display depth of the dependency tree. A depth of 1 displays the direct
          dependencies, for example. For `tree`, `path` and `all_paths` it defaults to
          `Integer.MAX_VALUE`, while for `deps` and `explain` it defaults to 1 (only displays
          direct deps of the root besides the target leaves and their parents).
          
          """.trimIndent()
    )
    abstract var depth: Int

    @kotlin.jvm.JvmField
    @get:Option(
        name = "cycles",
        defaultValue = "true",
        documentationCategory = OptionDocumentationCategory.MOD_COMMAND,
        effectTags = [OptionEffectTag.TERMINAL_OUTPUT],
        help = "Points out dependency cycles inside the displayed tree."
    )
    abstract var cycles: Boolean

    @get:Option(
        name = "include_builtin",
        defaultValue = "false",
        documentationCategory = OptionDocumentationCategory.MOD_COMMAND,
        effectTags = [OptionEffectTag.TERMINAL_OUTPUT],
        help = ("Include built-in modules in the dependency graph. Disabled by default because it is"
                + " quite noisy.")
    )
    abstract var includeBuiltin: Boolean

    @get:Option(
        name = "charset",
        defaultValue = "utf8",
        converter = CharsetConverter::class,
        documentationCategory = OptionDocumentationCategory.MOD_COMMAND,
        effectTags = [OptionEffectTag.TERMINAL_OUTPUT],
        help = """
          Chooses the character set to use for the tree. Only affects text output. Valid values
          are `utf8` or `ascii`. Default is `utf8`
          
          """.trimIndent()
    )
    abstract var charset: Charset?

    @kotlin.jvm.JvmField
    @get:Option(
        name = "output",
        defaultValue = "text",
        converter = OutputFormatConverter::class,
        documentationCategory = OptionDocumentationCategory.MOD_COMMAND,
        effectTags = [OptionEffectTag.TERMINAL_OUTPUT],
        help = """
          The format in which the query results should be printed. Allowed values for query are:
          `text`, `json`, `graph`.
          
          """.trimIndent()
    )
    abstract var outputFormat: OutputFormat?

    @get:Option(
        name = "all_repos",
        defaultValue = "false",
        documentationCategory = OptionDocumentationCategory.MOD_COMMAND,
        effectTags = [OptionEffectTag.TERMINAL_OUTPUT],
        help = """
          For `mod show_repo`: display all repos in the entire workspace.
          
          """.trimIndent()
    )
    abstract var allRepos: Boolean

    @get:Option(
        name = "all_visible_repos",
        defaultValue = "false",
        documentationCategory = OptionDocumentationCategory.MOD_COMMAND,
        effectTags = [OptionEffectTag.TERMINAL_OUTPUT],
        help = """
          For `mod show_repo`: display all repos visible to the chosen base module, under their apparent names.
          
          """.trimIndent()
    )
    abstract var allVisibleRepos: Boolean

    /** Possible subcommands that can be specified for the `mod` command.  */
    enum class ModSubcommand(
        /** Whether this subcommand produces a graph output.  */
        val isGraph: Boolean
    ) {
        DEPS(true),
        GRAPH(true),
        ALL_PATHS(true),
        PATH(true),
        EXPLAIN(true),
        SHOW_REPO(false),
        SHOW_EXTENSION(false),
        DUMP_REPO_MAPPING(false),
        TIDY(false);

        override fun toString(): String {
            return Ascii.toLowerCase(this.name())
        }

        companion object {
            fun printValues(): String {
                return "(" + Arrays.stream<ModSubcommand?>(ModSubcommand.entries.toTypedArray())
                    .map<String?>(Function { obj: ModSubcommand? -> obj.toString() })
                    .collect(Collectors.joining(", ")) + ")"
            }
        }
    }

    /** Converts a subcommand string to a properly typed [ModSubcommand]  */
    class ModSubcommandConverter : EnumConverter<ModSubcommand?>(ModSubcommand::class.java, "mod subcommand")

    internal enum class ExtensionShow {
        HIDDEN,
        USAGES,
        REPOS,
        ALL
    }

    /** Converts an option string to a properly typed [ExtensionShow]  */
    class ExtensionShowConverter : EnumConverter<ExtensionShow?>(ExtensionShow::class.java, "extension show")

    /** Charset to be used in outputting the `mod` command result.  */
    enum class Charset {
        UTF8,
        ASCII
    }

    /** Converts a charset option string to a properly typed [Charset]  */
    class CharsetConverter : EnumConverter<Charset?>(Charset::class.java, "output charset")

    /** Possible formats of the `mod` command result.  */
    enum class OutputFormat {
        // Default
        TEXT,

        // For graph commands:
        JSON,
        GRAPH,

        // For show_repo:
        STREAMED_PROTO,
        STREAMED_JSONPROTO;

        override fun toString(): String {
            return Ascii.toLowerCase(this.name())
        }
    }

    /** Converts an output format option string to a properly typed [OutputFormat]  */
    class OutputFormatConverter : EnumConverter<OutputFormat?>(OutputFormat::class.java, "output format")

    companion object {
        @kotlin.jvm.JvmStatic
        val defaultOptions: ModOptions
            /** Returns a [ModOptions] filled with default values for testing.  */
            get() {
                val options =
                    Options.getDefaults<ModOptions>(ModOptions::class.java)
                options.depth = Integer.MAX_VALUE
                options.cycles = false
                options.includeUnused = false
                options.verbose = false
                options.modulesFrom = ImmutableList.of<ModuleArg?>(
                    SpecificVersionOfModule.Companion.create(ModuleKey.Companion.ROOT)
                )
                options.charset = Charset.UTF8
                options.outputFormat =
                    OutputFormat.TEXT
                options.extensionFilter = null
                options.extensionInfo = ExtensionShow.HIDDEN
                return options
            }
    }
}
