package com.google.devtools.build.lib.query2.query.output

import com.google.common.base.Ascii
import com.google.common.base.Preconditions
import com.google.common.collect.Iterables
import com.google.devtools.build.lib.cmdline.Label
import com.google.devtools.build.lib.collect.compacthashset.CompactHashSet
import net.starlark.java.eval.Printer
import net.starlark.java.eval.Starlark
import net.starlark.java.eval.StarlarkSemantics
import net.starlark.java.eval.StarlarkThread
import java.io.OutputStream
import java.io.Writer
import java.lang.String
import java.util.function.BiPredicate
import kotlin.Any
import kotlin.Boolean
import kotlin.collections.ArrayList
import kotlin.collections.Iterable
import kotlin.collections.MutableList
import kotlin.collections.MutableSet
import kotlin.toString

/**
 * An output formatter that prints the generating rules using the syntax of the BUILD files. If
 * multiple targets are generated by the same rule, it is printed only once.
 */
class BuildOutputFormatter : AbstractUnorderedFormatter() {
    /**
     * Generic interface for determining the possible values for a given attribute on a given rule, as
     * precisely as the implementation knows. For example, cquery knows which branch a `select
    ` *  takes, while query doesn't.
     */
    interface AttributeReader {
        fun getPossibleValues(rule: Rule?, attr: Attribute?): Iterable<Any?>
    }

    /**
     * Generic logic for formatting a target BUILD-style.
     * 
     * 
     * This logic is implementation-agnostic. So it can be shared across query, cquery, and other
     * implementations.
     */
    class TargetOutputter(
        private val writer: Writer,
        preserveSelect: BiPredicate<Rule?, Attribute?>,
        lineTerm: String?,
        labelPrinter: LabelPrinter
    ) {
        private val preserveSelect: BiPredicate<Rule?, Attribute?>
        private val lineTerm: String?
        private val labelPrinter: LabelPrinter
        private val printed: MutableSet<Label?> = CompactHashSet.create<Label?>()

        /**
         * @param writer where to write output
         * @param preserveSelect a predicate that determines if the given attribute on the given rule is
         * a `select` that should be output as-is (without figuring out which branch it
         * takes). This is useful for implementations that can't evaluate `select`.
         * @param lineTerm character to add to the end of each line
         */
        init {
            this.preserveSelect = preserveSelect
            this.lineTerm = lineTerm
            this.labelPrinter = labelPrinter
        }

        /** Outputs a given target in BUILD-style syntax.  */
        @Throws(IOException::class)
        fun output(target: Target, attrReader: AttributeReader) {
            val rule: Rule? = target.getAssociatedRule()
            if (rule == null || printed.contains(rule.getLabel())) {
                return
            }
            outputRule(rule, attrReader, writer)
            printed.add(rule.getLabel())
        }

        /** Outputs a given rule in BUILD-style syntax.  */
        @Throws(IOException::class)
        private fun outputRule(rule: Rule, attrReader: AttributeReader, writer: Writer) {
            // TODO(b/151151653): display the filenames in root-relative form.
            // This is an incompatible change, but Blaze users (and their editors)
            // must already be equipped to handle relative paths as all compiler
            // error messages are execroot-relative.

            writer.append("# ").append(rule.getLocation().toString()).append(lineTerm)
            writer.append(rule.getRuleClass()).append("(").append(lineTerm)
            writer.append("  name = \"").append(rule.getName()).append("\",").append(lineTerm)

            for (attr in rule.getAttributes()) {
                // Ignore the "name" attribute here, as we already print it above.
                // This is not strictly necessary, but convention has it that the
                // name attribute is printed first.
                if ("name" == attr.name) {
                    continue
                }
                if (preserveSelect.test(rule, attr)) {
                    writer
                        .append("  ")
                        .append(attr.getPublicName())
                        .append(" = ")
                        .append(reconstructSelect(rule, attr))
                        .append(",")
                        .append(lineTerm)
                    continue
                }
                if (!rule.isAttributeValueExplicitlySpecified(attr)) {
                    continue  // Don't print default values.
                }

                val values = attrReader.getPossibleValues(rule, attr)
                if (Iterables.size(values) != 1) {
                    // Computed defaults that depend on configurable attributes can have multiple values.
                    continue
                }
                writer
                    .append("  ")
                    .append(attr.getPublicName())
                    .append(" = ")
                    .append(outputRawAttrValue(Iterables.getOnlyElement<Any?>(values)!!))
                    .append(",")
                    .append(lineTerm)
            }
            writer.append(")").append(lineTerm)

            // Display the instantiation stack, if any.
            appendStack(
                String.format("# Rule %s instantiated at (most recent call last):", rule.getName()),
                rule.reconstructCallStack()
            )

            // Display the stack of the rule class definition, if any.
            appendStack(
                String.format("# Rule %s defined at (most recent call last):", rule.getRuleClass()),
                rule.getRuleClassObject().getCallStack()
            )

            // TODO(adonovan): also list inputs and outputs of the rule.
            writer.append(lineTerm)
        }

        @Throws(IOException::class)
        private fun appendStack(title: kotlin.String?, stack: MutableList<StarlarkThread.CallStackEntry>) {
            // For readability, ensure columns line up.
            var maxLocLen = 0
            for (fr in stack) {
                maxLocLen = max(maxLocLen, fr.location.toString().length)
            }
            if (maxLocLen > 0) {
                writer.append(title).append(lineTerm)
                for (fr in stack) {
                    val loc = fr.location.toString() // TODO(b/151151653): display root-relative
                    // Java's String.format doesn't support
                    // right-padding with %*s, so we must loop.
                    writer.append("#   ").append(loc)
                    for (i in loc.length..<maxLocLen) {
                        writer.append(' ')
                    }
                    writer.append(" in ").append(fr.name).append(lineTerm)
                }
            }
        }

        /** Outputs the given attribute value BUILD-style. Does not support selects.  */
        private fun outputRawAttrValue(value: Any): kotlin.String {
            var value = value
            if (value is License) {
                val licenseTypes: MutableList<kotlin.String?> = ArrayList<kotlin.String?>()
                for (licenseType in (value as License).getLicenseTypes()) {
                    licenseTypes.add(Ascii.toLowerCase(licenseType.toString()))
                }
                value = licenseTypes
            } else if (value is TriState) {
                value = value.toInt()
            }

            return object : Printer() {
                // Print labels in their canonical form.
                override fun repr(o: Any?, semantics: StarlarkSemantics?): Printer? {
                    return when (o) {
                        -> appendPrettyQuoted(str)
                        -> super.repr(labelPrinter.toString(label), semantics)
                        null -> super.repr(Starlark.NONE, semantics)
                        else -> super.repr(o, semantics)
                    }
                }
            }.repr(value, StarlarkSemantics.DEFAULT).toString()
        }

        /**
         * Outputs a `select` BUILD-style without trying to resolve which branch it takes.
         */
        private fun reconstructSelect(rule: Rule?, attr: Attribute?): kotlin.String {
            val selectors: MutableList<kotlin.String?> = ArrayList<kotlin.String?>()
            val attributeMap: RawAttributeMapper = RawAttributeMapper.of(rule)
            for (selector in (attributeMap.getRawAttributeValue(rule, attr) as BuildType.SelectorList<*>).selectors) {
                if (selector.isUnconditional()) {
                    selectors.add(outputRawAttrValue(Preconditions.checkNotNull<T?>(selector.getDefault())))
                } else {
                    selectors.add(kotlin.String.format("select(%s)", outputRawAttrValue(selector.mapCopy())))
                }
            }
            return String.join(" + ", selectors)
        }
    }

    /** Query's implementation.  */
    override fun createPostFactoStreamCallback(
        out: OutputStream?, options: QueryOptions, labelPrinter: LabelPrinter
    ): OutputFormatterCallback<Target?> {
        return BuildOutputFormatterCallback(
            out,
            options.getLineTerminator(),
            labelPrinter,
            options.getIncompatiblePackageGroupBuildOutput(),
            options.getIncompatiblePackageGroupIncludesDoubleSlash()
        )
    }

    override fun createStreamCallback(
        out: OutputStream?, options: QueryOptions, env: QueryEnvironment<*>
    ): ThreadSafeOutputFormatterCallback<Target?> {
        return SynchronizedDelegatingOutputFormatterCallback<Target?>(
            createPostFactoStreamCallback(out, options, env.getLabelPrinter())
        )
    }

    /** BuildOutputFormatter callback for Query. Made visible for ModQuery.  */
    class BuildOutputFormatterCallback internal constructor(
        out: OutputStream?,
        private val lineTerm: kotlin.String?,
        labelPrinter: LabelPrinter,
        includePackageGroup: Boolean,
        packageGroupIncludesDoubleSlash: Boolean
    ) : TextOutputFormatterCallback<Target?>(out) {
        private val targetOutputter: TargetOutputter
        private val includePackageGroup: Boolean
        private val packageGroupIncludesDoubleSlash: Boolean
        private val labelPrinter: LabelPrinter

        init {
            this.labelPrinter = labelPrinter
            this.includePackageGroup = includePackageGroup
            this.packageGroupIncludesDoubleSlash = packageGroupIncludesDoubleSlash
            this.targetOutputter =
                TargetOutputter(
                    writer,
                    BiPredicate { rule: Rule?, attr: Attribute? ->
                        AbstractAttributeMapper.isConfigurable(
                            rule, attr.name,  /* includeComputedDefaults= */false
                        )
                    },
                    lineTerm,
                    labelPrinter
                )
        }

        @Throws(IOException::class)
        override fun processOutput(partialResult: Iterable<Target>) {
            for (target in partialResult) {
                if (target is PackageGroup && includePackageGroup) {
                    outputPackageGroup(target)
                } else {
                    targetOutputter.output(
                        target,  // Multiple possible values are ignored by the outputter.
                        BuildOutputFormatter.AttributeReader { rule: Rule?, attr: Attribute? ->
                            PossibleAttributeValues.forRuleAndAttribute(
                                rule, attr,  /* mayTreatMultipleAsNone= */true
                            )
                        })
                }
            }
        }

        @Throws(IOException::class)
        private fun outputPackageGroup(packageGroup: PackageGroup) {
            writer.append("# ").append(packageGroup.getLocation().toString()).append(lineTerm)
            writer.append("package_group(").append(lineTerm)
            writer.append("  name = \"").append(packageGroup.getName()).append("\",").append(lineTerm)

            val packages: MutableList<kotlin.String?> =
                packageGroup.getContainedPackages(packageGroupIncludesDoubleSlash)
            if (!packages.isEmpty()) {
                writer.append("  packages = [").append(lineTerm)
                for (pkg in packages) {
                    writer.append("    \"").append(pkg).append("\",").append(lineTerm)
                }
                writer.append("  ],").append(lineTerm)
            }

            val includes: MutableList<Label?> = packageGroup.getIncludes()
            if (!includes.isEmpty()) {
                writer.append("  includes = [").append(lineTerm)
                for (include in includes) {
                    writer
                        .append("    \"")
                        .append(labelPrinter.toString(include))
                        .append("\",")
                        .append(lineTerm)
                }
                writer.append("  ],").append(lineTerm)
            }

            writer.append(")").append(lineTerm).append(lineTerm)
        }
    }

    override fun getName(): kotlin.String {
        return "build"
    }
}
