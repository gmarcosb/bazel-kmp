package com.google.devtools.build.lib.bazel.bzlmod

import com.google.auto.value.AutoValue
import com.google.devtools.build.lib.bazel.bzlmod.Facts
import com.google.devtools.build.lib.cmdline.RepositoryName
import java.util.LinkedHashSet

/** The Starlark object optionally returned by a module extension's implementation function.  */
@net.starlark.java.annot.StarlarkBuiltin(
    name = "extension_metadata",
    category = com.google.devtools.build.docgen.annot.DocCategory.BUILTIN,
    doc = ("Return values of this type from a module extension's implementation function to "
            + "provide metadata about the repositories generated by the extension to Bazel.")
)
@AutoValue
abstract class ModuleExtensionMetadata : net.starlark.java.eval.StarlarkValue {
    abstract val explicitRootModuleDirectDeps: com.google.common.collect.ImmutableSet<String?>?

    abstract val explicitRootModuleDirectDevDeps: com.google.common.collect.ImmutableSet<String?>?

    abstract val useAllRepos: UseAllRepos?

    abstract val reproducible: Boolean

    abstract val facts: Facts?

    internal enum class UseAllRepos {
        NO,
        REGULAR,
        DEV,
    }

    companion object {
        val DEFAULT: ModuleExtensionMetadata = create( /* explicitRootModuleDirectDeps= */
            null,  /* explicitRootModuleDirectDevDeps= */
            null,
            UseAllRepos.NO,  /* reproducible= */
            false,  /* facts= */
            Facts.Companion.EMPTY
        )

        val REPRODUCIBLE: ModuleExtensionMetadata = create( /* explicitRootModuleDirectDeps= */
            null,  /* explicitRootModuleDirectDevDeps= */
            null,
            UseAllRepos.NO,  /* reproducible= */
            true,  /* facts= */
            Facts.Companion.EMPTY
        )

        private fun create(
            explicitRootModuleDirectDeps: MutableSet<String?>?,
            explicitRootModuleDirectDevDeps: MutableSet<String?>?,
            useAllRepos: UseAllRepos?,
            reproducible: Boolean,
            facts: Facts?
        ): ModuleExtensionMetadata {
            return AutoValue_ModuleExtensionMetadata(
                if (explicitRootModuleDirectDeps != null)
                    com.google.common.collect.ImmutableSet.< E > copyOf < E ? > (explicitRootModuleDirectDeps)
                else
                    null,
                if (explicitRootModuleDirectDevDeps != null)
                    com.google.common.collect.ImmutableSet.< E > copyOf < E ? > (explicitRootModuleDirectDevDeps)
                else
                    null,
                useAllRepos,
                reproducible,
                facts
            )
        }

        @Throws(net.starlark.java.eval.EvalException::class)
        fun create(
            rootModuleDirectDepsUnchecked: Any,
            rootModuleDirectDevDepsUnchecked: Any,
            reproducible: Boolean,
            factsObj: net.starlark.java.eval.Dict<String?, Any?>?
        ): ModuleExtensionMetadata {
            val facts: Facts = Facts.Companion.validateAndCreate(factsObj)

            if (rootModuleDirectDepsUnchecked === net.starlark.java.eval.Starlark.NONE
                && rootModuleDirectDevDepsUnchecked === net.starlark.java.eval.Starlark.NONE
            ) {
                return create(null, null, UseAllRepos.NO, reproducible, facts)
            }

            // When root_module_direct_deps = "all", accept both root_module_direct_dev_deps = None and
            // root_module_direct_dev_deps = [], but not root_module_direct_dev_deps = ["some_repo"].
            if (rootModuleDirectDepsUnchecked == "all"
                && rootModuleDirectDevDepsUnchecked == net.starlark.java.eval.StarlarkList.immutableOf<Any?>()
            ) {
                return create(null, null, UseAllRepos.REGULAR, reproducible, facts)
            }

            if (rootModuleDirectDevDepsUnchecked == "all"
                && rootModuleDirectDepsUnchecked == net.starlark.java.eval.StarlarkList.immutableOf<Any?>()
            ) {
                return create(null, null, UseAllRepos.DEV, reproducible, facts)
            }

            if (rootModuleDirectDepsUnchecked == "all"
                || rootModuleDirectDevDepsUnchecked == "all"
            ) {
                throw net.starlark.java.eval.Starlark.errorf(
                    "if one of root_module_direct_deps and root_module_direct_dev_deps is "
                            + "\"all\", the other must be an empty list"
                )
            }

            if (rootModuleDirectDepsUnchecked is String
                || rootModuleDirectDevDepsUnchecked is String
            ) {
                throw net.starlark.java.eval.Starlark.errorf(
                    "root_module_direct_deps and root_module_direct_dev_deps must be "
                            + "None, \"all\", or a list of strings"
                )
            }
            if ((rootModuleDirectDepsUnchecked === net.starlark.java.eval.Starlark.NONE)
                != (rootModuleDirectDevDepsUnchecked === net.starlark.java.eval.Starlark.NONE)
            ) {
                throw net.starlark.java.eval.Starlark.errorf(
                    "root_module_direct_deps and root_module_direct_dev_deps must both be "
                            + "specified or both be unspecified"
                )
            }

            val rootModuleDirectDeps: net.starlark.java.eval.Sequence<String?> =
                net.starlark.java.eval.Sequence.cast<String?>(
                    rootModuleDirectDepsUnchecked,
                    String::class.java,
                    "root_module_direct_deps"
                )
            val rootModuleDirectDevDeps: net.starlark.java.eval.Sequence<String?> =
                net.starlark.java.eval.Sequence.cast<String?>(
                    rootModuleDirectDevDepsUnchecked, String::class.java, "root_module_direct_dev_deps"
                )

            val explicitRootModuleDirectDeps: MutableSet<String?> = LinkedHashSet<String?>()
            for (dep in rootModuleDirectDeps) {
                try {
                    RepositoryName.validateUserProvidedRepoName(dep)
                } catch (e: net.starlark.java.eval.EvalException) {
                    throw net.starlark.java.eval.Starlark.errorf("in root_module_direct_deps: %s", e.getMessage())
                }
                if (!explicitRootModuleDirectDeps.add(dep)) {
                    throw net.starlark.java.eval.Starlark.errorf(
                        "in root_module_direct_deps: duplicate entry '%s'",
                        dep
                    )
                }
            }

            val explicitRootModuleDirectDevDeps: MutableSet<String?> = LinkedHashSet<String?>()
            for (dep in rootModuleDirectDevDeps) {
                try {
                    RepositoryName.validateUserProvidedRepoName(dep)
                } catch (e: net.starlark.java.eval.EvalException) {
                    throw net.starlark.java.eval.Starlark.errorf("in root_module_direct_dev_deps: %s", e.getMessage())
                }
                if (explicitRootModuleDirectDeps.contains(dep)) {
                    throw net.starlark.java.eval.Starlark.errorf(
                        "in root_module_direct_dev_deps: entry '%s' is also in " + "root_module_direct_deps",
                        dep
                    )
                }
                if (!explicitRootModuleDirectDevDeps.add(dep)) {
                    throw net.starlark.java.eval.Starlark.errorf(
                        "in root_module_direct_dev_deps: duplicate entry '%s'",
                        dep
                    )
                }
            }

            return create(
                explicitRootModuleDirectDeps,
                explicitRootModuleDirectDevDeps,
                UseAllRepos.NO,
                reproducible,
                facts
            )
        }
    }
}
