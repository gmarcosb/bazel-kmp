package com.google.devtools.build.lib.packages

import com.google.devtools.build.lib.cmdline.Label

/**
 * A file that is an input to the build system.
 * 
 * 
 * In the build system, a file is considered an *input* file iff it is not generated by the
 * build system (e.g. it's maintained under version control, or created by the test harness). It has
 * nothing to do with the type of the file; a generated file containing `Java` source
 * code is an OutputFile, not an InputFile.
 * 
 * 
 * [InputFile] assumes the input file follows package-default visibility and no license.
 * Use [PrivateVisibilityInputFile] if returned visibility is constantly `RuleVisibility.PRIVATE`. Use [VisibilityLicenseSpecifiedInputFile] if either visibility or
 * license needs to be specified.
 */
@Immutable
@ThreadSafe
open class InputFile internal constructor(pkg: Packageoid, label: Label, location: net.starlark.java.syntax.Location?) :
    FileTarget(pkg, label) {
    private val pkg: Packageoid
    private val location: net.starlark.java.syntax.Location

    /**
     * Constructs an input file with the given label, which must be a label for the given package, and
     * package-default visibility.
     */
    init {
        this.pkg = pkg
        this.location = com.google.common.base.Preconditions.checkNotNull<net.starlark.java.syntax.Location>(location)
    }

    override fun getPackageoid(): Packageoid {
        return pkg
    }

    override fun getPackageMetadata(): com.google.devtools.build.lib.packages.Package.Metadata? {
        return pkg.getMetadata()
    }

    override fun getPackageDeclarations(): Declarations? {
        return pkg.getDeclarations()
    }

    open fun isVisibilitySpecified(): Boolean {
        return false
    }

    override fun getRawVisibility(): RuleVisibility? {
        return null
    }

    override fun isConfigurable(): Boolean {
        return false
    }

    open fun isLicenseSpecified(): Boolean {
        return false
    }

    override fun getLicense(): License? {
        return License.Companion.NO_LICENSE
    }

    /**
     * Returns the path to the location of the input file (which is necessarily
     * within the source tree, not beneath `bin` or
     * `genfiles`.
     * 
     * 
     * Prefer [.getExecPath] if possible.
     */
    fun getPath(): com.google.devtools.build.lib.vfs.Path? {
        return pkg.getMetadata().getPackageDirectory().getRelative(label.name)
    }

    /**
     * Returns the exec path of the file, i.e. the path relative to the execution root working
     * directory.
     */
    fun getExecPath(siblingRepositoryLayout: Boolean): PathFragment {
        return label
            .getRepository()
            .getExecPath(siblingRepositoryLayout)
            .getRelative(label.getPackageName())
            .getRelative(label.name)
    }

    override fun getTargetKind(): String {
        return targetKind()
    }

    override fun getAssociatedRule(): com.google.devtools.build.lib.packages.Rule? {
        return null
    }

    override fun getLocation(): net.starlark.java.syntax.Location {
        return location
    }

    override fun isInputFile(): Boolean {
        return true
    }

    override fun getInputPath(): com.google.devtools.build.lib.vfs.Path? {
        return getPath()
    }

    override fun reduceForSerialization(): TargetData {
        return AutoValue_InputFile_InputFileData(getLocation(), getLabel(), getInputPath())
    }

    @AutoValue
    internal abstract class InputFileData : TargetData {
        override fun getTargetKind(): String {
            return targetKind()
        }

        override fun isFile(): Boolean {
            return true
        }

        override fun isInputFile(): Boolean {
            return true
        }

        abstract override fun getInputPath(): com.google.devtools.build.lib.vfs.Path?
    }

    companion object {
        /** Returns the target kind for all input files.  */
        fun targetKind(): String {
            return "source file"
        }
    }
}
