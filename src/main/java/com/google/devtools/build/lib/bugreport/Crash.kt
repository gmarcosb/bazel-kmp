package com.google.devtools.build.lib.bugreport

import com.google.common.base.MoreObjects
import com.google.common.base.Preconditions
import com.google.devtools.build.lib.util.CrashFailureDetails
import com.google.devtools.build.lib.util.DetailedExitCode

/** Encapsulates the [Throwable] and [DetailedExitCode] for a crash.  */
class Crash private constructor(throwable: Throwable?, detailedExitCode: DetailedExitCode?) {
    @kotlin.jvm.JvmField
    val throwable: Throwable
    @kotlin.jvm.JvmField
    val detailedExitCode: DetailedExitCode

    init {
        this.throwable = Preconditions.checkNotNull<Throwable>(throwable)
        this.detailedExitCode = Preconditions.checkNotNull<DetailedExitCode>(detailedExitCode)
    }

    override fun toString(): String {
        return MoreObjects.toStringHelper(this)
            .add("throwable", throwable)
            .add("detailedExitCode", detailedExitCode)
            .toString()
    }

    companion object {
        /**
         * Creates a crash caused by the given [Throwable].
         * 
         * 
         * The exit code is generated by [CrashFailureDetails.detailedExitCodeForThrowable].
         * Notably, this results in a failure detail with either [ ][com.google.devtools.build.lib.server.FailureDetails.Crash.Code.CRASH_OOM] or [ ][com.google.devtools.build.lib.server.FailureDetails.Crash.Code.CRASH_UNKNOWN]. Crashes that
         * deserve special handling should use [.from] so that they can
         * specify a custom [DetailedExitCode].
         */
        @kotlin.jvm.JvmStatic
        fun from(throwable: Throwable?): Crash {
            return Crash(throwable, CrashFailureDetails.detailedExitCodeForThrowable(throwable))
        }

        /**
         * Creates a crash caused by the given [Throwable] with a specified [ ].
         */
        @kotlin.jvm.JvmStatic
        fun from(throwable: Throwable?, detailedExitCode: DetailedExitCode?): Crash {
            return Crash(throwable, detailedExitCode)
        }
    }
}
