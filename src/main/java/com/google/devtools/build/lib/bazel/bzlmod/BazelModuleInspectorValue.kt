/**
 * The result of running Bazel module inspection pre-processing, containing the un-pruned and
 * augmented wrappers of the Bazel module dependency graph (post-version-resolution).
 * 
 * @param depGraph The (bidirectional) inspection dep graph, containing wrappers of the [     ], augmented with references to dependants. The order is non-deterministic, inherited
 * from the `completeDepGraph` of [BazelModuleResolutionValue]. For any KEY in the
 * returned map, it's guaranteed that `depGraph[KEY].getKey() == KEY`.
 * @param modulesIndex Index of all module keys mentioned in the un-pruned dep graph (loaded or not)
 * for easy lookup. It is a map from * module name * to the set of [ModuleKey]s that
 * point to a version of that module.
 * @param extensionToRepoInternalNames A mapping from a module extension ID, to the list of
 * "internal" names of the repos generated by that extension. The "internal" name is the name
 * directly used by the extension when instantiating a repo rule.
 * @param moduleKeyToCanonicalNames A mapping from a module key to the canonical repository name of
 * the module repository.
 */
class BazelModuleInspectorValue(
    depGraph: com.google.common.collect.ImmutableMap<ModuleKey?, AugmentedModule?>?,
    modulesIndex: com.google.common.collect.ImmutableMap<String?, com.google.common.collect.ImmutableSet<ModuleKey?>?>?,
    extensionToRepoInternalNames: com.google.common.collect.ImmutableSetMultimap<ModuleExtensionId?, String?>?,
    moduleKeyToCanonicalNames: com.google.common.collect.ImmutableMap<ModuleKey?, RepositoryName?>?,
    errors: com.google.common.collect.ImmutableList<ExternalDepsException?>?
) : SkyValue {
    /**
     * A wrapper for [Module], augmented with references to dependants (and also those who are
     * not used in the final dep graph).
     * 
     * @param name Name of the module. Same as in [Module].
     * @param version Version of the module. Same as in [Module].
     * @param key [ModuleKey] of this module. Same as in [Module]
     * @param repoName The apparent name used by the module to refer to its own repository.
     * @param dependants The set of modules in the resolved dep graph that depend on this module
     * ** after ** the module resolution.
     * @param originalDependants The set of modules in the complete dep graph that originally depended
     * on this module *before* the module resolution (can contain unused nodes).
     * @param deps A bi-map from the repo names of the resolved dependencies of this module to their
     * actual module keys. The inverse lookup is used to check how and why the dependency changed
     * using the other maps.
     * @param unusedDeps A bi-map from the repo names of the unused dependencies of this module to
     * their actual module keys. The inverse lookup is used to check how and why the dependency
     * changed using the other maps.
     * @param depReasons A map from the repo name of the dependencies of this module to the rules that
     * were used for their resolution (can be either the original dependency, changed by the
     * Minimal-Version Selection algorithm or by an override rule.
     * @param loaded Flag that tell whether the module was loaded and added to the dependency graph.
     * Modules overridden by `single_version_override` and [NonRegistryOverride] are
     * not loaded so their `originalDeps` are (yet) unknown.
     */
    class AugmentedModule(
        name: String?,
        version: com.google.devtools.build.lib.bazel.bzlmod.Version?,
        key: ModuleKey?,
        repoName: String?,
        dependants: com.google.common.collect.ImmutableSet<ModuleKey?>?,
        originalDependants: com.google.common.collect.ImmutableSet<ModuleKey?>?,
        deps: com.google.common.collect.ImmutableBiMap<String?, ModuleKey?>?,
        unusedDeps: com.google.common.collect.ImmutableBiMap<String?, ModuleKey?>?,
        depReasons: com.google.common.collect.ImmutableMap<String?, ResolutionReason?>?,
        val loaded: Boolean
    ) {
        /**
         * Shortcut for retrieving the sorted union of both used and unused deps based on the unused
         * flag.
         */
        fun getAllDeps(unused: Boolean): com.google.common.collect.ImmutableSortedMap<ModuleKey?, String?> {
            if (!unused) {
                return com.google.common.collect.ImmutableSortedMap.copyOf<ModuleKey?, String?>(
                    this.deps.inverse(),
                    ModuleKey.Companion.LEXICOGRAPHIC_COMPARATOR
                )
            } else {
                val map: MutableMap<ModuleKey?, String?> = HashMap<ModuleKey?, String?>()
                map.putAll(this.deps.inverse())
                map.putAll(this.unusedDeps.inverse())
                return com.google.common.collect.ImmutableSortedMap.copyOf<ModuleKey?, String?>(
                    map,
                    ModuleKey.Companion.LEXICOGRAPHIC_COMPARATOR
                )
            }
        }

        val isUsed: Boolean
            /** Flag for checking whether the module is present in the resolved dep graph.  */
            get() = this.key == ModuleKey.Companion.ROOT || !this.dependants.isEmpty()

        /** Builder type for [AugmentedModule].  */
        @AutoBuilder
        abstract class Builder {
            abstract fun setName(value: String?): Builder?

            abstract fun setVersion(value: com.google.devtools.build.lib.bazel.bzlmod.Version?): Builder?

            abstract fun setKey(value: ModuleKey?): Builder?

            abstract fun setRepoName(value: String?): Builder?

            abstract fun setLoaded(value: Boolean): Builder?

            abstract fun originalDependantsBuilder(): com.google.common.collect.ImmutableSet.Builder<ModuleKey?>?

            @com.google.errorprone.annotations.CanIgnoreReturnValue
            fun addOriginalDependant(depKey: ModuleKey?): Builder {
                originalDependantsBuilder().add(depKey)
                return this
            }

            abstract fun dependantsBuilder(): com.google.common.collect.ImmutableSet.Builder<ModuleKey?>?

            @com.google.errorprone.annotations.CanIgnoreReturnValue
            fun addDependant(depKey: ModuleKey?): Builder {
                dependantsBuilder().add(depKey)
                return this
            }

            abstract fun depsBuilder(): com.google.common.collect.ImmutableBiMap.Builder<String?, ModuleKey?>?

            @com.google.errorprone.annotations.CanIgnoreReturnValue
            fun addDep(repoName: String, key: ModuleKey): Builder {
                depsBuilder().put(repoName, key)
                return this
            }

            abstract fun unusedDepsBuilder(): com.google.common.collect.ImmutableBiMap.Builder<String?, ModuleKey?>?

            @com.google.errorprone.annotations.CanIgnoreReturnValue
            fun addUnusedDep(repoName: String, key: ModuleKey): Builder {
                unusedDepsBuilder().put(repoName, key)
                return this
            }

            abstract fun depReasonsBuilder(): com.google.common.collect.ImmutableMap.Builder<String?, ResolutionReason?>?

            @com.google.errorprone.annotations.CanIgnoreReturnValue
            fun addDepReason(repoName: String?, reason: ResolutionReason?): Builder {
                depReasonsBuilder().put(repoName, reason)
                return this
            }

            abstract fun build(): AugmentedModule?
        }

        /** The reason why a final dependency of a module was resolved the way it was.  */
        enum class ResolutionReason(label: String) {
            /** The dependency is the original dependency defined in the MODULE.bazel file.  */
            ORIGINAL(""),

            /** The dependency was replaced by the Minimal-Version Selection algorithm.  */
            MINIMAL_VERSION_SELECTION("MVS"),

            /** The dependency was replaced by a `single_version_override` rule.  */
            SINGLE_VERSION_OVERRIDE("SVO"),

            /** The dependency was replaced by a `multiple_version_override` rule.  */
            MULTIPLE_VERSION_OVERRIDE("MVO"),

            /** The dependency was replaced by one of the [NonRegistryOverride] rules.  */
            NON_REGISTRY_OVERRIDE("NRO");

            val label: String?

            init {
                this.label = label
            }
        }

        val name: String?
        val version: com.google.devtools.build.lib.bazel.bzlmod.Version?
        val key: ModuleKey?
        val repoName: String?
        val dependants: com.google.common.collect.ImmutableSet<ModuleKey?>?
        val originalDependants: com.google.common.collect.ImmutableSet<ModuleKey?>?
        val deps: com.google.common.collect.ImmutableBiMap<String?, ModuleKey?>?
        val unusedDeps: com.google.common.collect.ImmutableBiMap<String?, ModuleKey?>?
        val depReasons: com.google.common.collect.ImmutableMap<String?, ResolutionReason?>?

        init {
            this.depReasons = depReasons
            this.unusedDeps = unusedDeps
            this.deps = deps
            this.originalDependants = originalDependants
            this.dependants = dependants
            this.repoName = repoName
            this.key = key
            this.version = version
            this.name = name
            String > java.util.Objects.requireNonNull<String?>(name, "name")
            Version > java.util.Objects.requireNonNull<com.google.devtools.build.lib.bazel.bzlmod.Version?>(
                version,
                "version"
            )
            ModuleKey > java.util.Objects.requireNonNull<ModuleKey?>(key, "key")
            String > java.util.Objects.requireNonNull<String?>(repoName, "repoName")
            java.util.Objects.requireNonNull<com.google.common.collect.ImmutableSet<ModuleKey?>?>(
                dependants,
                "dependants"
            )
            java.util.Objects.requireNonNull<com.google.common.collect.ImmutableSet<ModuleKey?>?>(
                originalDependants,
                "originalDependants"
            )
            java.util.Objects.requireNonNull<com.google.common.collect.ImmutableBiMap<String?, ModuleKey?>?>(
                deps,
                "deps"
            )
            java.util.Objects.requireNonNull<com.google.common.collect.ImmutableBiMap<String?, ModuleKey?>?>(
                unusedDeps,
                "unusedDeps"
            )
            java.util.Objects.requireNonNull<com.google.common.collect.ImmutableMap<String?, ResolutionReason?>?>(
                depReasons,
                "depReasons"
            )
        }

        companion object {
            /** Returns a new [AugmentedModule.Builder] with `key` set.  */
            fun builder(key: ModuleKey): Builder {
                return AutoBuilder_BazelModuleInspectorValue_AugmentedModule_Builder()
                    .setName(key.name)
                    .setVersion(key.version)
                    .setRepoName(key.name)
                    .setKey(key)
                    .setLoaded(false)
            }
        }
    }

    val depGraph: com.google.common.collect.ImmutableMap<ModuleKey?, AugmentedModule?>?
    val modulesIndex: com.google.common.collect.ImmutableMap<String?, com.google.common.collect.ImmutableSet<ModuleKey?>?>?
    val extensionToRepoInternalNames: com.google.common.collect.ImmutableSetMultimap<ModuleExtensionId?, String?>?
    val moduleKeyToCanonicalNames: com.google.common.collect.ImmutableMap<ModuleKey?, RepositoryName?>?
    val errors: com.google.common.collect.ImmutableList<ExternalDepsException?>?

    init {
        this.errors = errors
        this.moduleKeyToCanonicalNames = moduleKeyToCanonicalNames
        this.extensionToRepoInternalNames = extensionToRepoInternalNames
        this.modulesIndex = modulesIndex
        this.depGraph = depGraph
        java.util.Objects.requireNonNull<com.google.common.collect.ImmutableMap<ModuleKey?, AugmentedModule?>?>(
            depGraph,
            "depGraph"
        )
        java.util.Objects.requireNonNull<com.google.common.collect.ImmutableMap<String?, com.google.common.collect.ImmutableSet<ModuleKey?>?>?>(
            modulesIndex,
            "modulesIndex"
        )
        java.util.Objects.requireNonNull<com.google.common.collect.ImmutableSetMultimap<ModuleExtensionId?, String?>?>(
            extensionToRepoInternalNames,
            "extensionToRepoInternalNames"
        )
        java.util.Objects.requireNonNull<com.google.common.collect.ImmutableMap<ModuleKey?, RepositoryName?>?>(
            moduleKeyToCanonicalNames,
            "moduleKeyToCanonicalNames"
        )
        java.util.Objects.requireNonNull<com.google.common.collect.ImmutableList<ExternalDepsException?>?>(
            errors,
            "errors"
        )
    }

    companion object {
        @SerializationConstant
        val KEY: SkyKey = SkyKey { SkyFunctions.BAZEL_MODULE_INSPECTION }

        fun create(
            depGraph: com.google.common.collect.ImmutableMap<ModuleKey?, AugmentedModule?>?,
            modulesIndex: com.google.common.collect.ImmutableMap<String?, com.google.common.collect.ImmutableSet<ModuleKey?>?>?,
            extensionToRepoInternalNames: com.google.common.collect.ImmutableSetMultimap<ModuleExtensionId?, String?>?,
            moduleKeyToCanonicalNames: com.google.common.collect.ImmutableMap<ModuleKey?, RepositoryName?>?,
            errors: com.google.common.collect.ImmutableList<ExternalDepsException?>?
        ): BazelModuleInspectorValue {
            return BazelModuleInspectorValue(
                depGraph, modulesIndex, extensionToRepoInternalNames, moduleKeyToCanonicalNames, errors
            )
        }
    }
}
