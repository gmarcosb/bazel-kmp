    fun mainRepoMappingComputationStarted() {
        status = "Computing main repo mapping"
        additionalMessage = ""
    }

    fun buildStarted() {
        status = "Loading"
        additionalMessage = ""
    }

    fun loadingStarted(event: LoadingPhaseStartedEvent) {
        status = null
        packageProgressReceiver = event.getPackageProgressReceiver()
    }

    fun configurationStarted(event: ConfigurationPhaseStartedEvent) {
        analysisProgressReceiver = event.getAnalysisProgressReceiver()
    }

    fun loadingComplete(event: LoadingPhaseCompleteEvent) {
        val count: Int = event.getLabels().size()
        status = "Analyzing"
        if (count == 1) {
            additionalMessage = "target " + com.google.common.collect.Iterables.getOnlyElement<T?>(event.getLabels())
        } else {
            additionalMessage = com.google.devtools.build.lib.util.StringUtil.formatCount(count.toLong()) + " targets"
        }
        mainRepositoryMapping = event.getMainRepositoryMapping()
    }

    fun executionPhaseStarted() {
        executionPhaseStarted = true
    }

    /**
     * Make the state tracker aware of the fact that the analysis has finished. Return a summary of
     * the work done in the analysis phase.
     */
    @kotlin.jvm.Synchronized
    fun analysisComplete(): String {
        var workDone = "Analyzed " + additionalMessage
        if (packageProgressReceiver != null) {
            val progress: com.google.devtools.build.lib.util.Pair<String?, String?> =
                packageProgressReceiver.progressState()
            workDone += " (" + progress.getFirst()
            if (analysisProgressReceiver != null) {
                workDone += ", " + analysisProgressReceiver.getProgressString()
            }
            workDone += ")"
        }
        workDone += "."
        status = null
        packageProgressReceiver = null
        analysisProgressReceiver = null
        return workDone
    }

    @kotlin.jvm.Synchronized
    fun progressReceiverAvailable(event: ExecutionProgressReceiverAvailableEvent) {
        executionProgressReceiver = event.executionProgressReceiver
    }

    fun buildComplete(event: BuildCompleteEvent): com.google.devtools.build.lib.events.Event? {
        setBuildComplete()
        executionProgressReceiver = null

        status = null
        additionalMessage = ""
        if (event.getResult().getSuccess()) {
            val actionsCompleted: Int = this.actionsCompleted.get()
            val completedStringBuilder: java.lang.StringBuilder = java.lang.StringBuilder().append("Build completed")
            if (failedTests == 0) {
                completedStringBuilder.append(" successfully")
            } else {
                completedStringBuilder
                    .append(", ")
                    .append(failedTests)
                    .append(pluralize(" test", failedTests))
                    .append(" FAILED")
            }
            if (!newStatsSummary) {
                completedStringBuilder
                    .append(", ")
                    .append(actionsCompleted)
                    .append(pluralize(" total action", actionsCompleted))
            }
            return com.google.devtools.build.lib.events.Event.info(completedStringBuilder.toString())
        } else {
            ok = false
            return com.google.devtools.build.lib.events.Event.error("Build did NOT complete successfully")
        }
    }

    protected fun buildCompleted(): Boolean {
        return buildComplete
    }

    fun setBuildComplete() {
        buildComplete = true
        buildCompleteAt = Instant.ofEpochMilli(clock.currentTimeMillis())
    }

    fun downloadProgress(event: FetchProgress) {
        runningDownloads.compute(
            event.resourceIdentifier
        ) { unusedKey: String?, latestData: DownloadData? ->
            if (event.isFinished)
                null
            else
                DownloadData(
                    event, if (latestData != null) latestData.nanoStartTime else clock.nanoTime()
                )
        }
    }

    private fun getActionState(
        action: ActionExecutionMetadata, actionId: Artifact?, nanoTimeNow: Long
    ): ActionState {
        return activeActions.computeIfAbsent(actionId) { key: Artifact? -> ActionState(action, nanoTimeNow) }
    }

    private fun getActionStateIfPresent(actionId: Artifact?): ActionState? {
        return activeActions.get(actionId)
    }

    fun actionStarted(event: ActionStartedEvent) {
        val action: Action = event.getAction()
        val actionId: Artifact? = action.getPrimaryOutput()

        getActionState(action, actionId, event.getNanoTimeStart())

        if (action.getOwner() != null
            && action.getOwner().getBuildConfigurationMnemonic().equals("TestRunner")
        ) {
            val owner: Label? = action.getOwner().getLabel()
            if (owner != null) {
                val testActionsForOwner: MutableSet<Artifact?>? = testActions.get(owner)
                if (testActionsForOwner != null) {
                    testActionsForOwner.add(actionId)
                }
            }
        }
    }

    fun scanningAction(event: ScanningActionEvent) {
        val action: ActionExecutionMetadata = event.getActionMetadata()
        val actionId: Artifact? = event.getActionMetadata().getPrimaryOutput()
        val now: Long = clock.nanoTime()
        getActionState(action, actionId, now).setScanning(now)
    }

    fun stopScanningAction(event: StoppedScanningActionEvent) {
        val action: Action = event.getAction()
        val actionId: Artifact? = action.getPrimaryOutput()
        val now: Long = clock.nanoTime()
        getActionState(action, actionId, now).setStopScanning(now)
    }

    fun cachingAction(event: CachingActionEvent) {
        val action: ActionExecutionMetadata = event.action()
        val actionId: Artifact? = action.getPrimaryOutput()
        val now: Long = clock.nanoTime()
        getActionState(action, actionId, now).setCaching(event.strategy(), now)
    }

    fun schedulingAction(event: SchedulingActionEvent) {
        val action: ActionExecutionMetadata = event.getActionMetadata()
        val actionId: Artifact? = event.getActionMetadata().getPrimaryOutput()
        val now: Long = clock.nanoTime()
        getActionState(action, actionId, now).setScheduling(event.getStrategy(), now)
    }

    fun runningAction(event: RunningActionEvent) {
        val action: ActionExecutionMetadata = event.getActionMetadata()
        val actionId: Artifact? = event.getActionMetadata().getPrimaryOutput()
        val now: Long = clock.nanoTime()
        getActionState(action, actionId, now).setRunning(event.getStrategy(), now)
    }

    fun actionProgress(event: ActionProgressEvent) {
        val actionId: Artifact? = event.action().getPrimaryOutput()
        val actionState = getActionStateIfPresent(actionId)
        if (actionState != null) {
            actionState.onProgressEvent(event)
        }
    }

    fun actionCompletion(event: ActionScanningCompletedEvent) {
        val action: Action = event.getAction()
        val actionId: Artifact? = action.getPrimaryOutput()
        com.google.common.base.Preconditions.checkNotNull<ActionState?>(
            activeActions.remove(actionId),
            "%s not active after %s",
            actionId,
            event
        )

        // As callers to the experimental state tracker assume we will fully report the new state once
        // informed of an action completion, we need to make sure the progress receiver is aware of the
        // completion, even though it might be called later on the event bus.
        if (executionProgressReceiver != null) {
            executionProgressReceiver.actionCompleted(event.getActionLookupData())
        }
    }

    fun actionCompletion(event: ActionCompletionEvent) {
        actionsCompleted.incrementAndGet()
        val action: Action = event.getAction()
        val actionId: Artifact? = action.getPrimaryOutput()

        com.google.common.base.Preconditions.checkNotNull<ActionState?>(
            activeActions.remove(actionId),
            "%s not active after %s",
            actionId,
            event
        )

        if (action.getOwner() != null
            && action.getOwner().getBuildConfigurationMnemonic().equals("TestRunner")
        ) {
            val owner: Label? = action.getOwner().getLabel()
            if (owner != null) {
                val testActionsForOwner: MutableSet<Artifact?>? = testActions.get(owner)
                if (testActionsForOwner != null) {
                    testActionsForOwner.remove(actionId)
                }
            }
        }

        // As callers to the experimental state tracker assume we will fully report the new state once
        // informed of an action completion, we need to make sure the progress receiver is aware of the
        // completion, even though it might be called later on the event bus.
        if (executionProgressReceiver != null) {
            executionProgressReceiver.actionCompleted(event.getActionLookupData())
        }
    }

    fun actionUploadStarted(event: ActionUploadStartedEvent?) {
        activeActionUploads.incrementAndGet()
    }

    fun actionUploadFinished(event: ActionUploadFinishedEvent?) {
        activeActionUploads.decrementAndGet()
    }

    fun logAndGetInflightActions(): InflightActionInfo {
        val mnemonicHistogram: com.google.common.collect.Multiset<String?> =
            com.google.common.collect.HashMultiset.create<String?>()
        for (actionState in activeActions.values) {
            mnemonicHistogram.add(actionState.action.getMnemonic())
        }

        val total: Int = mnemonicHistogram.size
        val top20: MutableList<com.google.common.collect.Multiset.Entry<String?>> =
            mnemonicHistogram.entrySet().stream()
                .collect(
                    com.google.common.collect.Comparators.greatest<com.google.common.collect.Multiset.Entry<String?>?>(
                        20,
                        java.util.Comparator.comparingInt<com.google.common.collect.Multiset.Entry<String?>?>(
                            ToIntFunction { com.google.common.collect.Multiset.Entry.getCount() })
                    )
                )
        logger.atInfo().log(
            "Total number of actions in flight: %d. Most frequent mnemonics: %s", total, top20
        )

        val inflightActions: Unit /* TODO: class org.jetbrains.kotlin.nj2k.types.JKJavaNullPrimitiveType */? =
            InflightActionInfo.newBuilder().setCount(total)
        for (entry in top20) {
            inflightActions
                .addTopMnemonicsBuilder()
                .setMnemonic(entry.getElement())
                .setCount(entry.getCount())
        }
        return inflightActions.build()
    }

    /**
     * If possible come up with a human-readable description of the label that fits within the given
     * width; a non-positive width indicates not no restriction at all.
     */
    private fun shortenedLabelString(label: Label, width: Int): String {
        if (width <= 0) {
            return label.getDisplayForm(mainRepositoryMapping)
        }
        var name: String = label.getDisplayForm(mainRepositoryMapping)
        if (name.length <= width) {
            return name
        }
        name = suffix(name, width - ELLIPSIS.length)
        val slashPos: Int = name.indexOf('/')
        if (slashPos >= 0) {
            return ELLIPSIS + name.substring(slashPos)
        }
        val colonPos: Int = name.indexOf(':')
        if (slashPos >= 0) {
            return ELLIPSIS + name.substring(colonPos)
        }
        // no reasonable place found to shorten; as last resort, just truncate
        if (3 * ELLIPSIS.length <= width) {
            return ELLIPSIS + suffix(label.toString(), width - ELLIPSIS.length)
        }
        return label.toString()
    }

    // Describe a group of actions running for the same test.
    private fun describeTestGroup(
        owner: Label, nanoTime: Long, desiredWidth: Int, allActions: MutableSet<Artifact?>
    ): String {
        val prefix = "Testing "
        val labelSep = " ["
        val postfix = " (" + allActions.size + " actions)]"
        // Leave enough room for at least 3 samples of run times, each 4 characters
        // (a digit, 's', comma, and space).
        val labelWidth = desiredWidth - prefix.length - labelSep.length - postfix.length - 12
        val message: java.lang.StringBuilder =
            java.lang.StringBuilder(prefix).append(shortenedLabelString(owner, labelWidth)).append(labelSep)

        // Compute the remaining width for the sample times, but if the desired width is too small
        // anyway, then show at least one sample.
        var remainingWidth: Int = desiredWidth - message.length - postfix.length
        if (remainingWidth < 0) {
            remainingWidth = "[1s], ".length + 1
        }

        var sep = ""
        var allReported = true
        for (actionId in allActions) {
            val actionState = activeActions.get(actionId)
            if (actionState == null) {
                // This action must have completed while we were constructing this output. Skip it.
                continue
            }
            val nanoRuntime = nanoTime - actionState.nanoStartTime
            val runtimeSeconds = nanoRuntime / NANOS_PER_SECOND
            val phase = actionState.phase
            val text =
                if (phase.compareTo(ActionPhase.RUNNING) < 0)
                    sep + "[" + runtimeSeconds + "s]"
                else
                    sep + runtimeSeconds + "s"
            if (remainingWidth < text.length) {
                allReported = false
                break
            }
            message.append(text)
            remainingWidth -= text.length
            sep = ", "
        }
        return message.append(if (allReported) "]" else postfix).toString()
    }

    private fun describeActionProgress(action: ActionState, desiredWidth: Int): String {
        val stateOpt: java.util.Optional<ProgressState> = action.firstProgress()
        if (!stateOpt.isPresent()) {
            return ""
        }

        val state: ProgressState = stateOpt.get()
        val event: ActionProgressEvent = state.latestEvent
        var message: String = event.progress()
        if (message.isEmpty()) {
            message = state.id
        }

        message = "; " + message

        if (desiredWidth <= 0 || message.length <= desiredWidth) {
            return message
        }

        message = message.substring(0, desiredWidth - ELLIPSIS.length) + ELLIPSIS
        return message
    }

    // Describe an action by a string of the desired length; if describing that action includes
    // describing other actions, add those to the to set of actions to skip in further samples of
    // actions.
    protected fun describeAction(
        actionState: ActionState, nanoTime: Long, desiredWidth: Int, toSkip: MutableSet<Artifact?>?
    ): String {
        val action: ActionExecutionMetadata = actionState.action
        if (action.getOwner() != null
            && action.getOwner().getBuildConfigurationMnemonic().equals("TestRunner")
        ) {
            val owner: Label? = action.getOwner().getLabel()
            if (owner != null) {
                val allRelatedActions: MutableSet<Artifact?>? = testActions.get(owner)
                if (allRelatedActions != null && allRelatedActions.size > 1) {
                    if (toSkip != null) {
                        toSkip.addAll(allRelatedActions)
                    }
                    return describeTestGroup(owner, nanoTime, desiredWidth, allRelatedActions)
                }
            }
        }

        var postfix = ""
        var prefix = ""
        val nanoRuntime = nanoTime - actionState.nanoStartTime
        val runtimeSeconds = nanoRuntime / NANOS_PER_SECOND
        var strategy: String? = null
        val phase = actionState.phase
        if (phase == ActionPhase.CACHING || phase == ActionPhase.RUNNING) {
            strategy = strategyIds.formatNames(actionState.strategyBitmap)
        } else {
            var status = phase.describe()
            if (status == null) {
                status = NO_STATUS
            }
            if (status.length > STATUS_LENGTH) {
                status = status.substring(0, STATUS_LENGTH)
            }
            prefix = prefix + "[" + status + "] "
        }
        // To keep the UI appearance more stable, always show the elapsed
        // time if we also show a strategy (otherwise the strategy will jump in
        // the progress bar).
        if (strategy != null || runtimeSeconds > SHOW_TIME_THRESHOLD_SECONDS) {
            postfix = "; " + runtimeSeconds + "s"
        }
        if (strategy != null) {
            postfix += " " + strategy
        }

        var message: String? = action.getProgressMessage(mainRepositoryMapping)
        if (message == null) {
            message = action.prettyPrint()
        }

        var progress = describeActionProgress(actionState, 0)

        if (desiredWidth <= 0
            || ((prefix.length + message!!.length + progress.length + postfix.length)
                    <= desiredWidth)
        ) {
            return prefix + message + progress + postfix
        }

        // We have to shorten the progress to fit into the line.
        val remainingWidthForProgress =
            desiredWidth - prefix.length - message.length - postfix.length
        val minWidthForProgress = 7 // "; " + at least two character + "..."
        if (remainingWidthForProgress >= minWidthForProgress) {
            progress = describeActionProgress(actionState, remainingWidthForProgress)
            return prefix + message + progress + postfix
        }

        // We have to skip the progress to fit into the line.
        if (prefix.length + message.length + postfix.length <= desiredWidth) {
            return prefix + message + postfix
        }

        // We have to shorten the message to fit into the line.
        if (action.getOwner() != null) {
            if (action.getOwner().getLabel() != null) {
                // First attempt is to shorten the package path string in the messge, if it occurs there
                val pathString = action.getOwner().getLabel().getPackageFragment().toString()
                val pathIndex: Int = message.indexOf(pathString)
                if (pathIndex >= 0) {
                    val start: String = message.substring(0, pathIndex)
                    val end: String = message.substring(pathIndex + pathString.length)
                    val pathTargetLength =
                        desiredWidth - start.length - end.length - postfix.length - prefix.length
                    // This attempt of shortening is reasonable if what is left from the label
                    // is significantly longer (twice as long) as the ellipsis symbols introduced.
                    if (pathTargetLength >= 3 * ELLIPSIS.length) {
                        val shortPath = suffix(pathString, pathTargetLength - ELLIPSIS.length)
                        val slashPos: Int = shortPath.indexOf('/')
                        if (slashPos >= 0) {
                            return prefix + start + ELLIPSIS + shortPath.substring(slashPos) + end + postfix
                        }
                    }
                }

                // Second attempt: just take a shortened version of the label.
                val shortLabel =
                    shortenedLabelString(
                        action.getOwner().getLabel(), desiredWidth - postfix.length - prefix.length
                    )
                if (prefix.length + shortLabel.length + postfix.length <= desiredWidth) {
                    return prefix + shortLabel + postfix
                }
            }
        }
        if (3 * ELLIPSIS.length + postfix.length + prefix.length <= desiredWidth) {
            message =
                (ELLIPSIS
                        + Companion.suffix(
                    message, desiredWidth - ELLIPSIS.length - postfix.length - prefix.length
                ))
        }

        return prefix + message + postfix
    }

    private val oldestAction: ActionState?
        get() {
            var minRunningStart = Long.Companion.MAX_VALUE
            var oldestRunning: ActionState? = null
            var minScheduledStart = Long.Companion.MAX_VALUE
            var oldestScheduled: ActionState? = null

            for (action in activeActions.values) {
                if (action.phase == ActionPhase.RUNNING) {
                    if (action.nanoStartTime < minRunningStart) {
                        minRunningStart = action.nanoStartTime
                        oldestRunning = action
                    }
                } else {
                    if (action.nanoStartTime < minScheduledStart) {
                        minScheduledStart = action.nanoStartTime
                        oldestScheduled = action
                    }
                }
            }

            return if (oldestRunning != null) oldestRunning else oldestScheduled
        }

    protected fun countActions(): String {
        // TODO(djasper): Iterating over the actions here is slow, but it's only done once per refresh
        // and thus might be faster than trying to update these values in the critical path.
        // Re-investigate if this ever turns up in a profile.
        var actionsCount = 0
        var executingActionsCount = 0
        for (actionState in activeActions.values) {
            actionsCount++
            if (actionState.phase == ActionPhase.RUNNING) {
                executingActionsCount++
            }
        }

        if (actionsCount == 1) {
            return " 1 action running"
        } else if (actionsCount == executingActionsCount) {
            return actionsCount.toString() + " actions running"
        } else {
            return actionsCount.toString() + " actions, " + executingActionsCount + " running"
        }
    }

