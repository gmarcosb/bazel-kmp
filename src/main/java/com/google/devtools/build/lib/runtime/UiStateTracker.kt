    protected fun reportOnDownloads(terminalWriter: PositionAwareAnsiTerminalWriter) {
        val runningDownloadsSnapshot: java.util.ArrayList<MutableMap.MutableEntry<String?, DownloadData?>> =
            java.util.ArrayList<MutableMap.MutableEntry<String?, DownloadData?>>(runningDownloads.entries)
        TODO(
