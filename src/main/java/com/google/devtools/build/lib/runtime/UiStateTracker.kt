    @Throws(IOException::class)
    private fun sampleOldestActions(terminalWriter: AnsiTerminalWriter) {
        // This method can only be called if 'activeActions.size()' was observed to be larger than 1 at
        // some point in the past. But the 'activeActions' map can grow and shrink concurrent with this
        // code here so we need to be very careful lest we fall victim to a check-then-act race.
        val racyActiveActionsCount = activeActions.size
        val priorityHeap: java.util.PriorityQueue<MutableMap.MutableEntry<Artifact?, ActionState?>> =
            java.util.PriorityQueue<MutableMap.MutableEntry<Artifact?, ActionState?>>( // The 'initialCapacity' parameter must be positive.
                /* initialCapacity= */
                max(racyActiveActionsCount, 1),
                TODO("Cannot convert element")
            )
        Boolean > java.util.Comparator.comparing<MutableMap.MutableEntry<Artifact?, ActionState?>?, Boolean?>(
            java.util.function.Function { entry: MutableMap.MutableEntry<Artifact?, ActionState?>? -> entry!!.value.phase == ActionPhase.RUNNING },
            com.google.common.primitives.Booleans.trueFirst()
        )
            .thenComparingLong(java.util.function.ToLongFunction { entry: MutableMap.MutableEntry<Artifact?, ActionState?>? -> entry!!.value!!.nanoStartTime })
            .thenComparingInt(ToIntFunction { entry: MutableMap.MutableEntry<Artifact?, ActionState?>? -> entry!!.value!!.hashCode() })

        priorityHeap.addAll(activeActions.entries)
        // From this point on, we no longer consume 'activeActions'. So now it's sound to look at how
        // many entries were added to 'priorityHeap' and act appropriately based on that count.
        val actualObservedActiveActionsCount: Int = priorityHeap.size

        val count = 0
        val totalCount = 0
        val nanoTime: Long = clock.nanoTime()
        val toSkip: MutableSet<Artifact?> = HashSet<Artifact?>()

        while (!priorityHeap.isEmpty()) {
            val entry: MutableMap.MutableEntry<Artifact?, ActionState?> = priorityHeap.poll()
            totalCount++
            if (toSkip.contains(entry.key)) {
                continue
            }
            count++
            if (count > sampleSize) {
                totalCount--
                break
            }
            val width =
                (targetWidth
                        - 4
                        - (if (count >= sampleSize && count < actualObservedActiveActionsCount)
                    AND_MORE.length
                else
                    0))
            terminalWriter
                .newline()
                .append("    " + describeAction(entry.value!!, nanoTime, width, toSkip))
        }
        if (totalCount < actualObservedActiveActionsCount) {
            terminalWriter.append(AND_MORE)
        }
    }

    @kotlin.jvm.Synchronized
    fun testFilteringComplete(event: TestFilteringCompleteEvent) {
        if (event.getTestTargets() != null) {
            totalTests = event.getTestTargets().size
            for (target in event.getTestTargets()) {
                if (target.getLabel() != null) {
                    testActions.put(target.getLabel(), com.google.common.collect.Sets.newConcurrentHashSet<Artifact?>())
                }
            }
        }
    }

    @kotlin.jvm.Synchronized
    fun singleTestAnalyzed(event: TestAnalyzedEvent) {
        val target: ConfiguredTarget = event.configuredTarget
        // Only register the count towards totalTests once.
        if (target.getLabel() != null
            && testActions.putIfAbsent(
                target.getLabel(),
                com.google.common.collect.Sets.newConcurrentHashSet<Artifact?>()
            ) == null
        ) {
            totalTests++
        }
    }

    @kotlin.jvm.Synchronized
    fun testSummary(summary: TestSummary) {
        completedTests++
        mostRecentTest = summary
        if ((summary.getStatus() !== BlazeTestStatus.PASSED)
            && (summary.getStatus() !== BlazeTestStatus.FLAKY)
        ) {
            failedTests++
        }
    }

