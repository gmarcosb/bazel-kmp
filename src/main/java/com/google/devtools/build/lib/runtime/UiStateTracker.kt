            """.trimMargin()
        )

        val count = 0
        val nanoTime: Long = clock.nanoTime()
        val downloadCount: Int = runningDownloadsSnapshot.size
        val suffix = AND_MORE + " (" + downloadCount + " fetches)"
        for (download in runningDownloadsSnapshot) {
            if (count >= sampleSize) {
