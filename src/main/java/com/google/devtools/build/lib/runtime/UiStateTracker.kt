    // Non-positive values indicate not to aim for a particular width.
    protected val targetWidth: Int

    /**
     * Tracker of strategy names to unique IDs and viceversa.
     * 
     * 
     * The IDs generated by this class can be used to index bitmaps.
     * 
     * 
     * TODO(jmmv): Would be nice if the strategies themselves contained their IDs (initialized at
     * construction time) and we passed around those IDs instead of strings.
     */
    @javax.annotation.concurrent.ThreadSafe
    @com.google.common.annotations.VisibleForTesting
    internal class StrategyIds {
        /** Counter of unique strategies seen so far.  */
        private val counter: AtomicInteger = AtomicInteger(0)

        /** Mapping of strategy names to their unique IDs.  */
        private val strategyIds: MutableMap<String?, Int?> = ConcurrentHashMap<String?, Int?>()

        /** Mapping of strategy unique IDs to their names.  */
        private val strategyNames: MutableMap<Int?, String?> = ConcurrentHashMap<Int?, String?>()

        @kotlin.jvm.JvmField
        val fallbackId: Int?

        /** Constructs a new collection of strategy IDs.  */
        init {
            fallbackId = getId(FALLBACK_NAME)
        }

        /** Computes the ID of a strategy given its name.  */
        fun getId(strategy: String?): Int? {
            val id: Int? =
                strategyIds.computeIfAbsent(
                    strategy
                ) { key: String? ->
                    val value: Int = counter.getAndIncrement()
                    if (value >= java.lang.Integer.SIZE) {
                        return@computeIfAbsent fallbackId
                    } else {
                        return@computeIfAbsent 1 shl value
                    }
                }
            strategyNames.putIfAbsent(id, strategy)
            return id
        }

        /** Flattens a bitmap of strategy IDs into a human-friendly string.  */
        fun formatNames(bitmap: Int): String {
            var bitmap = bitmap
            val builder: java.lang.StringBuilder = java.lang.StringBuilder()
            var mask = 0x1
            while (bitmap != 0) {
                val id = bitmap and mask
                if (id != 0) {
                    val name: String = com.google.common.base.Preconditions.checkNotNull<String>(
                        strategyNames.get(id),
                        "Unknown strategy with id %s",
                        id
                    )
                    builder.append(name)
                    bitmap = bitmap and mask.inv()
                    if (bitmap != 0) {
                        builder.append(", ")
                    }
                }
                mask = mask shl 1
            }
            return builder.toString()
        }

        companion object {
            /** Fallback name in case we exhaust our space for IDs.  */
            const val FALLBACK_NAME: String = "unknown"
        }
    }

    /**
     * The various phases of action execution.
     * 
     * 
     * The typical progression is:
     * 
     * <pre>
     * Preparing > Scanning > Preparing > Caching > Scheduling > Running
    </pre> * 
     * 
     * 
     * Some actions may not go through every phase (e.g. scanning).
     */
    private enum class ActionPhase(description: String) {
        PREPARING("Preparing"),
        SCANNING("Scanning"),
        CACHING("Caching"),
        SCHEDULING("Scheduling"),
        RUNNING("Running");

        val description: String?

        init {
            this.description = description
        }

        /** Returns a human-readable description of this phase.  */
        fun describe(): String? {
            return description
        }
    }

    /**
     * Tracks all details for an action that we have heard about.
     * 
     * 
     * We cannot make assumptions on the order in which action state events come in, so this class
     * takes care of always "advancing" the state of an action.
     */
    protected class ActionState internal constructor(action: ActionExecutionMetadata, nanoStartTime: Long) {
        /**
         * The action this state belongs to.
         * 
         * 
         * We assume that all events related to the same action refer to the same [ ] object.
         */
        val action: ActionExecutionMetadata

        /** Timestamp of the last state change.  */
        var nanoStartTime: Long

        /** Returns the phase this action is currently in.  */
        /**
         * The phase this action is currently in.
         * 
         * 
         * When multiple strategies are applied, this is the phase of the strategy that has made the
         * most progress.
         */
        @get:kotlin.jvm.Synchronized
        private var phase = ActionPhase.PREPARING

        /** Returns the set of strategies currently applied to this action.  */
        /** The set of strategies that have been applied to this action.  */
        @get:kotlin.jvm.Synchronized
        var strategyBitmap: Int = 0

        private class ProgressState(val id: String) {
            var latestEvent: ActionProgressEvent? = null
        }

        @javax.annotation.concurrent.GuardedBy("this")
        private val runningProgresses: LinkedHashMap<String?, ProgressState> = LinkedHashMap<String?, ProgressState>()

        /** Starts tracking the state of an action.  */
        init {
            this.action = action
            this.nanoStartTime = nanoStartTime
        }

        /**
         * Marks the action as scanning.
         * 
         * 
         * Because we may receive events out of order, this does not affect the current phase if the
         * action is already caching, scheduling or running for any strategy.
         */
        @kotlin.jvm.Synchronized
        fun setScanning(nanoChangeTime: Long) {
            if (phase.compareTo(ActionPhase.SCANNING) < 0) {
                this.phase = ActionPhase.SCANNING
                nanoStartTime = nanoChangeTime
            }
        }

        /**
         * Marks the action as no longer scanning.
         * 
         * 
         * Because we may receive events out of order, this does not affect the current phase if the
         * action is already caching, scheduling or running for any strategy.
         */
        @kotlin.jvm.Synchronized
        fun setStopScanning(nanoChangeTime: Long) {
            if (phase.compareTo(ActionPhase.CACHING) < 0) {
                this.phase = ActionPhase.PREPARING
                nanoStartTime = nanoChangeTime
            }
        }

        /**
         * Marks the action as caching with the given strategy.
         * 
         * 
         * Because we may receive events out of order, this does not affect the current phase if the
         * action is already caching, scheduling or running for any other strategy.
         */
        @kotlin.jvm.Synchronized
        fun setCaching(strategy: String?, nanoChangeTime: Long) {
            strategyBitmap = strategyBitmap or strategyIds.getId(strategy)!!
            if (phase.compareTo(ActionPhase.CACHING) < 0) {
                this.phase = ActionPhase.CACHING
                nanoStartTime = nanoChangeTime
            }
        }

        /**
         * Marks the action as scheduling with the given strategy.
         * 
         * 
         * Because we may receive events out of order, this does not affect the current phase if the
         * action is already scheduling or running for any other strategy.
         */
        @kotlin.jvm.Synchronized
        fun setScheduling(strategy: String?, nanoChangeTime: Long) {
            strategyBitmap = strategyBitmap or strategyIds.getId(strategy)!!
            if (phase.compareTo(ActionPhase.SCHEDULING) < 0) {
                this.phase = ActionPhase.SCHEDULING
                nanoStartTime = nanoChangeTime
            }
        }

        /**
         * Marks the action as running with the given strategy.
         * 
         * 
         * Because we may receive events out of order, this does not affect the current phase if the
         * action is already running for any other strategy.
         */
        @kotlin.jvm.Synchronized
        fun setRunning(strategy: String?, nanoChangeTime: Long) {
            strategyBitmap = strategyBitmap or strategyIds.getId(strategy)!!
            if (phase.compareTo(ActionPhase.RUNNING) < 0) {
                this.phase = ActionPhase.RUNNING
                nanoStartTime = nanoChangeTime
            }
        }

        /** Handles the progress event for the action.  */
        @kotlin.jvm.Synchronized
        fun onProgressEvent(event: ActionProgressEvent) {
            val id: String? = event.progressId()
            if (event.finished()) {
                // a progress is finished, clean it up
                runningProgresses.remove(id)
                return
            }

            val state: ProgressState = runningProgresses.computeIfAbsent(id) { key: String? -> ProgressState(key!!) }
            state.latestEvent = event
        }

        @kotlin.jvm.Synchronized
        private fun firstProgress(): java.util.Optional<ProgressState> {
            if (runningProgresses.isEmpty()) {
                return java.util.Optional.empty<ProgressState?>()
            }
            return java.util.Optional.of<ProgressState?>(runningProgresses.entries.iterator().next().value)
        }
    }

    protected val activeActions: MutableMap<Artifact?, ActionState>
    private val activeActionUploads: AtomicInteger = AtomicInteger(0)
    private val activeActionDownloads: AtomicInteger = AtomicInteger(0)

    // Running downloads are identified by the original URL they were trying to access.
    private val runningDownloads: ConcurrentHashMap<String?, DownloadData?> =
        ConcurrentHashMap<String?, DownloadData?>()

    private class DownloadData(latestEvent: FetchProgress?, nanoStartTime: Long) {
        val latestEvent: FetchProgress?
        val nanoStartTime: Long

        init {
            this.latestEvent = latestEvent
