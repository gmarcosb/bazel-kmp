package com.google.devtools.build.lib.runtime.commands

import com.google.devtools.build.lib.runtime.Command.BuildPhase.EXECUTES

/**
 * Handles the 'coverage' command on the Bazel command line.
 * 
 * 
 * Here follows a brief, partial and probably wrong description of how coverage collection works
 * in Bazel.
 * 
 * 
 * Coverage is reported by the tests in LCOV format in the files `testlogs/PACKAGE/TARGET/coverage.dat` and `testlogs/PACKAGE/TARGET/coverage.micro.dat`.
 * 
 * 
 * To collect coverage, each test execution is wrapped in a script called `collect_coverage.sh`. This script sets up the environment of the test to enable coverage
 * collection and determine where the coverage files are written by the coverage runtime(s). It then
 * runs the test. A test may itself run multiple subprocesses and consist of modules written in
 * multiple different languages (with separate coverage runtimes). As such, the wrapper script
 * converts the resulting files to lcov format if necessary, and merges them into a single file.
 * 
 * 
 * The interposition itself is done by the test strategies, which requires `collect_coverage.sh` to be on the inputs of the test. This is accomplished by an implicit
 * attribute `:coverage_support` which is resolved to the value of the configuration flag
 * `--coverage_support` (see [ ][com.google.devtools.build.lib.analysis.test.TestConfiguration.TestOptions.coverageSupport]).
 * 
 * 
 * There are languages for which we do offline instrumentation, meaning that the coverage
 * instrumentation is added at compile time, e.g. for C++, and for others, we do online
 * instrumentation, meaning that coverage instrumentation is added at execution time, e.g. for
 * Javascript.
 * 
 * 
 * Another core concept is that of **baseline coverage**. This is essentially the coverage of
 * library, binary, or test if no code in it was run. The problem it solves is that if you want to
 * compute the test coverage for a binary, it is not enough to merge the coverage of all of the
 * tests, because there may be code in the binary that is not linked into any test. Therefore, what
 * we do is to emit a coverage file for every binary, which contains only the files we collect
 * coverage for with no covered lines. The baseline coverage file for a target is at `testlogs/PACKAGE/TARGET/baseline_coverage.dat`, but rules are encouraged to generate their own
 * baseline coverage files with more meaningful content than just the names of the source files.
 * 
 * 
 * We track two groups of files for coverage collection for each rule: the set of instrumented
 * files and the set of instrumentation metadata files.
 * 
 * 
 * The set of instrumented files is just that, a set of files to instrument. For online coverage
 * runtimes, this can be used at runtime to decide which files to instrument. It is also used to
 * implement baseline coverage.
 * 
 * 
 * The set of instrumentation metadata files is the set of extra files a test needs to generate
 * the LCOV files Bazel requires from it. In practice, this consists of runtime-specific files; for
 * example, the gcc compiler emits `.gcno` files during compilation. These are added to the
 * set of inputs of test actions if coverage mode is enabled (otherwise the set of metadata files is
 * empty).
 * 
 * 
 * Whether or not coverage is being collected is stored in the `BuildConfigurationValue`.
 * This is handy because then we have an easy way to change the test action and the action graph
 * depending on this bit, but it also means that if this bit is flipped, all targets need to be
 * re-analyzed (note that some languages, e.g. C++ require different compiler options to emit code
 * that can collect coverage, which dominates the time required for analysis).
 * 
 * 
 * The coverage support files are depended on through labels an implicit dependency so that they
 * can be overridden by the invocation policy, which allows them to differ between the different
 * versions of Bazel. Ideally, these differences will be removed, and we standardize on
 * 
 * @bazel_tools//tools/coverage.
 * 
 * A partial set of file types that can be encountered in the coverage world:
 * 
 *  * **`.gcno`:** Coverage metadata file generated by GCC/Clang.
 *  * **`.gcda`:** Coverage file generated when a coverage-instrumented binary
 * compiled by GCC/Clang is run. When combined with the matching `.gcno` file, there
 * is enough data to generate an LCOV file.
 *  * **`.instrumented_files`:** A text file containing the exec paths of the
 * instrumented files in a library, binary or test, one in each line. Used to generate the
 * baseline coverage.
 *  * **`coverage.dat`:** Coverage data for a single test run.
 *  * **`coverage.micro.dat`:** Microcoverage data for a single test run.
 *  * **`_coverage_report.dat`:** Coverage file for a whole Bazel invocation.
 * Generated in `BuildView` in combination with `CoverageReportActionFactory`.
 * 
 * 
 * **OPEN QUESTIONS:**
 * 
 *  * How per-testcase microcoverage data get reported?
 *  * How does Jacoco work?
 * 
 */
@Command(
    name = "coverage",
    buildPhase = EXECUTES,
    inheritsOptionsFrom = [com.google.devtools.build.lib.runtime.commands.TestCommand::class],
    shortDescription = "Generates code coverage report for specified test targets.",
    completion = "label-test",
    help = "resource:coverage.txt",
    allowResidue = true
)
class CoverageCommand : com.google.devtools.build.lib.runtime.commands.TestCommand() {
    override fun commandName(): String {
        return "coverage"
    }

    override fun editOptions(optionsParser: com.google.devtools.common.options.OptionsParser) {
        super.editOptions(optionsParser)
        try {
            optionsParser.parse(
                com.google.devtools.common.options.OptionPriority.PriorityCategory.SOFTWARE_REQUIREMENT,
                "Options required by the coverage command",
                com.google.common.collect.ImmutableList.of<String?>("--collect_code_coverage")
            )
            optionsParser.parse(
                com.google.devtools.common.options.OptionPriority.PriorityCategory.COMPUTED_DEFAULT,
                "Options suggested for the coverage command",
                com.google.common.collect.ImmutableList.of<String?>(TestTimeout.COVERAGE_CMD_TIMEOUT)
            )
        } catch (e: com.google.devtools.common.options.OptionsParsingException) {
            // Should never happen.
            throw java.lang.IllegalStateException("Unexpected exception", e)
        }
    }
}
