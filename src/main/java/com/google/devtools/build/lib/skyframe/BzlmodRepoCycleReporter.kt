package com.google.devtools.build.lib.skyframe

import com.google.devtools.build.lib.bazel.bzlmod.BazelDepGraphValue

/** Reports cycles introduced by module extensions and .bzl files where they are declared.  */
class BzlmodRepoCycleReporter : SingleCycleReporter {
    public override fun maybeReportCycle(
        topLevelKey: SkyKey?,
        cycleInfo: CycleInfo,
        alreadyReported: Boolean,
        eventHandler: ExtendedEventHandler
    ): Boolean {
        val cycle: com.google.common.collect.ImmutableList<SkyKey?> = cycleInfo.getCycle()
        if (alreadyReported) {
            return true
        }

        // This cycle reporter is aimed to handle cycles between any chaining of general .bzl
        // files, extension-generated repositories, extension evaluations, and the .bzl files where
        // they are declared. The state machine that describes this kind of cycles is:
        //    ________________________
        //   V                        |
        // PACKAGE -> REPOSITORY -> EXT -> BZL_LOAD -
        //                   ^                   ^   \
        //                   |___________________|___|
        // TODO(andreisolo): Figure out how to detect and print this kind of cycles more specifically.
        if (com.google.common.collect.Iterables.all<SkyKey?>(
                cycle,
                com.google.common.base.Predicates.or<SkyKey?>(
                    IS_REPOSITORY_DIRECTORY,
                    IS_PACKAGE_LOOKUP,
                    IS_REPO_DEFINITION,
                    IS_EXTENSION_IMPL,
                    IS_EXTENSION_VALIDATION,
                    IS_BZL_LOAD,
                    IS_CONTAINING_PACKAGE,
                    IS_REPO_MAPPING,
                    IS_MODULE_EXTENSION_REPO_MAPPING_ENTRIES,
                    IS_PACKAGE,
                    IS_MODULE_RESOLUTION,
                    IS_DEP_GRAPH,
                    IS_MODULE_FILE,
                    IS_FILE,
                    IS_FILE_STATE
                )
            )
            && com.google.common.collect.Iterables.any<SkyKey?>(
                cycle,
                com.google.common.base.Predicates.or<SkyKey?>(
                    IS_REPOSITORY_DIRECTORY,
                    IS_REPO_DEFINITION,
                    IS_EXTENSION_IMPL
                )
            )
        ) {
            val cycleMessage: java.lang.StringBuilder =
                java.lang.StringBuilder(
                    "Circular definition of repositories generated by module extensions or files in"
                            + " external repositories:"
                )
            val repos: Iterable<SkyKey> =
                com.google.common.collect.Iterables.filter<SkyKey?>(
                    cycle,
                    com.google.common.base.Predicates.or<SkyKey?>(
                        IS_REPOSITORY_DIRECTORY,
                        IS_EXTENSION_IMPL,
                        IS_BZL_LOAD,
                        IS_REPO_MAPPING,
                        IS_MODULE_RESOLUTION,
                        IS_DEP_GRAPH,
                        IS_MODULE_FILE
                    )
                )
            val printer: com.google.common.base.Function<Any?, String?> =
                com.google.common.base.Function { rawInput: Any? ->
                    val input: SkyKey? = rawInput as SkyKey?
                    if (input is RepositoryDirectoryValue.Key) {
                        return@Function (input as RepositoryDirectoryValue.Key).argument().toString()
                    } else if (input.argument() is ModuleExtensionId) {
                        return@Function "module extension " + id
                    } else if (input.argument() is com.google.devtools.build.lib.skyframe.RepositoryMappingValue.Key) {
                        return@Function java.lang.String.format("repository mapping of %s", key.repoName())
                    } else if (input.argument() === BazelModuleResolutionValue.KEY) {
                        return@Function "module resolution"
                    } else if (input.argument() === BazelDepGraphValue.KEY) {
                        return@Function "module dependency graph"
                    } else if (input.argument() is ModuleFileValue.Key) {
                        return@Function "module file of " + input.argument()
                    } else if (input is com.google.devtools.build.lib.skyframe.FileKey) {
                        return@Function "file " + input.argument()
                    } else if (input is FileStateKey) {
                        return@Function "file state " + input.argument()
                    } else {
                        com.google.common.base.Preconditions.checkArgument(input.argument() is com.google.devtools.build.lib.skyframe.BzlLoadValue.Key)
                        return@Function (input.argument() as com.google.devtools.build.lib.skyframe.BzlLoadValue.Key).getLabel()
                            .toString()
                    }
                }
            AbstractLabelCycleReporter.printCycle(
                com.google.common.collect.ImmutableList.< E > copyOf < E ? > (repos),
                cycleMessage,
                printer
            )
            eventHandler.handle(com.google.devtools.build.lib.events.Event.error(null, cycleMessage.toString()))
            // To help debugging, request that the information be printed about where the respective
            // repositories were defined.
            requestRepoDefinitions(eventHandler, repos)
            return true
        } else if (com.google.common.collect.Iterables.any<SkyKey?>(cycle, IS_BZL_LOAD)) {
            val fileLabel: Label? =
                (com.google.common.collect.Iterables.getLast<SkyKey?>(
                    com.google.common.collect.Iterables.filter<SkyKey?>(
                        cycle,
                        IS_BZL_LOAD
                    )
                ) as com.google.devtools.build.lib.skyframe.BzlLoadValue.Key).getLabel()
            val errorMessage: String? =
                java.lang.String.format(
                    "Failed to load .bzl file '%s': possible dependency cycle detected.\n", fileLabel
                )
            eventHandler.handle(com.google.devtools.build.lib.events.Event.error(null, errorMessage))
            return true
        } else if (com.google.common.collect.Iterables.any<SkyKey?>(cycle, IS_PACKAGE_LOOKUP)) {
            val pkg: PackageIdentifier? =
                com.google.common.collect.Iterables.getLast<SkyKey?>(
                    com.google.common.collect.Iterables.filter<SkyKey?>(
                        cycle,
                        IS_PACKAGE_LOOKUP
                    )
                ).argument() as PackageIdentifier?
            eventHandler.handle(
                com.google.devtools.build.lib.events.Event.error(
                    null,
                    java.lang.String.format(
                        "cannot load package '%s': possible dependency cycle detected.\n", pkg
                    )
                )
            )
            return true
        }
        return false
    }

    companion object {
        private val IS_BZL_LOAD: com.google.common.base.Predicate<SkyKey?> =
            SkyFunctions.isSkyFunction(SkyFunctions.BZL_LOAD)

        private val IS_PACKAGE_LOOKUP: com.google.common.base.Predicate<SkyKey?> =
            SkyFunctions.isSkyFunction(SkyFunctions.PACKAGE_LOOKUP)

        private val IS_CONTAINING_PACKAGE: com.google.common.base.Predicate<SkyKey?> =
            SkyFunctions.isSkyFunction(SkyFunctions.CONTAINING_PACKAGE_LOOKUP)

        private val IS_REPOSITORY_DIRECTORY: com.google.common.base.Predicate<SkyKey?> =
            SkyFunctions.isSkyFunction(SkyFunctions.REPOSITORY_DIRECTORY)

        private val IS_REPO_DEFINITION: com.google.common.base.Predicate<SkyKey?> =
            SkyFunctions.isSkyFunction(RepoDefinitionValue.REPO_DEFINITION)

        private val IS_EXTENSION_IMPL: com.google.common.base.Predicate<SkyKey?> =
            SkyFunctions.isSkyFunction(SkyFunctions.SINGLE_EXTENSION_EVAL)

        private val IS_EXTENSION_VALIDATION: com.google.common.base.Predicate<SkyKey?> =
            SkyFunctions.isSkyFunction(SkyFunctions.SINGLE_EXTENSION)

        private val IS_REPO_MAPPING: com.google.common.base.Predicate<SkyKey?> =
            SkyFunctions.isSkyFunction(SkyFunctions.REPOSITORY_MAPPING)

        private val IS_MODULE_EXTENSION_REPO_MAPPING_ENTRIES: com.google.common.base.Predicate<SkyKey?> =
            SkyFunctions.isSkyFunction(SkyFunctions.MODULE_EXTENSION_REPO_MAPPING_ENTRIES)

        private val IS_PACKAGE: com.google.common.base.Predicate<SkyKey?> =
            SkyFunctions.isSkyFunction(SkyFunctions.PACKAGE)

        private val IS_MODULE_RESOLUTION: com.google.common.base.Predicate<SkyKey?> =
            SkyFunctions.isSkyFunction(SkyFunctions.BAZEL_MODULE_RESOLUTION)

        private val IS_DEP_GRAPH: com.google.common.base.Predicate<SkyKey?> =
            SkyFunctions.isSkyFunction(SkyFunctions.BAZEL_DEP_GRAPH)

        private val IS_MODULE_FILE: com.google.common.base.Predicate<SkyKey?> =
            SkyFunctions.isSkyFunction(SkyFunctions.MODULE_FILE)

        private val IS_FILE: com.google.common.base.Predicate<SkyKey?> = SkyFunctions.isSkyFunction(SkyFunctions.FILE)

        private val IS_FILE_STATE: com.google.common.base.Predicate<SkyKey?> =
            SkyFunctions.isSkyFunction(FileStateKey.FILE_STATE)

        private fun requestRepoDefinitions(
            eventHandler: ExtendedEventHandler, repos: Iterable<SkyKey>
        ) {
            for (repo in repos) {
                if (repo is RepositoryDirectoryValue.Key) {
                    eventHandler.post(
                        RequestRepositoryInformationEvent(
                            (repo as RepositoryDirectoryValue.Key).argument().name
                        )
                    )
                }
            }
        }
    }
}
