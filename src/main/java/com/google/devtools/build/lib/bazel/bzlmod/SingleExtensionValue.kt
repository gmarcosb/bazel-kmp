/**
 * The result of evaluating a single module extension (see [SingleExtensionEvalFunction]).
 * 
 * @param generatedRepoSpecs Returns the repos generated by the extension. The key is the "internal
 * name" (as specified by the extension) of the repo, and the value is the repo specs that
 * defins the repository.
 * @param canonicalRepoNameToInternalNames Returns the mapping from the canonical repo names of the
 * repos generated by this extension to their "internal name" (as specified by the extension).
 * @param lockFileInfo Returns the information stored about the extension in the lockfile. Non-empty
 * if and only if the lockfile mode is UPDATE.
 * @param fixup Returns the buildozer fixup for incorrect use_repo declarations by the root module
 * (if any).
 * @param facts Returns the facts about the extension, which can be used to generate the
 */
@AutoCodec(explicitlyAllowClass = [com.google.devtools.build.lib.packages.Package::class])
class SingleExtensionValue(
    generatedRepoSpecs: com.google.common.collect.ImmutableMap<String?, RepoSpec?>?,
    canonicalRepoNameToInternalNames: com.google.common.collect.ImmutableBiMap<RepositoryName?, String?>?,
    lockFileInfo: java.util.Optional<WithFactors?>?,
    fixup: java.util.Optional<RootModuleFileFixup?>?,
    facts: Facts?,
    val factsVersion: Int
) : SkyValue {
    /**
     * The [SkyKey] of a [SingleExtensionValue] containing the result of extension
     * evaluation.
     */
    @AutoCodec
    class Key private constructor(arg: ModuleExtensionId?) : AbstractSkyKey<ModuleExtensionId?>(arg) {
        override fun functionName(): SkyFunctionName {
            return SkyFunctions.SINGLE_EXTENSION
        }

        override fun getSkyKeyInterner(): SkyKeyInterner<Key?> {
            return com.google.devtools.build.lib.bazel.bzlmod.SingleExtensionValue.Key.Companion.interner
        }

        companion object {
            private val interner: SkyKeyInterner<Key?> = SkyKey.newInterner<Key?>()

            private fun create(arg: ModuleExtensionId?): Key? {
                return com.google.devtools.build.lib.bazel.bzlmod.SingleExtensionValue.Key.Companion.interner.intern(
                    com.google.devtools.build.lib.bazel.bzlmod.SingleExtensionValue.Key(
                        arg
                    )
                )
            }

            @com.google.devtools.build.lib.skyframe.serialization.VisibleForSerialization
            @AutoCodec.Interner
            fun intern(key: Key?): Key? {
                return com.google.devtools.build.lib.bazel.bzlmod.SingleExtensionValue.Key.Companion.interner.intern(key)
            }
        }
    }

    /**
     * The [SkyKey] of an [SingleExtensionValue] containing the **unvalidated** result
     * of extension evaluation.
     */
    @AutoCodec
    internal class EvalKey private constructor(arg: ModuleExtensionId?) : AbstractSkyKey<ModuleExtensionId?>(arg) {
        override fun functionName(): SkyFunctionName {
            return SkyFunctions.SINGLE_EXTENSION_EVAL
        }

        override fun getSkyKeyInterner(): SkyKeyInterner<EvalKey?> {
            return interner
        }

        companion object {
            private val interner: SkyKeyInterner<EvalKey?> = SkyKey.newInterner<EvalKey?>()

            private fun create(arg: ModuleExtensionId?): EvalKey? {
                return interner.intern(EvalKey(arg))
            }

            @com.google.devtools.build.lib.skyframe.serialization.VisibleForSerialization
            @AutoCodec.Interner
            fun intern(key: EvalKey?): EvalKey? {
                return interner.intern(key)
            }
        }
    }

    val generatedRepoSpecs: com.google.common.collect.ImmutableMap<String?, RepoSpec?>?
    val canonicalRepoNameToInternalNames: com.google.common.collect.ImmutableBiMap<RepositoryName?, String?>?
    val lockFileInfo: java.util.Optional<WithFactors?>?
    val fixup: java.util.Optional<RootModuleFileFixup?>?
    val facts: Facts?

    init {
        this.facts = facts
        this.fixup = fixup
        this.lockFileInfo = lockFileInfo
        this.canonicalRepoNameToInternalNames = canonicalRepoNameToInternalNames
        this.generatedRepoSpecs = generatedRepoSpecs
        java.util.Objects.requireNonNull<com.google.common.collect.ImmutableMap<String?, RepoSpec?>?>(
            generatedRepoSpecs,
            "generatedRepoSpecs"
        )
        java.util.Objects.requireNonNull<com.google.common.collect.ImmutableBiMap<RepositoryName?, String?>?>(
            canonicalRepoNameToInternalNames,
            "canonicalRepoNameToInternalNames"
        )
        java.util.Objects.requireNonNull<java.util.Optional<WithFactors?>?>(lockFileInfo, "lockFileInfo")
        java.util.Objects.requireNonNull<java.util.Optional<RootModuleFileFixup?>?>(fixup, "fixup")
        Facts > java.util.Objects.requireNonNull<Facts?>(facts, "facts")
    }

    companion object {
        fun key(id: ModuleExtensionId?): Key? {
            return com.google.devtools.build.lib.bazel.bzlmod.SingleExtensionValue.Key.Companion.create(id)
        }

        /**
         * Returns the canonical repo name for a repo generated by an extension. All names in [ ][.canonicalRepoNameToInternalNames] follow this format.
         */
        fun repositoryName(extensionUniqueName: String?, internalName: String?): RepositoryName? {
            return RepositoryName.createUnvalidated(extensionUniqueName + "+" + internalName)
        }

        /**
         * Provides access to [SingleExtensionValue] without validating the imports for the
         * repositories generated by the extension. This is only meant for special applications such as
         * `bazel mod tidy`.
         */
        fun evalKey(id: ModuleExtensionId?): EvalKey? {
            return EvalKey.Companion.create(id)
        }
    }
}
