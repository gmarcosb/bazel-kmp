package com.google.devtools.build.lib.skyframe

import com.google.devtools.build.lib.bazel.bzlmod.Version

/**
 * A [SkyValue] that wraps a [RepositoryMapping].
 * 
 * @param repositoryMapping The actual repo mapping. Will be null if the requested repo doesn't
 * exist.
 * @param associatedModuleName Returns the name of the Bzlmod module associated with the requested
 * repo. For repos generated by module extensions, this is the name of the module hosting the
 * extension.
 * @param associatedModuleVersion Returns the version of the Bzlmod module associated with the
 * requested repo. For repos generated by module extensions, this is the version of the module
 * hosting the extension.
 */
@AutoCodec
class RepositoryMappingValue(
    repositoryMapping: RepositoryMapping?,
    associatedModuleName: java.util.Optional<String?>?,
    associatedModuleVersion: java.util.Optional<String?>?
) : SkyValue {
    /**
     * Replaces the inner [repository mapping][.repositoryMapping] with one returned by calling
     * its [RepositoryMapping.withAdditionalMappings] method.
     */
    fun withAdditionalMappings(repoMapping: RepositoryMapping?): RepositoryMappingValue {
        return RepositoryMappingValue(
            repositoryMapping.withAdditionalMappings(repoMapping),
            associatedModuleName,
            associatedModuleVersion
        )
    }

    /**
     * Replaces the inner [repository mapping][.repositoryMapping] with one returned by calling
     * its [RepositoryMapping.withCachedInverseMap] method.
     */
    fun withCachedInverseMap(): RepositoryMappingValue {
        return RepositoryMappingValue(
            this.repositoryMapping.withCachedInverseMap(),
            this.associatedModuleName,
            this.associatedModuleVersion
        )
    }

    /** [SkyKey] for [RepositoryMappingValue].  */ // TODO: b/331765692 - migrate to a record once autocodec supports it.
    @AutoValue
    abstract class Key : SkyKey {
        /** The name of the repo to grab mappings for.  */
        abstract fun repoName(): RepositoryName?

        override fun functionName(): SkyFunctionName {
            return SkyFunctions.REPOSITORY_MAPPING
        }

        val skyKeyInterner: SkyKeyInterner<Key?>
            get() = com.google.devtools.build.lib.skyframe.RepositoryMappingValue.Key.Companion.interner

        companion object {
            private val interner: SkyKeyInterner<Key?> = SkyKey.newInterner<Key?>()

            fun create(repoName: RepositoryName?): Key {
                return com.google.devtools.build.lib.skyframe.RepositoryMappingValue.Key.Companion.interner.intern(
                    AutoValue_RepositoryMappingValue_Key(repoName)
                )
            }

            @com.google.devtools.build.lib.skyframe.serialization.VisibleForSerialization
            @AutoCodec.Interner
            fun intern(key: Key?): Key {
                return com.google.devtools.build.lib.skyframe.RepositoryMappingValue.Key.Companion.interner.intern(key)
            }
        }
    }

    /**
     * Exception thrown where the RepositoryMappingValue is requested and its computation fails for
     * any reason.
     */
    class RepositoryMappingResolutionException : java.lang.Exception {
        private val detailedExitCode: DetailedExitCode

        constructor(detailedExitCode: DetailedExitCode) : super(
            java.lang.String.format(
                "Error computing the main repository mapping: %s",
                detailedExitCode.getFailureDetail().getMessage()
            )
        ) {
            this.detailedExitCode = detailedExitCode
        }

        constructor(detailedExitCode: DetailedExitCode, cause: Throwable?) : super(
            java.lang.String.format(
                "Error computing the main repository mapping: %s",
                detailedExitCode.getFailureDetail().getMessage()
            ),
            cause
        ) {
            this.detailedExitCode = detailedExitCode
        }

        val exitCode: ExitCode?
            get() = detailedExitCode.getExitCode()

        fun getDetailedExitCode(): DetailedExitCode {
            return detailedExitCode
        }
    }

    val repositoryMapping: RepositoryMapping?
    val associatedModuleName: java.util.Optional<String?>?
    val associatedModuleVersion: java.util.Optional<String?>?

    init {
        this.associatedModuleVersion = associatedModuleVersion
        this.associatedModuleName = associatedModuleName
        this.repositoryMapping = repositoryMapping
        java.util.Objects.requireNonNull<java.util.Optional<String?>?>(associatedModuleName, "associatedModuleName")
        java.util.Objects.requireNonNull<java.util.Optional<String?>?>(
            associatedModuleVersion,
            "associatedModuleVersion"
        )
    }

    companion object {
        @kotlin.jvm.JvmField
        val VALUE_FOR_EMPTY_ROOT_MODULE: RepositoryMappingValue = create(RepositoryMapping.EMPTY, "", Version.EMPTY)

        val NOT_FOUND_VALUE: RepositoryMappingValue = createSpecial(null)

        val DEFAULT_VALUE_FOR_BUILTINS_REPO: RepositoryMappingValue = createSpecial(
            RepositoryMapping.create(
                com.google.common.collect.ImmutableMap.of<K?, V?>(
                    RepositoryName.BUILTINS.name,
                    RepositoryName.BUILTINS,
                    "",
                    RepositoryName.MAIN
                ),
                RepositoryName.BUILTINS
            )
        )

        fun create(
            repositoryMapping: RepositoryMapping?,
            associatedModuleName: String,
            associatedModuleVersion: Version
        ): RepositoryMappingValue {
            return RepositoryMappingValue(
                repositoryMapping,
                java.util.Optional.of<String?>(associatedModuleName),
                java.util.Optional.of<T?>(associatedModuleVersion.getNormalized())
            )
        }

        /**
         * Returns a [RepositoryMappingValue] for certain special repos with no associated module
         * (for example `@_builtins`).
         */
        fun createSpecial(repositoryMapping: RepositoryMapping?): RepositoryMappingValue {
            return RepositoryMappingValue(
                repositoryMapping,
                java.util.Optional.empty<String?>(),
                java.util.Optional.empty<String?>()
            )
        }

        /** Returns the [Key] for [RepositoryMappingValue]s.  */
        fun key(repositoryName: RepositoryName?): Key {
            return com.google.devtools.build.lib.skyframe.RepositoryMappingValue.Key.Companion.create(repositoryName)
        }
    }
}
