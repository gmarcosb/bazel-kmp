package com.google.devtools.build.lib.packages

import com.google.devtools.build.lib.cmdline.Label

/**
 * An instance of a build rule in the build language. A rule has a name, a package to which it
 * belongs, a class such as `cc_library`, and set of typed attributes. The set of
 * attribute names and types is a property of the rule's class. The use of the term "class" here has
 * nothing to do with Java classes. All rules are implemented by the same Java classes, Rule and
 * RuleClass.
 * 
 * 
 * Here is a typical rule as it appears in a BUILD file:
 * 
 * <pre>
 * cc_library(name = 'foo',
 * defines = ['-Dkey=value'],
 * srcs = ['foo.cc'],
 * deps = ['bar'])
</pre> * 
 */
// Non-final only for mocking in tests. Do not subclass!
class Rule internal constructor(
    pkg: Packageoid?,
    label: Label?,
    ruleClass: RuleClass,
    location: net.starlark.java.syntax.Location?,
    interiorCallStack: CallStack.Node?
) : RuleOrMacroInstance(label, ruleClass.getAttributeProvider().getAttributeCount()),
    com.google.devtools.build.lib.packages.Target {
    private val pkg: Packageoid
    private val ruleClass: RuleClass
    private val location: net.starlark.java.syntax.Location
    private val interiorCallStack: CallStack.Node?

    /**
     * Output files generated by this rule.
     * 
     * 
     * To save memory, this field is either [.NO_OUTPUTS] for zero outputs, an [ ] for a single output, or an `OutputFile[]` for multiple outputs.
     * 
     * 
     * In the case of multiple outputs, all implicit outputs come before any explicit outputs in
     * the array.
     * 
     * 
     * The order of the implicit outputs is the same as returned by the implicit output function.
     * This allows a native rule implementation and native implicit outputs function to agree on the
     * index of a given kind of output. The order of explicit outputs preserves the attribute
     * iteration order and the order of values in a list attribute; the latter is important so that
     * `ctx.outputs.some_list` has a well-defined order.
     */
    // Initialized by populateOutputFilesInternal().
    private var outputFiles: Any? = null

    init {
        this.pkg = com.google.common.base.Preconditions.checkNotNull<Packageoid>(pkg)
        this.ruleClass = com.google.common.base.Preconditions.checkNotNull<RuleClass>(ruleClass)
        this.location = com.google.common.base.Preconditions.checkNotNull<net.starlark.java.syntax.Location>(location)
        this.interiorCallStack = interiorCallStack
    }

    override fun getPackageoid(): Packageoid {
        return pkg
    }

    override fun getPackageMetadata(): com.google.devtools.build.lib.packages.Package.Metadata? {
        return pkg.getMetadata()
    }

    override fun getPackageDeclarations(): Declarations? {
        return pkg.getDeclarations()
    }

    /**
     * Implements [RuleOrMacroClass.getDeclaringMacro] using [Target.getDeclaringMacro].
     * 
     * 
     * This method cannot be called for rules in deserialized packages.
     */
    override fun getDeclaringMacro(): MacroInstance? {
        return super<com.google.devtools.build.lib.packages.Target>.getDeclaringMacro()
    }

    fun getRuleClassObject(): RuleClass {
        return ruleClass
    }

    override fun getTargetKind(): String? {
        return ruleClass.getTargetKind()
    }

    /** Returns the class of this rule. (e.g. "cc_library")  */
    override fun getRuleClass(): String? {
        return ruleClass.getName()
    }

    /**
     * Returns true iff the outputs of this rule should be created beneath the bin directory, false if
     * beneath genfiles. For most rule classes, this is constant, but for genrule, it is a property of
     * the individual target, derived from the 'output_to_bindir' attribute.
     */
    fun outputsToBindir(): Boolean {
        return if (ruleClass.getName() == "genrule" // this is unfortunate...
        )
            NonconfigurableAttributeMapper.Companion.of(this)
                .get<Boolean?>("output_to_bindir", com.google.devtools.build.lib.packages.Type.Companion.BOOLEAN)
        else
            ruleClass.outputsToBindir()
    }

    /** Returns true if this rule is an analysis test (set by analysis_test = true).  */
    fun isAnalysisTest(): Boolean {
        return ruleClass.isAnalysisTest()
    }

    /**
     * Returns true if this rule has at least one attribute with an analysis test transition. (A
     * starlark-defined transition using analysis_test_transition()).
     */
    fun hasAnalysisTestTransition(): Boolean {
        return ruleClass.hasAnalysisTestTransition()
    }

    fun isBuildSetting(): Boolean {
        return ruleClass.getBuildSetting() != null
    }

    /**
     * Returns true if this rule is in error.
     * 
     * 
     * Examples of rule errors include attributes with missing values or values of the wrong type.
     * 
     * 
     * Any error in a package means that all rules in the package are considered to be in error
     * (even if they were evaluated prior to the error). This policy is arguably stricter than need
     * be, but stopping a build only for some errors but not others creates user confusion.
     */
    fun containsErrors(): Boolean {
        return pkg.containsErrors()
    }

    fun hasAspects(): Boolean {
        return ruleClass.hasAspects()
    }

    /**
     * Returns true if the given attribute is configurable.
     */
    fun isConfigurableAttribute(attributeName: String?): Boolean {
        // TODO(murali): This method should be property of ruleclass not rule instance.
        // Further, this call to AbstractAttributeMapper.isConfigurable is delegated right back
        // to this instance!
        return com.google.devtools.build.lib.packages.AbstractAttributeMapper.Companion.isConfigurable(
            this,
            attributeName
        )
    }

    /**
     * Returns the attribute definition whose name is `attrName`, or null if not found. (Use
     * get[X]Attr for the actual value.)
     * 
     */
    @Deprecated("use {@link AbstractAttributeMapper#getAttributeDefinition} instead")
    fun getAttributeDefinition(attrName: String?): com.google.devtools.build.lib.packages.Attribute? {
        return ruleClass.getAttributeProvider().getAttributeByNameMaybe(attrName)
    }

    /**
     * Constructs and returns an immutable list containing all the declared output files of this rule.
     * 
     * 
     * There are two kinds of outputs. Explicit outputs are declared in attributes of type OUTPUT
     * or OUTPUT_LABEL. Implicit outputs are determined by custom rule logic in an "implicit outputs
     * function" (either defined natively or in Starlark), and are named following a template pattern
     * based on the target's attributes.
     * 
     * 
     * All implicit output files (declared in the [RuleClass]) are listed first, followed by
     * any explicit files (declared via output attributes). Additionally, both implicit and explicit
     * outputs will retain the relative order in which they were declared.
     */
    fun getOutputFiles(): com.google.common.collect.ImmutableList<OutputFile?> {
        return com.google.common.collect.ImmutableList.copyOf<OutputFile?>(outputFilesArray())
    }

    /**
     * Constructs and returns an immutable list of all the implicit output files of this rule, in the
     * order they were declared.
     */
    fun getImplicitOutputFiles(): com.google.common.collect.ImmutableList<OutputFile?> {
        val result: com.google.common.collect.ImmutableList.Builder<OutputFile?> =
            com.google.common.collect.ImmutableList.builder<OutputFile?>()
        for (output in outputFilesArray()!!) {
            if (!output.isImplicit()) {
                break
            }
            result.add(output)
        }
        return result.build()
    }

    /**
     * Constructs and returns an immutable multimap of the explicit outputs, from attribute name to
     * associated value.
     * 
     * 
     * Keys are listed in the same order as attributes. Order of attribute values (outputs in an
     * output list) is preserved.
     * 
     * 
     * Since this is a multimap, attributes that have no associated outputs are omitted from the
     * result.
     */
    fun getExplicitOutputFileMap(): com.google.common.collect.ImmutableListMultimap<String?, OutputFile?> {
        val result: com.google.common.collect.ImmutableListMultimap.Builder<String?, OutputFile?> =
            com.google.common.collect.ImmutableListMultimap.builder<String?, OutputFile?>()
        for (output in outputFilesArray()!!) {
            if (!output.isImplicit()) {
                result.put(output.getOutputKey(), output)
            }
        }
        return result.build()
    }

    /**
     * Returns a map of the Starlark-defined implicit outputs, from dict key to output file.
     * 
     * 
     * If there is no implicit outputs function, or it is a native one, an empty map is returned.
     * 
     * 
     * This is not a multimap because Starlark-defined implicit output functions return exactly one
     * output per key.
     */
    fun getStarlarkImplicitOutputFileMap(): com.google.common.collect.ImmutableMap<String?, OutputFile?> {
        if (ruleClass.getDefaultImplicitOutputsFunction()
                    !is StarlarkImplicitOutputsFunction
        ) {
            return com.google.common.collect.ImmutableMap.of<String?, OutputFile?>()
        }
        val result: com.google.common.collect.ImmutableMap.Builder<String?, OutputFile?> =
            com.google.common.collect.ImmutableMap.builder<String?, OutputFile?>()
        for (output in outputFilesArray()!!) {
            if (!output.isImplicit()) {
                break
            }
            result.put(output.getOutputKey(), output)
        }
        return result.buildOrThrow()
    }

    private fun outputFilesArray(): Array<OutputFile>? {
        return if (outputFiles is OutputFile)
            arrayOf<OutputFile>(outputFiles)
        else
            outputFiles as Array<OutputFile?>?
    }

    override fun getLocation(): net.starlark.java.syntax.Location {
        return location
    }

    /**
     * Returns the stack of function calls active when this rule was instantiated.
     * 
     * 
     * Requires reconstructing the call stack from a compact representation, so should only be
     * called when the full call stack is needed.
     */
    // TODO(https://github.com/bazelbuild/bazel/issues/26128): Avoid new uses of this method; it is
    // hostile to change pruning for lazy macro expansion. Replace with a method that takes a context
    // argument which provides ancestor symbolic macros.
    fun reconstructCallStack(): com.google.common.collect.ImmutableList<net.starlark.java.eval.StarlarkThread.CallStackEntry?> {
        val stack: com.google.common.collect.ImmutableList.Builder<net.starlark.java.eval.StarlarkThread.CallStackEntry?> =
            com.google.common.collect.ImmutableList.builder<net.starlark.java.eval.StarlarkThread.CallStackEntry?>()
        stack.add(
            net.starlark.java.eval.StarlarkThread.callStackEntry(
                net.starlark.java.eval.StarlarkThread.TOP_LEVEL,
                location
            )
        )
        var node: CallStack.Node? = interiorCallStack
        while (node != null) {
            stack.add(node.toCallStackEntry())
            node = node.next()
        }
        return stack.build()
    }

    fun getInteriorCallStack(): CallStack.Node? {
        return interiorCallStack
    }

    override fun getAssociatedRule(): Rule? {
        return this
    }

    /**
     * ****************************************************************** Attribute accessor
     * functions.
     * 
     * 
     * The below provide access to attribute definitions and other generic metadata.
     * 
     * 
     * For access to attribute *values* (e.g. "What's the value of attribute X for Rule Y?"), go
     * through [RuleContext.attributes]. If no RuleContext is available, create a localized
     * [AbstractAttributeMapper] instance instead.
     * ******************************************************************
     */
    private fun getRelativeLocation(): String? {
        // Determining the workspace root only works reliably if both location and label point to files
        // in the same package.
        // It would be preferable to construct the path from the label itself, but this doesn't work for
        // rules created from function calls in a subincluded file, even if both files share a path
        // prefix (for example, when //a/package:BUILD subincludes //a/package/with/a/subpackage:BUILD).
        // We can revert to that approach once subincludes aren't supported anymore.
        //
        // TODO(b/151165647): this logic has always been wrong:
        // it spuriously matches occurrences of the package name earlier in the path.
        val absolutePath = location.toString()
        val pos: Int = absolutePath.indexOf(label.getPackageName())
        return if (pos < 0) null else absolutePath.substring(pos)
    }

    /**
     * Returns the value of the attribute with the given index. Returns null, if no such attribute
     * exists OR no value was set.
     */
    override fun getAttrWithIndex(attrIndex: Int): Any? {
        val value: Any? = getAttrIfStored(attrIndex)
        if (value != null) {
            return value
        }
        val attr: com.google.devtools.build.lib.packages.Attribute =
            ruleClass.getAttributeProvider().getAttribute(attrIndex)
        if (attr.hasComputedDefault()) {
            // Frozen rules don't store computed defaults, so get it from the attribute. Mutable rules do
            // store computed defaults if they've been populated. If no value is stored for a mutable
            // rule, return null here since resolving the default could trigger reads of other attributes
            // which have not yet been populated. Note that in this situation returning null does not
            // result in a correctness issue, since the value for the attribute is actually a function to
            // compute the value.
            return if (isFrozen()) attr.getDefaultValue(this) else null
        }
        if (attr.isMaterializing()) {
            com.google.common.base.Preconditions.checkState(isFrozen(), "Mutable rule missing LateBoundDefault")
            return attr.getMaterializer()
        }
        if (attr.isLateBound()) {
            // Frozen rules don't store late bound defaults.
            com.google.common.base.Preconditions.checkState(isFrozen(), "Mutable rule missing LateBoundDefault")
            return attr.getLateBoundDefault()
        }
        return when (attr.getName()) {
            RuleOrMacroInstance.Companion.GENERATOR_FUNCTION -> if (interiorCallStack != null) interiorCallStack.functionName() else ""
            RuleOrMacroInstance.Companion.GENERATOR_LOCATION -> if (interiorCallStack != null) getRelativeLocation() else ""
            RuleOrMacroInstance.Companion.GENERATOR_NAME -> if (generatorNamePrefixLength > 0) getName().substring(
                0,
                generatorNamePrefixLength
            ) else ""

            else -> attr.getDefaultValue(this)
        }
    }

    override fun isRuleInstance(): Boolean {
        return true
    }

    override fun isRuleCreatedInMacro(): Boolean {
        // TODO(bazel-team): do we really need the `hasStringAttribute(GENERATOR_NAME)` check?
        return interiorCallStack != null || hasStringAttribute(RuleOrMacroInstance.Companion.GENERATOR_NAME)
    }

    /** Returns the macro that generated this rule, or an empty string.  */
    fun getGeneratorFunction(): String {
        val value: Any? = getAttr(RuleOrMacroInstance.Companion.GENERATOR_FUNCTION)
        if (value is String) {
            return value
        }
        return ""
    }

    private fun hasStringAttribute(attrName: String): Boolean {
        val value: Any? = getAttr(attrName)
        if (value is String) {
            return !value.isEmpty()
        }
        return false
    }

    /**
     * Returns a new list containing all direct dependencies (all types except outputs and nodeps).
     */
    fun getLabels(): MutableList<Label?> {
        val labels: MutableList<Label?> = java.util.ArrayList<Label?>()
        AggregatingAttributeMapper.Companion.of(this)
            .visitAllLabels(java.util.function.BiConsumer { attribute: com.google.devtools.build.lib.packages.Attribute?, label: Label? ->
                labels.add(label)
            })
        return labels
    }

    /**
     * Returns a sorted set containing all labels that match a given [DependencyFilter], not
     * including outputs.
     * 
     * @param filter A dependency filter that determines whether a label should be included in the
     * result. [DependencyFilter.test] is called with this rule and the attribute that
     * contains the label. The label will be contained in the result iff the predicate returns
     * `true` *and* the label is not an output.
     */
    fun getSortedLabels(filter: DependencyFilter?): com.google.common.collect.ImmutableSortedSet<Label?> {
        val labels: com.google.common.collect.ImmutableSortedSet.Builder<Label?> =
            com.google.common.collect.ImmutableSortedSet.naturalOrder<Label?>()
        AggregatingAttributeMapper.Companion.of(this)
            .visitLabels(
                filter,
                java.util.function.BiConsumer { attribute: com.google.devtools.build.lib.packages.Attribute?, label: Label? ->
                    labels.add(label)
                })
        return labels.build()
    }

    /**
     * Returns a [SetMultimap] containing all non-output labels matching a given [ ], keyed by the corresponding attribute.
     * 
     * 
     * Labels that appear in multiple attributes will be mapped from each of their corresponding
     * attributes, provided they pass the [DependencyFilter].
     * 
     * @param filter A dependency filter that determines whether a label should be included in the
     * result. [DependencyFilter.test] is called with this rule and the attribute that
     * contains the label. The label will be contained in the result iff the predicate returns
     * `true` *and* the label is not an output.
     */
    fun getTransitions(filter: DependencyFilter?): com.google.common.collect.SetMultimap<com.google.devtools.build.lib.packages.Attribute?, Label?> {
        val transitions: com.google.common.collect.SetMultimap<com.google.devtools.build.lib.packages.Attribute?, Label?> =
            com.google.common.collect.HashMultimap.create<com.google.devtools.build.lib.packages.Attribute?, Label?>()
        AggregatingAttributeMapper.Companion.of(this).visitLabels(
            filter,
            java.util.function.BiConsumer { key: com.google.devtools.build.lib.packages.Attribute?, value: Label? ->
                transitions.put(
                    key,
                    value
                )
            })
        return transitions
    }

    /**
     * Collects the output files (both implicit and explicit). Must be called before the output
     * accessors methods can be used, and must be called only once.
     */
    @Throws(LabelSyntaxException::class, java.lang.InterruptedException::class)
    fun populateOutputFiles(eventHandler: EventHandler, pkgId: PackageIdentifier?) {
        populateOutputFilesInternal(
            eventHandler,
            pkgId,
            ruleClass.getDefaultImplicitOutputsFunction(),  /* checkLabels= */
            true
        )
    }

    @Throws(java.lang.InterruptedException::class)
    fun populateOutputFilesUnchecked(
        targetDefinitionContext: TargetDefinitionContext,
        implicitOutputsFunction: ImplicitOutputsFunction
    ) {
        try {
            populateOutputFilesInternal(
                NullEventHandler.INSTANCE,
                targetDefinitionContext.getPackageIdentifier(),
                implicitOutputsFunction,  /* checkLabels= */
                false
            )
        } catch (e: LabelSyntaxException) {
            throw java.lang.IllegalStateException(e)
        }
    }

    private fun interface ExplicitOutputHandler {
        @Throws(LabelSyntaxException::class)
        fun accept(attribute: com.google.devtools.build.lib.packages.Attribute?, outputLabel: Label?)
    }

    private fun interface ImplicitOutputHandler {
        fun accept(outputKey: String?, outputName: String?)
    }

    @Throws(LabelSyntaxException::class, java.lang.InterruptedException::class)
    private fun populateOutputFilesInternal(
        eventHandler: EventHandler,
        pkgId: PackageIdentifier?,
        implicitOutputsFunction: ImplicitOutputsFunction,
        checkLabels: Boolean
    ) {
        com.google.common.base.Preconditions.checkState(outputFiles == null)

        val outputs: MutableList<OutputFile?> = java.util.ArrayList<OutputFile?>()
        // Detects collisions where the same output key is used for both an explicit and implicit entry.
        val implicitOutputKeys: HashSet<String?> = HashSet<String?>()

        // We need the implicits to appear before the explicits in the final data structure, so we
        // process them first. We check for duplicates while handling the explicits.
        //
        // Each of these cases has two subcases, so we factor their bodies out into lambdas.
        val implicitOutputHandler =  // outputKey: associated dict key if Starlark-defined, empty string otherwise
            // outputName: package-relative path fragment
            ImplicitOutputHandler { outputKey: String?, outputName: String? ->
                val label: Label
                if (checkLabels) { // controls label syntax validation only
                    try {
                        label = Label.create(pkgId, outputName)
                    } catch (e: LabelSyntaxException) {
                        reportError(
                            java.lang.String.format(
                                "illegal output file name '%s' in rule %s due to: %s",
                                outputName, this.label, e.getMessage()
                            ),
                            eventHandler
                        )
                        return@ImplicitOutputHandler
                    }
                } else {
                    label = Label.createUnvalidated(pkgId, outputName)
                }
                validateOutputLabel(label, eventHandler)

                outputs.add(OutputFile.Companion.createImplicit(label, this, outputKey))
                implicitOutputKeys.add(outputKey)
            }

        // Populate the implicit outputs.
        try {
            val attributeMap: RawAttributeMapper = RawAttributeMapper.Companion.of(this)
            // TODO(bazel-team): Reconsider the ImplicitOutputsFunction abstraction. It doesn't seem to be
            // a good fit if it forces us to downcast in situations like this. It also causes
            // getImplicitOutputs() to declare that it throws EvalException (which then has to be
            // explicitly disclaimed by the subclass SafeImplicitOutputsFunction).
            if (implicitOutputsFunction is StarlarkImplicitOutputsFunction) {
                for (e in (implicitOutputsFunction as StarlarkImplicitOutputsFunction)
                    .calculateOutputs(eventHandler, attributeMap)
                    .entrySet()) {
                    implicitOutputHandler.accept(e.getKey(), e.getValue())
                }
            } else {
                for (out in implicitOutputsFunction.getImplicitOutputs(eventHandler, attributeMap)) {
                    implicitOutputHandler.accept( /*outputKey=*/"", out)
                }
            }
        } catch (e: net.starlark.java.eval.EvalException) {
            reportError(java.lang.String.format("In rule %s: %s", label, e.getMessageWithStack()), eventHandler)
        }

        val explicitOutputHandler =
            ExplicitOutputHandler { attribute: com.google.devtools.build.lib.packages.Attribute?, outputLabel: Label? ->
                val attrName: String? = attribute.getName()
                if (implicitOutputKeys.contains(attrName)) {
                    reportError(
                        java.lang.String.format(
                            "Implicit output key '%s' collides with output attribute name", attrName
                        ),
                        eventHandler
                    )
                }
                if (checkLabels) {
                    check(outputLabel.getPackageIdentifier().equals(pkg.getPackageIdentifier())) {
                        java.lang.String.format(
                            "Label for attribute %s should refer to '%s' but instead refers to '%s'"
                                    + " (label '%s')",
                            attribute,
                            pkg.getMetadata().getName(),
                            outputLabel.getPackageFragment(),
                            outputLabel.name
                        )
                    }
                    if (outputLabel.name.equals(".")) {
                        throw LabelSyntaxException("output file name can't be equal '.'")
                    }
                }
                validateOutputLabel(outputLabel, eventHandler)
                outputs.add(OutputFile.Companion.createExplicit(outputLabel, this, attrName))
            }

        // Populate the explicit outputs.
        val nonConfigurableAttributes: NonconfigurableAttributeMapper =
            NonconfigurableAttributeMapper.Companion.of(this)
        for (attribute in ruleClass.getAttributeProvider().getAttributes()) {
            val name: String? = attribute.getName()
            val type: com.google.devtools.build.lib.packages.Type<*> = attribute.getType()
            if (type === BuildType.OUTPUT) {
                val label: Label? = nonConfigurableAttributes.get<Label?>(name, BuildType.OUTPUT)
                if (label != null) {
                    explicitOutputHandler.accept(attribute, label)
                }
            } else if (type === BuildType.OUTPUT_LIST) {
                for (label in nonConfigurableAttributes.get<MutableList<Label?>?>(name, BuildType.OUTPUT_LIST)) {
                    explicitOutputHandler.accept(attribute, label)
                }
            }
        }

        if (outputs.isEmpty()) {
            outputFiles = com.google.devtools.build.lib.packages.Rule.Companion.NO_OUTPUTS
        } else if (outputs.size() == 1) {
            outputFiles = outputs.get(0)
        } else {
            outputFiles = outputs.toArray<OutputFile?>(java.util.function.IntFunction { _Dummy_.__Array__() })
        }
    }

    private fun validateOutputLabel(label: Label, eventHandler: EventHandler) {
        if (label.name.equals(getName())) {
            // TODO(bazel-team): for now (23 Apr 2008) this is just a warning.  After
            // June 1st we should make it an error.
            reportWarning(
                ("target '" + getName() + "' is both a rule and a file; please choose "
                        + "another name for the rule"), eventHandler
            )
        }
    }

    /**
     * Marks the rule's package or package piece as in error, and propagates the error message to the
     * reporter.
     * 
     * 
     * This method may only be called while the rule's package or package piece is being
     * constructed.
     */
    override fun reportError(message: String?, eventHandler: EventHandler) {
        eventHandler.handle(
            com.google.devtools.build.lib.packages.Package.Companion.error(
                location,
                message,
                PackageLoading.Code.STARLARK_EVAL_ERROR
            )
        )
        pkg.setContainsErrors()
    }

    private fun reportWarning(message: String?, eventHandler: EventHandler) {
        eventHandler.handle(Event.warn(location, message))
    }

    /** Returns a string of the form "cc_binary rule //foo:foo"  */
    override fun toString(): String {
        return getRuleClass() + " rule " + label
    }

    /**
     * Implementation of [.getRawVisibility] that avoids constructing a `RuleVisibility`.
     */
    private fun getRawVisibilityLabels(): MutableList<Label?>? {
        val visibilityIndex: Int? = ruleClass.getAttributeProvider().getAttributeIndex("visibility")
        if (visibilityIndex == null) {
            return null
        }
        return getAttrIfStored(visibilityIndex) as MutableList<Label?>?
    }

    override fun getRawVisibility(): RuleVisibility? {
        val rawLabels: MutableList<Label?>? = getRawVisibilityLabels()
        // The attribute value was already validated when it was set, so call the unchecked method.
        return if (rawLabels != null) RuleVisibility.Companion.parseUnchecked(rawLabels) else null
    }

    /**
     * Retrieves the package's default visibility, or for certain rule classes, injects a different
     * default visibility.
     */
    override fun getDefaultVisibility(): RuleVisibility? {
        if (ruleClass.getName() == "bind") {
            return RuleVisibility.Companion.PUBLIC // bind rules are always public.
        }
        // Temporary logic to relax config_setting's visibility enforcement while depot migrations set
        // visibility settings properly (legacy code may have visibility settings that would break if
        // enforced). See https://github.com/bazelbuild/bazel/issues/12669. Ultimately this entire
        // conditional should be removed.
        if (ruleClass.getName() == "config_setting"
            && (pkg.getMetadata().configSettingVisibilityPolicy
                    == ConfigSettingVisibilityPolicy.DEFAULT_PUBLIC)
        ) {
            return RuleVisibility.Companion.PUBLIC // Default: //visibility:public.
        }

        return super<com.google.devtools.build.lib.packages.Target>.getDefaultVisibility()
    }

    override fun getVisibilityDependencyLabels(): Iterable<Label?>? {
        val rawLabels: MutableList<Label?>? = getRawVisibilityLabels()
        if (rawLabels == null) {
            return getDefaultVisibility().getDependencyLabels()
        }
        val constantVisibility: RuleVisibility? = RuleVisibility.Companion.parseIfConstant(rawLabels)
        if (constantVisibility != null) {
            return constantVisibility.getDependencyLabels()
        }
        // Filter out labels like :__pkg__ and :__subpackages__.
        return com.google.common.collect.Iterables.filter<Label?>(
            rawLabels,
            com.google.common.base.Predicate { label: Label? -> PackageSpecification.Companion.fromLabel(label) == null })
    }


