    override fun getLicense(): License? {
        // New style licenses defined by Starlark rules don't
        // have old-style licenses. This is hardcoding the representation
        // of new-style rules, but it's in the old-style licensing code path
        // and will ultimately be removed.
        if (ruleClass.isPackageMetadataRule()) {
            return License.Companion.NO_LICENSE
        } else if (isAttrDefined("licenses", BuildType.LICENSE)
            && isAttributeValueExplicitlySpecified("licenses")
        ) {
            return NonconfigurableAttributeMapper.Companion.of(this).get<License?>("licenses", BuildType.LICENSE)
        } else if (ruleClass.ignoreLicenses()) {
            return License.Companion.NO_LICENSE
        } else {
            return getPackageDeclarations().getPackageArgs().license()
        }
    }

    /** Returns the Set of all tags exhibited by this target. May be empty.  */
    override fun getRuleTags(): MutableSet<String?> {
        val ruleTags: MutableSet<String?> = LinkedHashSet<String?>()
        for (attribute in ruleClass.getAttributeProvider().getAttributes()) {
            if (attribute.isTaggable()) {
                val attrType: com.google.devtools.build.lib.packages.Type<*> = attribute.getType()
                val name: String? = attribute.getName()
                // This enforces the expectation that taggable attributes are non-configurable.
                val value: Any? = NonconfigurableAttributeMapper.Companion.of(this).get(name, attrType)
                val tags: MutableSet<String?>? = attrType.toTagSet(value, name)
                ruleTags.addAll(tags!!)
            }
        }
        return ruleTags
    }

    /** Returns only the `tags` attribute value.  */
    override fun getOnlyTagsAttribute(): com.google.common.collect.ImmutableList<String?>? {
        val tagsAttribute: com.google.devtools.build.lib.packages.Attribute? =
            ruleClass.getAttributeProvider().getAttributeByName("tags")
        if (tagsAttribute == null) {
            return com.google.common.collect.ImmutableList.of<String?>()
        }
        val attrType: com.google.devtools.build.lib.packages.Type<*> = tagsAttribute.getType()
        val name: String? = tagsAttribute.getName()
        // This enforces the expectation that taggable attributes are non-configurable.
        val value: Any? = NonconfigurableAttributeMapper.Companion.of(this).get(name, attrType)
        return com.google.common.collect.ImmutableList.copyOf<String?>(attrType.toTagSet(value, name))
    }

