    /**
     * Computes labels of additional dependencies that can be provided by aspects that this rule can
     * require from its direct dependencies.
     */
    fun getAspectLabelsSuperset(predicate: DependencyFilter?): MutableCollection<Label?> {
        if (!hasAspects()) {
            return com.google.common.collect.ImmutableList.of<Label?>()
        }
        val labels: com.google.common.collect.SetMultimap<com.google.devtools.build.lib.packages.Attribute?, Label?> =
            com.google.common.collect.LinkedHashMultimap.create<com.google.devtools.build.lib.packages.Attribute?, Label?>()
        for (attribute in this.getAttributes()) {
            for (candidateClass in attribute.getAspects(this)) {
                AspectDefinition.Companion.addAllAttributesOfAspect(labels, candidateClass, predicate)
            }
        }
        return labels.values()
    }

    /**
     * Should this rule instance resolve toolchains?
     * 
     * 
     * This may happen for two reasons:
     * 
     * 
     *  1. The rule uses toolchains by definition ([       ][RuleClass.Builder.toolchainResolutionMode]
     *  1. The rule instance has a select() or target_compatible_with attribute, which means it may
     * depend on target platform properties that are only provided when toolchain resolution is
     * enabled.
     * 
     */
    fun useToolchainResolution(): Boolean {
        return ruleClass.useToolchainResolution(this)
    }

    fun isExecutable(): Boolean {
        if (getRuleClassObject()
                .getAttributeProvider()
                .hasAttr(
                    com.google.devtools.build.lib.packages.Rule.Companion.IS_EXECUTABLE_ATTRIBUTE_NAME,
                    com.google.devtools.build.lib.packages.Type.Companion.BOOLEAN
                )
        ) {
            return NonconfigurableAttributeMapper.Companion.of(this)
                .get<Boolean?>(
                    com.google.devtools.build.lib.packages.Rule.Companion.IS_EXECUTABLE_ATTRIBUTE_NAME,
                    com.google.devtools.build.lib.packages.Type.Companion.BOOLEAN
                )
        }
        return false
    }

