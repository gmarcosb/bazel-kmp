package com.google.devtools.build.lib.skyframe

import com.google.devtools.build.lib.analysis.BlazeDirectories

/** Common utilities for dealing with paths outside the package roots.  */
class ExternalFilesHelper private constructor(
    pkgLocator: AtomicReference<PathPackageLocator>,
    externalFileAction: ExternalFileAction?,
    directories: BlazeDirectories,
    repoContentsCachePathSupplier: java.util.function.Supplier<com.google.devtools.build.lib.vfs.Path?>,
    maxNumExternalFilesToLog: Int
) {
    private val pkgLocator: AtomicReference<PathPackageLocator>
    private val externalFileAction: ExternalFileAction?
    private val directories: BlazeDirectories
    private val maxNumExternalFilesToLog: Int
    private val repoContentsCachePathSupplier: java.util.function.Supplier<com.google.devtools.build.lib.vfs.Path?>
    private val numExternalFilesLogged: AtomicInteger = AtomicInteger(0)

    // These variables are set to true from multiple threads, but only read in the main thread.
    // So volatility or an AtomicBoolean is not needed.
    private var anyOutputFilesSeen = false
    private var tooManyExternalOtherFilesSeen = false
    private var anyFilesInExternalReposSeen = false

    // This is the set of EXTERNAL_OTHER files.
    private var externalOtherFilesSeen: MutableSet<RootedPath?> =
        com.google.common.collect.Sets.newConcurrentHashSet<RootedPath?>()

    init {
        this.pkgLocator = pkgLocator
        this.externalFileAction = externalFileAction
        this.directories = directories
        this.repoContentsCachePathSupplier = repoContentsCachePathSupplier
        this.maxNumExternalFilesToLog = maxNumExternalFilesToLog
    }

    /**
     * The action to take when an external path is encountered. See [FileType] for the
     * definition of "external".
     */
    enum class ExternalFileAction {
        /**
         * For paths of type [FileType.EXTERNAL_REPO], introduce a Skyframe dependency on the
         * 'external' package.
         * 
         * 
         * This is the default for Bazel, since it's required for correctness of the external
         * repositories feature.
         */
        DEPEND_ON_EXTERNAL_PKG_FOR_EXTERNAL_REPO_PATHS,

        /**
         * For paths of type [FileType.EXTERNAL_OTHER] or [FileType.OUTPUT], assume the path
         * does not exist and will never exist.
         */
        ASSUME_NON_EXISTENT_AND_IMMUTABLE_FOR_EXTERNAL_PATHS,
    }

    /** Classification of a path encountered by Bazel.  */
    enum class FileType {
        /**
         * A path to a file located inside of Bazel, e.g. the bundled builtins_bzl root (for `--experimental_builtins_bzl_root=%bundled%`) that live in an InMemoryFileSystem. These files
         * must not change throughout the lifetime of the server.
         */
        BUNDLED,

        /** A path inside the package roots.  */
        INTERNAL,

        /**
         * A path in Bazel's output tree that's a proper output of an action (*not* a source file in an
         * external repository). Such files are theoretically mutable, but certain Bazel flags may tell
         * Bazel to assume these paths are immutable.
         * 
         * 
         * Note that [ExternalFilesHelper.maybeHandleExternalFile] is only used for [ ] and [DirectoryListingStateValue],
         * and also note that output files do not normally have corresponding [ ] instances (and thus also [ ] instances) in the Skyframe graph
         * ([ArtifactFunction] only uses [com.google.devtools.build.lib.actions.FileValue]s
         * for source files). But [com.google.devtools.build.lib.actions.FileStateValue]s for
         * output files can still make their way into the Skyframe graph if e.g. a source file is a
         * symlink to an output file.
         */
        // TODO(nharmata): Consider an alternative design where we have an OutputFileDiffAwareness. This
        // could work but would first require that we clean up all RootedPath usage.
        OUTPUT,

        /**
         * A path in the part of Bazel's output tree that contains (/ symlinks to) to external
         * repositories. Every such path under the external repository is generated by the execution of
         * the corresponding repository rule, so these paths should not be cached by Skyframe before the
         * RepositoryDirectoryValue is computed.
         */
        EXTERNAL_REPO,

        /**
         * The directory containing the repo contents cache entries as well as direct children
         * corresponding to individual predeclared input hashes. These directories are created by Bazel
         * but may be deleted when users delete the entire repo contents cache. However, they are always
         * recreated by Bazel before they are used and/or depended on via Skyframe. They are thus
         * immutably present from the perspective of Skyframe and don't require invalidation.
         * 
         * 
         * Note: If these directories ever need to be checked for dirtiness during diffing, they have
         * to be made non-cacheable according to [ ][DirtinessCheckerUtils.ExternalDirtinessChecker.isCacheableType] so that they are not locked
         * in as non-existent if they have been removed. This would result in FileValues for files below
         * them (the actual repo contents, of type EXTERNAL_OTHER) being locked in as non-existent too,
         * even after a refetch of the repo has added a new cache entry.
         */
        REPO_CONTENTS_CACHE_DIRS,

        /**
         * None of the above. We encounter these paths when outputs, source files or external repos
         * symlink to files outside aforementioned Bazel-managed directories. For example, C compilation
         * by the host compiler may depend on /usr/bin/gcc. Bazel makes a best-effort attempt to detect
         * changes in such files. This type also includes files in repo contents cache entries, which
         * are created by Bazel but never modified after creation.
         */
        EXTERNAL_OTHER,
    }

    /**
     * Thrown by [.maybeHandleExternalFile] when an applicable path is processed (see [ ][ExternalFileAction.ASSUME_NON_EXISTENT_AND_IMMUTABLE_FOR_EXTERNAL_PATHS].
     */
    internal class NonexistentImmutableExternalFileException : java.lang.Exception()

    internal class ExternalFilesKnowledge private constructor(
        val anyOutputFilesSeen: Boolean,
        externalOtherFilesSeen: MutableSet<RootedPath?>,
        anyFilesInExternalReposSeen: Boolean,
        tooManyExternalOtherFilesSeen: Boolean
    ) {
        val externalOtherFilesSeen: MutableSet<RootedPath?>
        val anyFilesInExternalReposSeen: Boolean
        val tooManyExternalOtherFilesSeen: Boolean

        init {
            this.externalOtherFilesSeen = externalOtherFilesSeen
            this.anyFilesInExternalReposSeen = anyFilesInExternalReposSeen
            this.tooManyExternalOtherFilesSeen = tooManyExternalOtherFilesSeen
        }
    }

    @get:ThreadCompatible
    @set:ThreadCompatible
    var externalFilesKnowledge: ExternalFilesKnowledge
        get() = ExternalFilesKnowledge(
            anyOutputFilesSeen,
            externalOtherFilesSeen,
            anyFilesInExternalReposSeen,
            tooManyExternalOtherFilesSeen
        )
        set(externalFilesKnowledge) {
            anyOutputFilesSeen = externalFilesKnowledge.anyOutputFilesSeen
            externalOtherFilesSeen = externalFilesKnowledge.externalOtherFilesSeen
            anyFilesInExternalReposSeen = externalFilesKnowledge.anyFilesInExternalReposSeen
            tooManyExternalOtherFilesSeen = externalFilesKnowledge.tooManyExternalOtherFilesSeen
        }

    fun cloneWithFreshExternalFilesKnowledge(): ExternalFilesHelper {
        return ExternalFilesHelper(
            pkgLocator,
            externalFileAction,
            directories,
            repoContentsCachePathSupplier,
            maxNumExternalFilesToLog
        )
    }

    fun getAndNoteFileType(rootedPath: RootedPath): FileType {
        val fileType = detectFileType(rootedPath)
        if (fileType == com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.EXTERNAL_OTHER) {
            if (externalOtherFilesSeen.size() >= MAX_EXTERNAL_FILES_TO_TRACK) {
                tooManyExternalOtherFilesSeen = true
            } else {
                externalOtherFilesSeen.add(rootedPath)
            }
        }
        if (com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.EXTERNAL_REPO == fileType) {
            anyFilesInExternalReposSeen = true
        }
        if (com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.OUTPUT == fileType) {
            anyOutputFilesSeen = true
        }
        return fileType
    }

    /**
     * Returns the classification of a path, and updates this instance's state regarding what kinds of
     * paths have been seen.
     */
    private fun detectFileType(rootedPath: RootedPath): FileType {
        if (rootedPath.getRoot().getFileSystem() is BundledFileSystem) {
            return com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.BUNDLED
        }
        val packageLocator: PathPackageLocator = pkgLocator.get()
        if (packageLocator.getPathEntries().contains(rootedPath.getRoot())) {
            return com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.INTERNAL
        }
        val repoContentsCachePath: com.google.devtools.build.lib.vfs.Path? = repoContentsCachePathSupplier.get()
        if (repoContentsCachePath != null && rootedPath.asPath().startsWith(repoContentsCachePath)
            && !rootedPath.asPath().relativeTo(repoContentsCachePath).isMultiSegment()
        ) {
            return com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.REPO_CONTENTS_CACHE_DIRS
        }
        // The outputBase may be null if we're not actually running a build.
        val outputBase: com.google.devtools.build.lib.vfs.Path? = packageLocator.getOutputBase()
        if (outputBase == null) {
            return com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.EXTERNAL_OTHER
        }
        if (rootedPath.asPath().startsWith(outputBase)) {
            val externalRepoDir: com.google.devtools.build.lib.vfs.Path =
                outputBase.getRelative(LabelConstants.EXTERNAL_REPOSITORY_LOCATION)
            if (rootedPath.asPath().startsWith(externalRepoDir)) {
                return com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.EXTERNAL_REPO
            } else {
                return com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.OUTPUT
            }
        }
        return com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.EXTERNAL_OTHER
    }

    /**
     * If this instance is configured with [ ][ExternalFileAction.DEPEND_ON_EXTERNAL_PKG_FOR_EXTERNAL_REPO_PATHS] and `rootedPath` isn't
     * under a package root then this adds a dependency on the //external package. If the action is
     * [ExternalFileAction.ASSUME_NON_EXISTENT_AND_IMMUTABLE_FOR_EXTERNAL_PATHS], it will throw
     * a [NonexistentImmutableExternalFileException] instead.
     */
    @com.google.devtools.build.lib.concurrent.ThreadSafety.ThreadSafe
    @Throws(NonexistentImmutableExternalFileException::class, IOException::class, java.lang.InterruptedException::class)
    fun maybeHandleExternalFile(rootedPath: RootedPath, env: SkyFunction.Environment): FileType {
        val fileType: FileType =
            com.google.common.base.Preconditions.checkNotNull<FileType>(getAndNoteFileType(rootedPath))
        when (fileType) {
            com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.BUNDLED, com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.INTERNAL, com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.REPO_CONTENTS_CACHE_DIRS -> {}
            com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.EXTERNAL_OTHER -> {
                if (numExternalFilesLogged.incrementAndGet() < maxNumExternalFilesToLog) {
                    logger.atInfo().log("Encountered an external path %s", rootedPath)
                }
                if (externalFileAction
                    == ExternalFileAction.ASSUME_NON_EXISTENT_AND_IMMUTABLE_FOR_EXTERNAL_PATHS
                ) {
                    throw NonexistentImmutableExternalFileException()
                }
            }

            com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.OUTPUT -> if (externalFileAction
                == ExternalFileAction.ASSUME_NON_EXISTENT_AND_IMMUTABLE_FOR_EXTERNAL_PATHS
            ) {
                throw NonexistentImmutableExternalFileException()
            }

            com.google.devtools.build.lib.skyframe.ExternalFilesHelper.FileType.EXTERNAL_REPO -> {
                com.google.common.base.Preconditions.checkState(
                    externalFileAction == ExternalFileAction.DEPEND_ON_EXTERNAL_PKG_FOR_EXTERNAL_REPO_PATHS,
                    externalFileAction
                )
                addExternalFilesDependencies(rootedPath, env)
            }
        }
        return fileType
    }

    /**
     * For files that are under $OUTPUT_BASE/external, add a dependency on the corresponding repo so
     * that if the repo is refetched, the {File,DirectoryListing}StateValue's of files underneath will
     * be re-evaluated.
     * 
     * 
     * Note that we don't add a dependency on the parent directory at the package root boundary, so
     * the only transitive dependencies from files inside the package roots to external files are
     * through symlinks. So the upwards transitive closure of external files is small.
     */
    @Throws(java.lang.InterruptedException::class)
    private fun addExternalFilesDependencies(rootedPath: RootedPath, env: SkyFunction.Environment) {
        val repositoryName: RepositoryName? = getExternalRepoName(rootedPath)
        if (repositoryName != null) {
            env.getValue(RepositoryDirectoryValue.key(repositoryName))
        }
    }

    /**
     * For a file of type [FileType.EXTERNAL_REPO], returns the name of the external repository
     * it is in or null if the path is not in a valid external repository.
     */
    fun getExternalRepoName(rootedPath: RootedPath): RepositoryName? {
        val repositoryPath: PathFragment = rootedPath.asPath().relativeTo(this.externalDirectory)
        if (repositoryPath.isEmpty()) {
            // We are the top of the repository path (<outputBase>/external), not in an actual external
            // repository path.
            return null
        }
        try {
            return RepositoryName.create(repositoryPath.getSegment(0))
        } catch (ignored: LabelSyntaxException) {
            // The directory of a repository with an invalid name can never exist.
            return null
        }
    }

    fun getExtraKeysToInvalidate(
        dirtyExternalRepos: MutableMap<RepositoryName?, RootedPath?>, eventHandler: ExtendedEventHandler
    ): Iterable<SkyKey?> {
        dirtyExternalRepos.forEach(
            java.util.function.BiConsumer { repoName: RepositoryName?, file: RootedPath? ->
                eventHandler.handle(
                    com.google.devtools.build.lib.events.Event.warn(
                        """
                  Repository '%s' will be fetched again since the file '%s' has been modified externally. External modifications can lead to incorrect builds.
                  """
                            .trimIndent()
                            .formatted(repoName, file.getRootRelativePath())
                    )
                )
                // Delete the marker file so that invalidating the RepositoryDirectoryValue actually
                // causes a re-fetch of the repository.
                try {
                    this.externalDirectory.getRelative(repoName.getMarkerFileName()).delete()
                } catch (e: IOException) {
                    // Any failure to delete the file should also make it non-readable, so we still achieve
                    // our goal of forcing a re-fetch of the repository.
                }
            })
        return com.google.common.collect.Iterables.transform<RepositoryName?, SkyKey?>(
            dirtyExternalRepos.keySet(),
            RepositoryDirectoryValue::key
        )
    }

    private val externalDirectory: com.google.devtools.build.lib.vfs.Path
        get() = directories.getOutputBase().getRelative(LabelConstants.EXTERNAL_REPOSITORY_LOCATION)

    companion object {
        private val logger: GoogleLogger = GoogleLogger.forEnclosingClass()

        private const val MAX_EXTERNAL_FILES_TO_TRACK = 2500

        fun create(
            pkgLocator: AtomicReference<PathPackageLocator>,
            externalFileAction: ExternalFileAction?,
            directories: BlazeDirectories,
            repoContentsCachePathSupplier: java.util.function.Supplier<com.google.devtools.build.lib.vfs.Path?>
        ): ExternalFilesHelper {
            return if (TestType.isInTest())
                createForTesting(
                    pkgLocator, externalFileAction, directories, repoContentsCachePathSupplier
                )
            else
                ExternalFilesHelper(
                    pkgLocator,
                    externalFileAction,
                    directories,
                    repoContentsCachePathSupplier,  /* maxNumExternalFilesToLog= */
                    100
                )
        }

        fun createForTesting(
            pkgLocator: AtomicReference<PathPackageLocator>,
            externalFileAction: ExternalFileAction?,
            directories: BlazeDirectories
        ): ExternalFilesHelper {
            return createForTesting(
                pkgLocator,
                externalFileAction,
                directories,  /* repoContentsCachePathSupplier= */
                java.util.function.Supplier { null })
        }

        fun createForTesting(
            pkgLocator: AtomicReference<PathPackageLocator>,
            externalFileAction: ExternalFileAction?,
            directories: BlazeDirectories,
            repoContentsCachePathSupplier: java.util.function.Supplier<com.google.devtools.build.lib.vfs.Path?>
        ): ExternalFilesHelper {
            return ExternalFilesHelper(
                pkgLocator,
                externalFileAction,
                directories,
                repoContentsCachePathSupplier,  // These log lines are mostly spam during unit and integration tests.
                /* maxNumExternalFilesToLog= */
                0
            )
        }
    }
}
