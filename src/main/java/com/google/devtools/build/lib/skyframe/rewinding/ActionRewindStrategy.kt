package com.google.devtools.build.lib.skyframe.rewinding

import com.google.devtools.build.lib.actions.Action

/**
 * Given an action that failed to execute because of lost inputs which were generated by other
 * actions, finds the actions which generated them and the set of Skyframe nodes which must be
 * rewound in order to recreate the lost inputs.
 */
class ActionRewindStrategy(
    skyframeActionExecutor: SkyframeActionExecutor?,
    bugReporter: BugReporter?,
    cachingDependenciesSupplier: java.util.function.Supplier<RemoteAnalysisCacheReaderDepsProvider?>
) {
    private val skyframeActionExecutor: SkyframeActionExecutor
    private val bugReporter: BugReporter

    private var currentBuildLostInputRecords: MutableMap<SkyKey?, com.google.common.collect.Multiset<LostInputRecord?>> =
        ConcurrentHashMap<SkyKey?, com.google.common.collect.Multiset<LostInputRecord?>>()
    private val lostInputsCount: AtomicInteger = AtomicInteger()
    private val lostOutputsCount: AtomicInteger = AtomicInteger()
    private val sameActionLostInputsCount: AtomicInteger = AtomicInteger()
    private val sameTopLevelKeyLostOutputsCount: AtomicInteger = AtomicInteger()

    private val rewindEventSamples: MutableList<ActionRewindEvent?> = Collections.synchronizedList<ActionRewindEvent?>(
        java.util.ArrayList<ActionRewindEvent?>(
            MAX_ACTION_REWIND_EVENTS
        )
    )
    private val rewindEventSampleCounter: AtomicInteger = AtomicInteger()

    private val cachingDependenciesSupplier: java.util.function.Supplier<RemoteAnalysisCacheReaderDepsProvider?>

    init {
        this.skyframeActionExecutor =
            com.google.common.base.Preconditions.checkNotNull<SkyframeActionExecutor>(skyframeActionExecutor)
        this.bugReporter = com.google.common.base.Preconditions.checkNotNull<BugReporter>(bugReporter)
        this.cachingDependenciesSupplier = cachingDependenciesSupplier
    }

    /** The result of rewind planning.  */
    class RewindPlanResult private constructor(reset: Reset?) {
        // null if there were missing dependencies
        private val reset: Reset?

        init {
            this.reset = reset
        }

        fun toNullIfMissingDependenciesElseReset(): Reset? {
            return reset
        }
    }

    /**
     * Returns a [RewindPlanResult] specifying the Skyframe nodes to rewind to recreate the lost
     * inputs specified by `lostInputsException`.
     * 
     * 
     * If `#allowSkyframeRestarts` is true, the returned [RewindPlanResult] may return
     * null for [RewindPlanResult.toNullIfMissingDependenciesElseReset] if some dependencies are
     * not yet done. Otherwise, the returned [ ][RewindPlanResult.toNullIfMissingDependenciesElseReset] always returns a [Reset].
     * 
     * 
     * Also prepares [SkyframeActionExecutor] for the rewind plan.
     * 
     * 
     * Lost outputs and their owning expansion artifacts are removed from `builtArtifacts`,
     * as they should not be reported as built.
     * 
     * @throws ActionRewindException if rewinding is disabled, or if any lost outputs have been seen
     * by `failedKey` as lost before too many times
     */
    @Throws(ActionRewindException::class, java.lang.InterruptedException::class)
    fun prepareRewindPlanForLostTopLevelOutputs(
        failedKey: TopLevelActionLookupKeyWrapper,
        failedKeyDeps: MutableSet<SkyKey?>,
        lostOutputsByDigest: com.google.common.collect.ImmutableSetMultimap<String?, ActionInput?>,
        metadataProvider: InputMetadataProvider,
        builtArtifacts: MutableSet<Artifact?>,
        env: SkyFunction.Environment
    ): RewindPlanResult {
        checkRewindingEnabled(lostOutputsByDigest, LostType.OUTPUT, env.getListener())

        val lostRecords: com.google.common.collect.ImmutableList<LostInputRecord> =
            createLostInputRecords(lostOutputsByDigest)

        val owners: com.google.common.collect.SetMultimap<ActionInput?, Artifact> =
            calculateLostInputOwners(lostOutputsByDigest.values(), metadataProvider)

        for (lostOutput in lostOutputsByDigest.values()) {
            builtArtifacts.remove(lostOutput)
            builtArtifacts.removeAll(owners.get(lostOutput))
        }

        val depsToRewind: com.google.common.collect.ImmutableList.Builder<ActionAnalysisMetadata?> =
            com.google.common.collect.ImmutableList.builder<ActionAnalysisMetadata?>()
        val rewindPlanResult: RewindPlanResult
        AutoProfiler.profiled(
            "Preparing rewind plan for %d lost outputs of %s"
                .formatted(lostRecords.size(), failedKey.actionLookupKey().getLabel()),
            ProfilerTask.ACTION_REWINDING
        ).use { ignored ->
            rewindPlanResult =
                prepareRewindPlan(
                    failedKey, failedKeyDeps, lostOutputsByDigest, owners, env, depsToRewind
                )
        }
        val reset: Reset? = rewindPlanResult.reset
        if (reset == null) {
            // Skips steps that manipulate persistent state, structures retained by this class and
            // information tracked by SkyframeActionExecutor, if a restart is needed.
            //
            // This includes counting if an input has been lost too many times.
            return rewindPlanResult
        }

        checkIfTopLevelOutputLostTooManyTimes(failedKey, lostRecords, lostOutputsByDigest)

        if (shouldRecordRewindEventSample()) {
            rewindEventSamples.add(createLostOutputRewindEvent(failedKey, reset, lostRecords))
        }

        for (dep in depsToRewind.build()) {
            skyframeActionExecutor.prepareDepForRewinding(failedKey, dep)
        }

        return rewindPlanResult
    }

    /**
     * Returns a [RewindPlanResult] specifying the Skyframe nodes to rewind to recreate the lost
     * inputs specified by `lostInputsException`.
     * 
     * 
     * If `#allowSkyframeRestarts` is true, the returned [RewindPlanResult] may return
     * null for [RewindPlanResult.toNullIfMissingDependenciesElseReset] if some dependencies are
     * not yet done. Otherwise, the returned [ ][RewindPlanResult.toNullIfMissingDependenciesElseReset] always returns a [Reset].
     * 
     * 
     * Also prepares [SkyframeActionExecutor] for the rewind plan and emits an [ ] if necessary.
     * 
     * @throws ActionRewindException if rewinding is disabled, or if any lost inputs have been seen by
     * `failedKey` as lost before too many times
     */
    @Throws(ActionRewindException::class, java.lang.InterruptedException::class)
    fun prepareRewindPlanForLostInputs(
        failedKey: ActionLookupData?,
        failedAction: Action,
        failedActionDeps: MutableSet<SkyKey?>,
        e: LostInputsActionExecutionException,
        metadataProvider: InputMetadataProvider,
        env: SkyFunction.Environment,
        actionStartTimeNanos: Long
    ): RewindPlanResult {
        val lostInputsByDigest: com.google.common.collect.ImmutableSetMultimap<String?, ActionInput?> =
            e.getLostInputs()
        checkRewindingEnabled(lostInputsByDigest, LostType.INPUT, env.getListener())

        val lostInputRecords: com.google.common.collect.ImmutableList<LostInputRecord> =
            createLostInputRecords(lostInputsByDigest)

        val owners: com.google.common.collect.SetMultimap<ActionInput?, Artifact> =
            calculateLostInputOwners(lostInputsByDigest.values(), metadataProvider)

        val depsToRewind: com.google.common.collect.ImmutableList.Builder<ActionAnalysisMetadata?> =
            com.google.common.collect.ImmutableList.builder<ActionAnalysisMetadata?>()
        val rewindPlanResult: RewindPlanResult
        AutoProfiler.profiled(
            "Preparing rewind plan for %d lost inputs of %s"
                .formatted(lostInputRecords.size(), failedAction.prettyPrint()),
            ProfilerTask.ACTION_REWINDING
        ).use { ignored ->
            rewindPlanResult =
                prepareRewindPlan(
                    failedKey, failedActionDeps, lostInputsByDigest, owners, env, depsToRewind
                )
        }
        val rewindPlan: Reset? = rewindPlanResult.reset
        if (rewindPlan == null) {
            // Skips steps that manipulate persistent state, structures retained by this class and
            // information tracked by SkyframeActionExecutor, if a restart is needed.
            //
            // This includes counting if an input has been lost too many times.
            return rewindPlanResult
        }

        checkIfActionLostInputTooManyTimes(
            failedKey, failedAction, lostInputRecords, lostInputsByDigest
        )

        if (shouldRecordRewindEventSample()) {
            rewindEventSamples.add(
                createLostInputRewindEvent(failedAction, rewindPlan, lostInputRecords)
            )
        }

        if (e.isActionStartedEventAlreadyEmitted()) {
            env.getListener()
                .post(
                    ActionRewoundEvent(
                        actionStartTimeNanos,
                        com.google.devtools.build.lib.clock.BlazeClock.nanoTime(),
                        failedAction
                    )
                )
        }
        skyframeActionExecutor.prepareForRewinding(failedKey, failedAction, depsToRewind.build())

        return rewindPlanResult
    }

    private enum class LostType(description: String, codeWhenDisabled: Code) {
        INPUT("inputs", Code.LOST_INPUT_REWINDING_DISABLED),
        OUTPUT("outputs", Code.LOST_OUTPUT_REWINDING_DISABLED);

        private val description: String?
        private val codeWhenDisabled: Code?

        init {
            this.description = description
            this.codeWhenDisabled = codeWhenDisabled
        }
    }

    @Throws(ActionRewindException::class)
    private fun checkRewindingEnabled(
        lostArtifacts: com.google.common.collect.ImmutableSetMultimap<String?, ActionInput?>,
        lostType: LostType,
        listener: ExtendedEventHandler
    ) {
        if (skyframeActionExecutor.rewindingEnabled()) {
            return
        }
        if (skyframeActionExecutor.invocationRetriesEnabled()) {
            // If rewinding failed, Bazel may still be able to recover by retrying the invocation in
            // BlazeCommandDispatcher if retries are enabled. This requires emitting an event to inform
            // Bazel's remote module of the lost inputs.
            listener.post(LostInputsEvent(lostArtifacts.keySet()))
            throw FallbackToBuildRewindingException(
                lostArtifacts.entries().stream()
                    .limit(MAX_LOST_INPUTS_RECORDED.toLong())
                    .map<String?>(java.util.function.Function { lost: MutableMap.MutableEntry<String?, ActionInput?>? ->
                        "%s (%s)".formatted(
                            Companion.prettyPrint(lost.getValue()), lost.getKey()
                        )
                    })
                    .collect(
                        Collectors.joining(
                            ", ",
                            "Lost %s no longer available remotely: ".formatted(lostType.description),
                            ""
                        )
                    )
            )
        }
        throw GenericActionRewindException(
            "Unexpected lost %s (pass --rewind_lost_inputs to enable recovery): %s"
                .formatted(lostType.description, Companion.prettyPrint(lostArtifacts.values())),
            lostType.codeWhenDisabled
        )
    }

    @Throws(java.lang.InterruptedException::class)
    private fun prepareRewindPlan(
        failedKey: SkyKey?,
        failedKeyDeps: MutableSet<SkyKey?>,
        lostInputsByDigest: com.google.common.collect.ImmutableSetMultimap<String?, ActionInput?>,
        owners: com.google.common.collect.SetMultimap<ActionInput?, Artifact>,
        env: SkyFunction.Environment?,
        depsToRewind: com.google.common.collect.ImmutableList.Builder<ActionAnalysisMetadata?>
    ): RewindPlanResult {
        val lostInputs: com.google.common.collect.ImmutableList<ActionInput?> = lostInputsByDigest.values().asList()

        // This graph tracks which Skyframe nodes must be rewound and the dependency relationships
        // between them.
        val rewindGraph: com.google.common.graph.MutableGraph<SkyKey?> = Reset.newRewindGraphFor(failedKey)

        val lostArtifacts: MutableSet<DerivedArtifact> =
            getLostInputOwningDirectDeps(failedKey, failedKeyDeps, lostInputs, owners)

        // Additional nested sets we may need to invalidate that are the dependencies of an
        // insensitively propagating action, associated with the key that depends on them.
        val nestedSetsForPropagatingActions: com.google.common.collect.SetMultimap<SkyKey?, ArtifactNestedSetKey?> =
            com.google.common.collect.HashMultimap.create<SkyKey?, ArtifactNestedSetKey?>()

        var missingDependencies = false
        for (lostArtifact in lostArtifacts) {
            val actionMap: MutableMap<ActionLookupData?, ActionAnalysisMetadata?>? =
                getActionsForLostArtifact(lostArtifact, env)
            if (actionMap == null) {
                // Some deps of the artifact are not done. If allowSkyframeRestarts() is false, another
                // rewind must be in-flight, and there is no need to rewind the shared deps twice.
                //
                // TODO: b/420979437 - clearly document the scenario above.
                missingDependencies = true
                continue
            }
            val newlyVisitedActions: com.google.common.collect.ImmutableList<ActionAndLookupDataOrTemplate> =
                addArtifactDepsAndGetNewlyVisitedActions(rewindGraph, lostArtifact, actionMap)

            // Note that Artifact.key(lostArtifact) must be rewound. We do this after
            // addArtifactDepsAndGetNewlyVisitedActions so that it can track if actions are already known
            // to be in the graph. It is possible that the Artifact.key() is not actually a direct dep of
            // the action if it is below an ArtifactNestedSetKey, but this edge is benign since it's
            // always a transitive dep.
            rewindGraph.putEdge(failedKey, Artifact.key(lostArtifact))
            depsToRewind.addAll(actionAnalysisMetadatas(newlyVisitedActions))
            when (checkActions(
                newlyVisitedActions, env, rewindGraph, depsToRewind, nestedSetsForPropagatingActions
            )) {
                CheckActionsStatus.SUCCESS -> {}
                CheckActionsStatus.MISSING_DEPENDENCIES -> missingDependencies = true
            }
        }

        // The default behavior, when allowSkyframeRestarts() is false, ignores missing dependencies.
        //
        // TODO: b/420979437 - clearly document why this is okay
        if (missingDependencies && allowSkyframeRestarts()) {
            // When this is reached, the calling SkyFunction will request a restart. It's possible that
            // the restarted SkyFunction won't observe a missing input and instead succeed without
            // rewinding. Then, the resulting deps could include transitive deps that aren't usually
            // present for that function.
            //
            // TODO: b/399637310 - consider using SkyKeyComputeState to avoid this.
            return RewindPlanResult( /* reset= */null)
        }

        // addNestedSetPathsToRewindGraph, called after this loop, stops its walk when it finds a node
        // that is already in the rewind graph.
        // However, because this rewinds all NestedSet chains from a given root, early termination later
        // on won't matter because all dependent NestedSets are already in the graph.
        // This may seem excessive, but it is not expected that many NestedSets are actually involved in
        // this walk, and that this only happens rarely.
        // TODO(b/395634488): This should be solved in a more elegant way, but a solution is needed to
        // unblock the simplifications to Fileset (b/394611260)
        for (rootKey in nestedSetsForPropagatingActions.keySet()) {
            for (nestedSetKey in nestedSetsForPropagatingActions.get(rootKey)) {
                ArtifactNestedSetKey.addNestedSetChainsToRewindGraph(rewindGraph, nestedSetKey)
                rewindGraph.putEdge(rootKey, nestedSetKey)
            }
        }

        // This needs to be done after the loop above because addArtifactDepsAndGetNewlyVisitedActions
        // short-circuits when a node is already in the rewind graph.
        ArtifactNestedSetKey.addNestedSetPathsToRewindGraph(
            rewindGraph, failedKey, failedKeyDeps, lostArtifacts
        )

        return RewindPlanResult(Reset.of(rewindGraph))
    }

    /**
     * Creates a [Reset] to recover from undone indirect inputs that are unavailable due to
     * unsuccessful rewinding.
     * 
     * 
     * Undone direct dependencies are handled by Skyframe (see [ ]). This
     * method only exists for artifacts whose [Artifact.key] is *not* a direct dependency
     * of `failedKey` because the artifact is behind an [ArtifactNestedSetKey].
     * 
     * 
     * Used when an indirect dependency [Artifact.key] was rewound and completed with an
     * error, but intermediate nested set nodes were never rewound, resulting in an inconsistent state
     * where successful nodes depend on a node in error.
     * 
     * 
     * The returned [Reset] contains the [Artifact.key], but that is expected to
     * already be in error, and attempting to rewind an error is no-op.
     */
    fun patchNestedSetGraphToPropagateError(
        failedKey: ActionLookupData?,
        failedAction: Action,
        undoneInputs: com.google.common.collect.ImmutableSet<Artifact?>,
        failedActionDeps: com.google.common.collect.ImmutableSet<SkyKey?>?
    ): Reset {
        com.google.common.base.Preconditions.checkState(
            skyframeActionExecutor.rewindingEnabled(), "Unexpected undone inputs: %s", undoneInputs
        )
        val rewindGraph: com.google.common.graph.MutableGraph<SkyKey?> = Reset.newRewindGraphFor(failedKey)
        ArtifactNestedSetKey.addNestedSetPathsToRewindGraph(
            rewindGraph, failedKey, failedActionDeps, undoneInputs
        )
        for (input in undoneInputs) {
            com.google.common.base.Preconditions.checkState(
                rewindGraph.nodes().contains(Artifact.key(input)),
                "Cannot find input %s under any nested set deps of %s",
                input,
                failedKey
            )
        }

        // An undone input may be observed either during input checking (before attempting action
        // execution) or during lost input handling (after attempting action execution). In the latter
        // case, it is necessary to obsolete the ActionExecutionState so that after rewinding, we will
        // check inputs again and discover the propagated exception. This call is a no-op in the former
        // case, since there is no ActionExecutionState to obsolete.
        skyframeActionExecutor.prepareForRewinding(
            failedKey,
            failedAction,  /* depsToRewind= */
            com.google.common.collect.ImmutableList.of<ActionAnalysisMetadata?>()
        )

        return Reset.of(rewindGraph)
    }

    /**
     * Logs the first N action rewind events and clears the history of failed actions' lost inputs and
     * rewind plans.
     */
    fun reset(eventHandler: ExtendedEventHandler) {
        val rewindingStats: PostableActionRewindingStats =
            PostableActionRewindingStats( /* lostInputsCount= */
                lostInputsCount.getAndSet(0),  /* lostOutputsCount= */
                lostOutputsCount.getAndSet(0),  /* rewoundActionCount= */
                skyframeActionExecutor.getRewoundActionCount(),  /* sameActionLostInputsCount= */
                sameActionLostInputsCount.getAndSet(0),  /* sameTopLevelKeyLostOutputsCount= */
                sameTopLevelKeyLostOutputsCount.getAndSet(0),  /* actionRewindEvents= */
                com.google.common.collect.ImmutableList.copyOf<ActionRewindEvent?>(rewindEventSamples)
            )
        eventHandler.post(rewindingStats)
        currentBuildLostInputRecords =
            ConcurrentHashMap<SkyKey?, com.google.common.collect.Multiset<LostInputRecord?>>()
        rewindEventSamples.clear()
        rewindEventSampleCounter.set(0)
    }

    @Throws(ActionRewindException::class)
    private fun checkIfTopLevelOutputLostTooManyTimes(
        failedKey: TopLevelActionLookupKeyWrapper?,
        currentAttemptLostOutputRecords: com.google.common.collect.ImmutableList<LostInputRecord>,
        lostOutputsByDigest: com.google.common.collect.ImmutableSetMultimap<String?, ActionInput?>
    ) {
        lostOutputsCount.addAndGet(currentAttemptLostOutputRecords.size())

        val historyForThisTopLevelKey: com.google.common.collect.Multiset<LostInputRecord?> =
            currentBuildLostInputRecords.computeIfAbsent(
                failedKey,
                java.util.function.Function { k: SkyKey? -> com.google.common.collect.ConcurrentHashMultiset.create<LostInputRecord?>() })
        if (!historyForThisTopLevelKey.isEmpty()) {
            sameTopLevelKeyLostOutputsCount.incrementAndGet()
        }

        for (lostInputRecord in currentAttemptLostOutputRecords) {
            val digest: String? = lostInputRecord.lostInputDigest
            val losses: Int = historyForThisTopLevelKey.add(lostInputRecord,  /* occurrences= */1) + 1
            if (losses > MAX_REPEATED_LOST_INPUTS) {
                val lostOutput: ActionInput? =
                    com.google.common.collect.Iterables.find<ActionInput?>(
                        lostOutputsByDigest.get(digest),
                        com.google.common.base.Predicate { lost: ActionInput? ->
                            lost.getExecPathString().equals(lostInputRecord.lostInputPath)
                        })
                val e: ActionRewindException =
                    GenericActionRewindException(
                        java.lang.String.format(
                            "Lost output %s (digest %s), and rewinding was ineffective after %d attempts.",
                            Companion.prettyPrint(lostOutput), digest, MAX_REPEATED_LOST_INPUTS
                        ),
                        ActionRewinding.Code.LOST_OUTPUT_TOO_MANY_TIMES
                    )
                bugReporter.sendBugReport(e)
                throw e
            } else if (losses > 1) {
                logger.atWarning().log(
                    "Lost output again (losses=%s, output=%s, digest=%s, failedKey=%s)",
                    losses, lostOutputsByDigest.get(digest), digest, failedKey
                )
            }
        }
    }

    /**
     * Checks if the action identified by `failedKey` has lost any of the inputs in `currentAttemptLostInputRecords` too many times.
     * 
     * @throws ActionRewindException if any lost input has been seen by `failedKey` as lost
     * before too many times
     */
    @Throws(ActionRewindException::class)
    private fun checkIfActionLostInputTooManyTimes(
        failedKey: ActionLookupData?,
        failedAction: Action,
        currentAttemptLostInputRecords: com.google.common.collect.ImmutableList<LostInputRecord>,
        lostInputsByDigest: com.google.common.collect.ImmutableSetMultimap<String?, ActionInput?>
    ) {
        lostInputsCount.addAndGet(currentAttemptLostInputRecords.size())

        val historyForThisAction: com.google.common.collect.Multiset<LostInputRecord?> =
            currentBuildLostInputRecords.computeIfAbsent(
                failedKey,
                java.util.function.Function { k: SkyKey? -> com.google.common.collect.ConcurrentHashMultiset.create<LostInputRecord?>() })
        if (!historyForThisAction.isEmpty()) {
            sameActionLostInputsCount.incrementAndGet()
        }

        for (lostInputRecord in currentAttemptLostInputRecords) {
            // The same action losing the same input more than once is unexpected [*]. The action should
            // have waited until the depended-on action which generates the lost input is (re)run before
            // trying again.
            //
            // Note that we could enforce a stronger check: if action A, which depends on an input N
            // previously detected as lost (by any action, not just A), discovers that N is still lost,
            // and action A started after the re-evaluation of N's generating action, then something has
            // gone wrong. Administering that check would be more complex (e.g., the start/completion
            // times of actions would need tracking), so we punt on it for now.
            //
            // [*], TODO(b/123993876): To mitigate a race condition (believed to be) caused by
            // non-topological Skyframe dirtying of depended-on nodes, this check fails the build only if
            // the same input is repeatedly lost.
            val digest: String? = lostInputRecord.lostInputDigest
            val losses: Int = historyForThisAction.add(lostInputRecord,  /* occurrences= */1) + 1
            if (losses > MAX_REPEATED_LOST_INPUTS) {
                // This ensures coalesced shared actions aren't orphaned.
                skyframeActionExecutor.prepareForRewinding(
                    failedKey,
                    failedAction,  /* depsToRewind= */
                    com.google.common.collect.ImmutableList.of<ActionAnalysisMetadata?>()
                )
                val lostInput: ActionInput? =
                    com.google.common.collect.Iterables.find<ActionInput?>(
                        lostInputsByDigest.get(digest),
                        com.google.common.base.Predicate { lost: ActionInput? ->
                            lost.getExecPathString().equals(lostInputRecord.lostInputPath)
                        })
                val message: String? =
                    java.lang.String.format(
                        "lost input too many times (#%s) for the same action. lostInput: %s, "
                                + "lostInput digest: %s, failedAction: %.10000s",
                        losses, lostInput, digest, failedAction
                    )
                val e: ActionRewindException =
                    GenericActionRewindException(
                        message, ActionRewinding.Code.LOST_INPUT_TOO_MANY_TIMES
                    )
                bugReporter.sendBugReport(e)
                throw e
            } else if (losses > 1) {
                logger.atInfo().log(
                    "lost input again (#%s) for the same action. lostInput: %s, "
                            + "lostInput digest: %s, failedAction: %.10000s",
                    losses, lostInputsByDigest.get(digest), digest, failedAction
                )
            }
        }
    }

    private fun getLostInputOwningDirectDeps(
        failedKey: SkyKey?,
        failedKeyDeps: MutableSet<SkyKey?>,
        lostInputs: com.google.common.collect.ImmutableList<ActionInput?>,
        owners: com.google.common.collect.SetMultimap<ActionInput?, Artifact>
    ): MutableSet<DerivedArtifact> {
        // Not all input artifacts' keys are direct deps - they may be below an ArtifactNestedSetKey.
        // Expand all ArtifactNestedSetKey deps to get a flat set with all input artifact keys.
        val expandedDeps: MutableSet<SkyKey?> = HashSet<SkyKey?>()
        for (dep in failedKeyDeps) {
            if (dep is ArtifactNestedSetKey) {
                expandedDeps.addAll(Artifact.keys(dep.expandToArtifacts()))
            } else {
                expandedDeps.add(dep)
            }
        }

        val lostInputOwningDirectDeps: MutableSet<DerivedArtifact> = HashSet<DerivedArtifact>()
        for (lostInput in lostInputs) {
            var foundLostInputDepOwner = false

            val directOwners: MutableSet<Artifact> = owners.get(lostInput)
            for (directOwner in directOwners) {
                checkDerived(directOwner)

                // Rewinding must invalidate all Skyframe paths from the failed action to the action which
                // generates the lost input. Intermediate nodes not on the shortest path to that action may
                // have values that depend on the output of that action. If these intermediate nodes are not
                // invalidated, then their values may become stale. Therefore, this method collects not only
                // the first action dep associated with the lost input, but all of them.
                val transitiveOwners: MutableSet<Artifact> = owners.get(directOwner)
                for (transitiveOwner in transitiveOwners) {
                    checkDerived(transitiveOwner)

                    if (expandedDeps.contains(Artifact.key(transitiveOwner))) {
                        // The lost input is included in an aggregation artifact (e.g. a tree artifact or
                        // fileset) that is included by an aggregation artifact (e.g. a runfiles tree) that the
                        // action directly depends on.
                        lostInputOwningDirectDeps.add(transitiveOwner as DerivedArtifact?)
                        foundLostInputDepOwner = true
                    }
                }

                if (expandedDeps.contains(Artifact.key(directOwner))) {
                    // The lost input is included in an aggregation artifact (e.g. a tree artifact, fileset,
                    // or runfiles tree) that the action directly depends on.
                    lostInputOwningDirectDeps.add(directOwner as DerivedArtifact?)
                    foundLostInputDepOwner = true
                }
            }

            if (lostInput is Artifact && expandedDeps.contains(Artifact.key(lostInput))) {
                checkDerived(lostInput)

                lostInputOwningDirectDeps.add(lostInput as DerivedArtifact?)
                foundLostInputDepOwner = true
            }

            if (!foundLostInputDepOwner) {
                // Rewinding can't do anything about a lost input that can't be associated with a direct dep
                // of the failed action. In this case, try resetting the failed action (and no other deps)
                // just in case that helps. If it does not help, then eventually the action will fail in
                // checkIfActionLostInputTooManyTimes.
                bugReporter.sendNonFatalBugReport(
                    java.lang.IllegalStateException(
                        java.lang.String.format(
                            "Lost input not a dep of the failed action and can't be associated with such"
                                    + " a dep. lostInput: %s, owners: %s, failedKey: %s",
                            lostInput, owners, failedKey
                        )
                    )
                )
            }
        }
        return lostInputOwningDirectDeps
    }

    private enum class CheckActionsStatus {
        MISSING_DEPENDENCIES,
        SUCCESS
    }

    /**
     * Looks at each action in `actionsToCheck` and determines whether additional artifacts or
     * actions need to be rewound. If this finds more actions to rewind, those actions are recursively
     * checked too.
     */
    @Throws(java.lang.InterruptedException::class)
    private fun checkActions(
        actionsToCheck: com.google.common.collect.ImmutableList<ActionAndLookupDataOrTemplate>,
        env: SkyFunction.Environment?,
        rewindGraph: com.google.common.graph.MutableGraph<SkyKey?>,
        depsToRewind: com.google.common.collect.ImmutableList.Builder<ActionAnalysisMetadata?>,
        nestedSetDeps: com.google.common.collect.SetMultimap<SkyKey?, ArtifactNestedSetKey?>
    ): CheckActionsStatus {
        var missingDependencies = false
        val uncheckedActions: ArrayDeque<ActionAndLookupData> = ArrayDeque<ActionAndLookupData>(actionsToCheck.size())
        filterActionAndLookupDataTo(actionsToCheck, uncheckedActions)
        while (!uncheckedActions.isEmpty()) {
            val actionAndLookupData: ActionAndLookupData = uncheckedActions.removeFirst()
            val actionKey: ActionLookupData? = actionAndLookupData.lookupData
            val action: Action = actionAndLookupData.actionAnalysisMetadata
            val artifactsToCheck: java.util.ArrayList<DerivedArtifact> = java.util.ArrayList<DerivedArtifact>()
            val newlyDiscoveredActions: java.util.ArrayList<ActionLookupData?> =
                java.util.ArrayList<ActionLookupData?>()

            if (action.mayInsensitivelyPropagateInputs()) {
                // Rewinding this action won't recreate the missing input. We need to also rewind this
                // action's non-source inputs and the actions which created those inputs.
                addPropagatingActionDepsAndGetNewlyVisitedArtifactsAndActions(
                    rewindGraph,
                    actionKey,
                    action,
                    artifactsToCheck,
                    newlyDiscoveredActions,
                    nestedSetDeps
                )
            }

            for (actionLookupData in newlyDiscoveredActions) {
                val additionalAction: Action? =
                    ActionUtils.getActionForLookupData(
                        env, actionLookupData,  /* crashIfActionOwnerMissing= */!allowSkyframeRestarts()
                    )
                if (additionalAction == null) {
                    missingDependencies = true
                    continue
                }
                depsToRewind.add(additionalAction)
                uncheckedActions.add(ActionAndLookupData(actionLookupData, additionalAction))
            }
            for (artifact in artifactsToCheck) {
                val actionMap: MutableMap<ActionLookupData?, ActionAnalysisMetadata?>? =
                    getActionsForLostArtifact(artifact, env)
                if (actionMap == null) {
                    missingDependencies = true
                    continue
                }
                val newlyVisitedActions: com.google.common.collect.ImmutableList<ActionAndLookupDataOrTemplate> =
                    addArtifactDepsAndGetNewlyVisitedActions(rewindGraph, artifact, actionMap)
                depsToRewind.addAll(actionAnalysisMetadatas(newlyVisitedActions))
                filterActionAndLookupDataTo(newlyVisitedActions, uncheckedActions)
            }
        }
        return if (missingDependencies)
            CheckActionsStatus.MISSING_DEPENDENCIES
        else
            CheckActionsStatus.SUCCESS
    }

    /**
     * For a propagating `action` with key `actionKey`, add its generated inputs' keys to
     * `rewindGraph`, add edges from `actionKey` to those keys, add any [Artifact]s
     * to `newlyVisitedArtifacts`, and add any [ActionLookupData]s to `newlyVisitedActions`.
     */
    private fun addPropagatingActionDepsAndGetNewlyVisitedArtifactsAndActions(
        rewindGraph: com.google.common.graph.MutableGraph<SkyKey?>,
        actionKey: ActionLookupData?,
        action: Action,
        newlyVisitedArtifacts: java.util.ArrayList<DerivedArtifact>,
        newlyVisitedActions: java.util.ArrayList<ActionLookupData?>,
        nestedSetDeps: com.google.common.collect.SetMultimap<SkyKey?, ArtifactNestedSetKey?>
    ) {
        for (input in action.getInputs().toList()) {
            if (input.isSourceArtifact()) {
                continue
            }
            val artifactKey: SkyKey? = Artifact.key(input)
            // Rewinding all derived inputs of propagating actions is overkill. Preferably, we'd want to
            // only rewind the inputs which correspond to the known lost outputs. The information to do
            // this is probably present in the data available to #prepareRewindPlan.
            //
            // Rewinding is expected to be rare, so refining this may not be necessary.
            val newlyVisited: Boolean = rewindGraph.addNode(artifactKey)
            if (newlyVisited) {
                if (artifactKey is Artifact) {
                    newlyVisitedArtifacts.add(artifactKey as DerivedArtifact)
                } else if (artifactKey is ActionLookupData) {
                    newlyVisitedActions.add(artifactKey)
                }
            }
            rewindGraph.putEdge(actionKey, artifactKey)
        }

        // Record the action's NestedSet inputs as dependencies to be rewound.
        action
            .getInputs()
            .getNonLeaves()
            .forEach({ nestedSet -> nestedSetDeps.put(actionKey, ArtifactNestedSetKey.create(nestedSet)) })

        // Rewinding ignores artifacts returned by Action#getAllowedDerivedInputs because:
        // 1) the set of actions with non-throwing implementations of getAllowedDerivedInputs,
        // 2) the set of actions that "mayInsensitivelyPropagateInputs",
        // should have no overlap. Log a bug report if we see such an action:
        if (action.discoversInputs()) {
            bugReporter.sendBugReport(
                java.lang.IllegalStateException(
                    java.lang.String.format(
                        "Action insensitively propagates and discovers inputs. actionKey: %s, action: "
                                + "%.10000s",
                        actionKey, action
                    )
                )
            )
        }
    }

    /**
     * Returns the map of `lostInput`'s execution-phase dependencies (i.e. generating actions),
     * keyed by their [ActionLookupData] keys, or `null` if any of those dependencies are
     * not done.
     */
    @Throws(java.lang.InterruptedException::class)
    private fun getActionsForLostArtifact(
        lostInput: DerivedArtifact, env: SkyFunction.Environment?
    ): MutableMap<ActionLookupData?, ActionAnalysisMetadata?>? {
        val actionExecutionDeps: com.google.common.collect.ImmutableSet<ActionLookupData>? =
            getActionExecutionDeps(lostInput, env)
        if (actionExecutionDeps == null) {
            return null
        }

        val actions: MutableMap<ActionLookupData?, ActionAnalysisMetadata?> =
            com.google.common.collect.Maps.newHashMapWithExpectedSize<ActionLookupData?, ActionAnalysisMetadata?>(
                actionExecutionDeps.size()
            )
        var missingAction = false
        for (dep in actionExecutionDeps) {
            val actionAnalysisMetadata: ActionAnalysisMetadata? = getActionAnalysisMetadata(env, dep)
            if (actionAnalysisMetadata == null) {
                missingAction = true
                continue
            }
            actions.put(dep, actionAnalysisMetadata)
        }
        if (missingAction) {
            return null
        }
        return actions
    }

    @Throws(java.lang.InterruptedException::class)
    private fun getActionAnalysisMetadata(
        env: SkyFunction.Environment?, actionLookupData: ActionLookupData
    ): ActionAnalysisMetadata? {
        val actionLookupValue: ActionLookupValue? =
            ArtifactFunction.getActionLookupValue(
                actionLookupData.getActionLookupKey(),
                env,  /* crashIfActionOwnerMissing= */
                !allowSkyframeRestarts()
            )
        if (actionLookupValue == null) {
            return null
        }
        return actionLookupValue.getActions().get(actionLookupData.getActionIndex())
    }

    /**
     * Returns the set of `lostInput`'s execution-phase dependencies (i.e. generating actions),
     * or `null` if any of those dependencies are not done.
     */
    @Throws(java.lang.InterruptedException::class)
    private fun getActionExecutionDeps(
        lostInput: DerivedArtifact, env: SkyFunction.Environment?
    ): com.google.common.collect.ImmutableSet<ActionLookupData>? {
        if (!lostInput.isTreeArtifact()) {
            return com.google.common.collect.ImmutableSet.of<E?>(lostInput.getGeneratingActionKey())
        }
        val artifactDependencies: ArtifactDependencies? =
            ArtifactDependencies.discoverDependencies(
                lostInput, env,  /* crashIfActionOwnerMissing= */!allowSkyframeRestarts()
            )
        if (artifactDependencies == null) {
            return null
        }

        if (!artifactDependencies.isTemplateActionForTreeArtifact()) {
            return com.google.common.collect.ImmutableSet.of<E?>(lostInput.getGeneratingActionKey())
        }

        // This ignores the ActionTemplateExpansionKey dependency of the template artifact because we
        // expect to never need to rewind that.
        val actionTemplateExpansionKeys: com.google.common.collect.ImmutableList<ActionLookupData?>? =
            artifactDependencies.getActionTemplateExpansionKeys(env)
        if (actionTemplateExpansionKeys == null) {
            return null
        }
        return com.google.common.collect.ImmutableSet.builder<ActionLookupData?>()
            .add(lostInput.getGeneratingActionKey())
            .addAll(actionTemplateExpansionKeys)
            .build()
    }

    private fun shouldRecordRewindEventSample(): Boolean {
        return rewindEventSampleCounter.getAndIncrement() < MAX_ACTION_REWIND_EVENTS
    }

    private fun allowSkyframeRestarts(): Boolean {
        return cachingDependenciesSupplier.get().mode().isRetrievalEnabled()
    }

