    private data class LostInputRecord(val lostInputDigest: String?, val lostInputPath: String?) {
        init {
            java.util.Objects.requireNonNull<String?>(lostInputDigest, "lostInputDigest")
            java.util.Objects.requireNonNull<String?>(lostInputPath, "lostInputPath")
        }
    }

    private interface ActionAndLookupDataOrTemplate {
        fun actionAnalysisMetadata(): ActionAnalysisMetadata?
    }

    private class TemplateWrapper(actionAnalysisMetadata: ActionTemplate<*>?) : ActionAndLookupDataOrTemplate {
        val actionAnalysisMetadata: ActionTemplate<*>?

        init {
            this.actionAnalysisMetadata = actionAnalysisMetadata
            java.util.Objects.requireNonNull<Any?>(actionAnalysisMetadata, "actionAnalysisMetadata")
        }
    }

    private class ActionAndLookupData(lookupData: ActionLookupData?, actionAnalysisMetadata: Action) :
        ActionAndLookupDataOrTemplate {
