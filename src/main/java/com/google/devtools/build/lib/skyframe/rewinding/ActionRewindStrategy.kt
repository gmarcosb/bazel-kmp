        val actionAnalysisMetadata: Action

        init {
            this.actionAnalysisMetadata = actionAnalysisMetadata
            this.lookupData = lookupData
            java.util.Objects.requireNonNull<Any?>(lookupData, "lookupData")
            java.util.Objects.requireNonNull<Any?>(actionAnalysisMetadata, "actionAnalysisMetadata")
        }
