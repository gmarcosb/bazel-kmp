    companion object {
        private val logger: GoogleLogger = GoogleLogger.forEnclosingClass()

        @com.google.common.annotations.VisibleForTesting
        const val MAX_REPEATED_LOST_INPUTS: Int = 20

        @com.google.common.annotations.VisibleForTesting
        const val MAX_ACTION_REWIND_EVENTS: Int = 5
        private const val MAX_LOST_INPUTS_RECORDED = 5

        private fun prettyPrint(inputs: MutableCollection<ActionInput?>): String? {
            return inputs.stream()
                .map<String?>(java.util.function.Function { input: ActionInput? -> Companion.prettyPrint(input) })
                .collect(Collectors.joining(","))
        }

        private fun prettyPrint(input: ActionInput): String {
            return if (input is Artifact) input.prettyPrint() else input.getExecPathString()
        }

        private fun createLostInputRecords(
            lostInputsByDigest: com.google.common.collect.ImmutableSetMultimap<String?, ActionInput?>
        ): com.google.common.collect.ImmutableList<LostInputRecord> {
            return lostInputsByDigest.entries().stream()
                .map<LostInputRecord?>(java.util.function.Function { e: MutableMap.MutableEntry<String?, ActionInput?>? ->
                    LostInputRecord(
                        e.getKey(),
                        e.getValue().getExecPathString()
                    )
                })
                .collect(com.google.common.collect.ImmutableList.toImmutableList<LostInputRecord?>())
        }

        /**
         * Calculates the aggregation artifacts (tree artifacts, filesets, runfiles) that own `lostInputs`.
         */
        private fun calculateLostInputOwners(
            lostInputs: com.google.common.collect.ImmutableCollection<ActionInput?>,
            inputArtifactData: InputMetadataProvider
        ): com.google.common.collect.SetMultimap<ActionInput?, Artifact> {
            val lostInputsAndOwners: MutableSet<ActionInput?> = HashSet<ActionInput?>()
            val owners: com.google.common.collect.SetMultimap<ActionInput?, Artifact> =
                com.google.common.collect.HashMultimap.create<ActionInput?, Artifact>()
            for (lostInput in lostInputs) {
                lostInputsAndOwners.add(lostInput)
                if (lostInput is Artifact && lostInput.hasParent()) {
                    lostInputsAndOwners.add(lostInput.getParent())
                    owners.put(lostInput, lostInput.getParent())
                }
            }

            inputArtifactData
                .getFilesets()
                .forEach(
                    { fileset, outputTree ->
                        for (link in outputTree.symlinks()) {
                            if (lostInputsAndOwners.contains(link.target())) {
                                lostInputsAndOwners.add(fileset)
                                owners.put(link.target(), fileset)
                            }
                        }
                    })

            // Runfiles trees may contain tree artifacts and filesets, but not vice versa. Runfiles are
            // processed last to ensure that any lost input owning tree artifacts and filesets are already
            // in lostInputsAndOwners.
            for (runfilesTree in inputArtifactData.getRunfilesTrees()) {
                val runfilesArtifact: Artifact = inputArtifactData.getInput(runfilesTree.getExecPath()) as Artifact
                checkState(runfilesArtifact.isRunfilesTree(), runfilesArtifact)

                val runfilesValue: RunfilesArtifactValue = inputArtifactData.getRunfilesMetadata(runfilesArtifact)
                for (artifact in runfilesValue.getAllArtifacts()) {
                    if (lostInputsAndOwners.contains(artifact)) {
                        owners.put(artifact, runfilesArtifact)
                    }
                }
            }

            return owners
        }

        private fun checkDerived(artifact: Artifact) {
            com.google.common.base.Preconditions.checkState(
                !artifact.isSourceArtifact(),
                "Unexpected source artifact: %s",
                artifact
            )
        }

        private fun filterActionAndLookupDataTo(
            actions: com.google.common.collect.ImmutableList<ActionAndLookupDataOrTemplate>,
            queue: ArrayDeque<ActionAndLookupData>
        ) {
            for (action in actions) {
                when (action) {
                    -> queue.add(actionAndLookupData)
                    -> {}
                }
            }
        }

        /**
         * For an artifact `artifact` with generating actions (and their associated [ ]) `actionMap`, add those actions' keys to `rewindGraph` and add
         * edges from `artifact` to those keys.
         * 
         * 
         * Returns a list of key+action pairs for each action whose key was newly added to the graph.
         */
        private fun addArtifactDepsAndGetNewlyVisitedActions(
            rewindGraph: com.google.common.graph.MutableGraph<SkyKey?>,
            artifact: Artifact?,
            actionMap: MutableMap<ActionLookupData?, ActionAnalysisMetadata?>
        ): com.google.common.collect.ImmutableList<ActionAndLookupDataOrTemplate> {
            val newlyVisitedActions: com.google.common.collect.ImmutableList.Builder<ActionAndLookupDataOrTemplate?> =
                com.google.common.collect.ImmutableList.builderWithExpectedSize<ActionAndLookupDataOrTemplate?>(
                    actionMap.size()
                )
            val artifactKey: SkyKey = Artifact.key(artifact)
            for (actionEntry in actionMap.entrySet()) {
                val actionKey: ActionLookupData? = actionEntry.getKey()
                if (rewindGraph.addNode(actionKey)) {
                    newlyVisitedActions.add(
                        when (actionEntry.getValue()) {
                            -> ActionAndLookupData(actionKey, action)
                            -> TemplateWrapper(template)
                            else -> throw java.lang.IllegalStateException(
                                "ActionAnalysisMetadata " + actionEntry.getValue() + " of unexpected type"
                            )
                        }
                    )
                }
                if (artifactKey != actionKey) {
                    rewindGraph.putEdge(artifactKey, actionKey)
                }
            }
            return newlyVisitedActions.build()
        }

        private fun createLostOutputRewindEvent(
            failedKey: TopLevelActionLookupKeyWrapper,
            rewindPlan: Reset,
            lostOutputRecords: com.google.common.collect.ImmutableList<LostInputRecord>
        ): ActionRewindEvent {
            return createRewindEventBuilder(rewindPlan, lostOutputRecords)
                .setTopLevelActionLookupKeyDescription(failedKey.actionLookupKey().toString())
                .build()
        }

        private fun createLostInputRewindEvent(
            failedAction: Action,
            rewindPlan: Reset,
            lostInputRecords: com.google.common.collect.ImmutableList<LostInputRecord>
        ): ActionRewindEvent {
            return createRewindEventBuilder(rewindPlan, lostInputRecords)
                .setActionDescription(
                    ActionDescription.newBuilder()
                        .setType(failedAction.getMnemonic())
                        .setRuleLabel(failedAction.getOwner().getLabel().toString())
                )
                .build()
        }

        private fun createRewindEventBuilder(
            rewindPlan: Reset, lostInputRecords: com.google.common.collect.ImmutableList<LostInputRecord>
        ): ActionRewindEvent.Builder {
            return ActionRewindEvent.newBuilder()
                .addAllLostInputs(
                    lostInputRecords.stream()
                        .limit(MAX_LOST_INPUTS_RECORDED.toLong())
                        .map<Any?>(
                            java.util.function.Function { lostInputRecord: LostInputRecord? ->
                                LostInput.newBuilder()
                                    .setPath(lostInputRecord!!.lostInputPath)
                                    .setDigest(lostInputRecord.lostInputDigest)
                                    .build()
                            })
                        .collect(com.google.common.collect.ImmutableList.toImmutableList<E?>())
                )
                .setTotalLostInputsCount(lostInputRecords.size())
                .setInvalidatedNodesCount(rewindPlan.rewindGraph().nodes().size())
        }

        private fun actionAnalysisMetadatas(
            newlyVisitedActions: MutableList<ActionAndLookupDataOrTemplate>
        ): MutableList<ActionAnalysisMetadata?> {
            return com.google.common.collect.Lists.transform<ActionAndLookupDataOrTemplate?, ActionAnalysisMetadata?>(
                newlyVisitedActions,
                com.google.common.base.Function { obj: ActionAndLookupDataOrTemplate? -> obj!!.actionAnalysisMetadata() })
        }
    }
