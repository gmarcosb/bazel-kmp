/** All the information needed to perform a single Java library build operation.  */
class JavaLibraryBuildRequest @kotlin.jvm.JvmOverloads constructor(
    optionsParser: com.google.devtools.build.buildjar.OptionsParser,
    extraPlugins: MutableList<BlazeJavaCompilerPlugin>,
    depsBuilder: com.google.devtools.build.buildjar.javac.plugins.dependency.DependencyModule.Builder = com.google.devtools.build.buildjar.javac.plugins.dependency.DependencyModule.Builder(),
    workDir: Path = Path.of(""),
    requestId: OptionalInt? = OptionalInt.empty()
) {
    private val javacOpts: com.google.common.collect.ImmutableList<String?>

    /** The directory relative to which all other paths should be resolved.  */
    private val workDir: Path

    /** Where to store source files generated by annotation processors.  */
    private val sourceGenDir: Path

    /** The path to an output jar for source files generated by annotation processors.  */
    private val generatedSourcesOutputJar: Path?

    private val sourceFiles: java.util.ArrayList<Path?>
    private val sourceJars: com.google.common.collect.ImmutableList<Path?>

    private val sourcePath: com.google.common.collect.ImmutableList<Path?>
    private val classPath: com.google.common.collect.ImmutableList<Path?>
    private val bootClassPath: com.google.common.collect.ImmutableList<Path?>
    private val system: Path?

    private val processorPath: com.google.common.collect.ImmutableList<Path?>

    // TODO(bazel-team): This might be modified by a JavaLibraryBuilder to enable specific
    // annotation processors.
    val processors: MutableList<String?>

    private val outputJar: Path?
    private val nativeHeaderOutput: Path?
    val targetLabel: String?
    val injectingRuleKind: String?

    private val classDir: Path
    private val tempDir: Path

    private var jacocoInstrumentationProcessor: JacocoInstrumentationProcessor? = null

    private val compressJar: Boolean

    private val reduceClasspathMode: ReduceClasspathMode
    private val fullClasspathLength: Int
    private val reducedClasspathLength: Int

    /** Repository for all dependency-related information.  */
    private val dependencyModule: DependencyModule

    /** Repository for information about annotation processor-generated symbols.  */
    private val processingModule: AnnotationProcessingModule

    /** List of plugins that are given to javac.  */
    private val plugins: com.google.common.collect.ImmutableList<BlazeJavaCompilerPlugin?>

    private val requestId: OptionalInt?

    /**
     * Constructs a build from a list of command args. Sets the same JavacRunner for both compilation
     * and annotation processing.
     * 
     * @param optionsParser the parsed command line args.
     * @param extraPlugins extraneous plugins to use in addition to the strict dependency module.
     * @param depsBuilder a preconstructed dependency module builder.
     * @param requestId the id of executed request to builder.
     * @throws InvalidCommandLineException on any command line error
     */
    constructor(
        optionsParser: com.google.devtools.build.buildjar.OptionsParser,
        extraPlugins: MutableList<BlazeJavaCompilerPlugin>,
        depsBuilder: com.google.devtools.build.buildjar.javac.plugins.dependency.DependencyModule.Builder,
        requestId: OptionalInt?
    ) : this(optionsParser, extraPlugins, depsBuilder, Path.of(""), requestId)

    /**
     * Constructs a build from a list of command args. Sets the same JavacRunner for both compilation
     * and annotation processing.
     * 
     * @param optionsParser the parsed command line args.
     * @param extraPlugins extraneous plugins to use in addition to the strict dependency module.
     * @param depsBuilder a preconstructed dependency module builder.
     * @throws InvalidCommandLineException on any command line error
     */
    /**
     * Constructs a build from a list of command args. Sets the same JavacRunner for both compilation
     * and annotation processing.
     * 
     * @param optionsParser the parsed command line args.
     * @param extraPlugins extraneous plugins to use in addition to the strict dependency module.
     * @param depsBuilder a preconstructed dependency module builder.
     * @param workDir the directory relative to which all other paths should be resolved.
     * @throws InvalidCommandLineException on any command line error
     */
    /**
     * Constructs a build from a list of command args. Sets the same JavacRunner for both compilation
     * and annotation processing.
     * 
     * @param optionsParser the parsed command line args.
     * @param extraPlugins extraneous plugins to use in addition to the strict dependency module.
     * @throws InvalidCommandLineException on any command line error
     */
    init {
        // Keep this first as it is used by asPath.
        this.workDir = workDir
        depsBuilder.setDirectJars(
            optionsParser.directJars().stream().map<Path?> { path: String? -> this.asPath(path) }
                .collect(com.google.common.collect.ImmutableSet.toImmutableSet<Path?>()))
        if (optionsParser.getStrictJavaDeps() != null) {
            depsBuilder.setStrictJavaDeps(optionsParser.getStrictJavaDeps())
        }
        if (optionsParser.getOutputDepsProtoFile() != null) {
            depsBuilder.setOutputDepsProtoFile(asPath(optionsParser.getOutputDepsProtoFile()))
        }
        depsBuilder.addDepsArtifacts(asPaths(optionsParser.getDepsArtifacts()))
        depsBuilder.setPlatformJars(
            optionsParser.getBootClassPath().stream().map<Path?> { path: String? -> this.asPath(path) }
                .collect(com.google.common.collect.ImmutableSet.toImmutableSet<Path?>()))
        if (optionsParser.reduceClasspathMode() != ReduceClasspathMode.NONE) {
            depsBuilder.setReduceClasspath()
        }
        if (optionsParser.getTargetLabel() != null) {
            depsBuilder.setTargetLabel(optionsParser.getTargetLabel())
        }
        this.dependencyModule = depsBuilder.build()
        this.sourceGenDir =
            deriveDirectory(optionsParser.getTargetLabel(), optionsParser.getOutputJar(), "_sources")

        val processingBuilder: com.google.devtools.build.buildjar.javac.plugins.processing.AnnotationProcessingModule.Builder =
            AnnotationProcessingModule.builder()
        processingBuilder.setSourceGenDir(sourceGenDir)
        if (optionsParser.getManifestProtoPath() != null) {
            processingBuilder.setManifestProtoPath(asPath(optionsParser.getManifestProtoPath()))
        }
        this.processingModule = processingBuilder.build()

        val pluginsBuilder: com.google.common.collect.ImmutableList.Builder<BlazeJavaCompilerPlugin?> =
            com.google.common.collect.ImmutableList.builder<BlazeJavaCompilerPlugin?>().add(dependencyModule.plugin)
        processingModule.registerPlugin(pluginsBuilder)
        pluginsBuilder.addAll(extraPlugins)
        this.plugins = pluginsBuilder.build()

        this.compressJar = optionsParser.compressJar()
        this.reduceClasspathMode = optionsParser.reduceClasspathMode()
        this.fullClasspathLength = optionsParser.fullClasspathLength()
        this.reducedClasspathLength = optionsParser.reducedClasspathLength()
        this.sourceFiles = java.util.ArrayList<Path?>(asPaths(optionsParser.getSourceFiles()))
        this.sourceJars = asPaths(optionsParser.getSourceJars())
        this.classPath = asPaths(optionsParser.getClassPath())
        this.sourcePath = asPaths(optionsParser.getSourcePath())
        this.bootClassPath = asPaths(optionsParser.getBootClassPath())
        this.system = asPath(optionsParser.getSystem())
        this.processorPath = asPaths(optionsParser.getProcessorPath())
        this.processors = optionsParser.getProcessorNames()
        this.classDir =
            deriveDirectory(optionsParser.getTargetLabel(), optionsParser.getOutputJar(), "_classes")
        this.tempDir =
            deriveDirectory(optionsParser.getTargetLabel(), optionsParser.getOutputJar(), "_tmp")
        this.outputJar = asPath(optionsParser.getOutputJar())
        this.nativeHeaderOutput = asPath(optionsParser.getNativeHeaderOutput())
        for (entry in optionsParser.getPostProcessors().entries) {
            when (entry.key) {
                "jacoco" -> this.jacocoInstrumentationProcessor =
                    JacocoInstrumentationProcessor.Companion.create(entry.value)

                else -> throw java.lang.AssertionError("unsupported post-processor " + entry.key)
            }
        }
        this.javacOpts = com.google.common.collect.ImmutableList.copyOf<String?>(optionsParser.getJavacOpts())
        this.generatedSourcesOutputJar = asPath(optionsParser.getGeneratedSourcesOutputJar())
        this.targetLabel = optionsParser.getTargetLabel()
        this.injectingRuleKind = optionsParser.getInjectingRuleKind()
        this.requestId = requestId
    }

    private fun deriveDirectory(label: String, outputJar: String, suffix: String?): Path {
        return deriveDirectory(label, outputJar, suffix, workDir)
    }

    private fun asPaths(paths: MutableCollection<String?>): com.google.common.collect.ImmutableList<Path?> {
        return paths.stream().map<Path?> { path: String? -> this.asPath(path) }
            .collect(com.google.common.collect.ImmutableList.toImmutableList<Path?>())
    }

    private fun asPath(path: String?): Path? {
        return if (path != null) workDir.resolve(path) else null
    }

    fun getJavacOpts(): com.google.common.collect.ImmutableList<String?> {
        return javacOpts
    }

    fun getSourceGenDir(): Path {
        return sourceGenDir
    }

    fun getSourcePath(): com.google.common.collect.ImmutableList<Path?> {
        return sourcePath
    }

    fun getGeneratedSourcesOutputJar(): Path? {
        return generatedSourcesOutputJar
    }

    fun getSourceFiles(): java.util.ArrayList<Path?> {
        // TODO(cushon): This is being modified after parsing to add files from source jars.
        return sourceFiles
    }

    fun getSourceJars(): com.google.common.collect.ImmutableList<Path?> {
        return sourceJars
    }

    fun getClassPath(): com.google.common.collect.ImmutableList<Path?> {
        return classPath
    }

    fun getBootClassPath(): com.google.common.collect.ImmutableList<Path?> {
        return bootClassPath
    }

    fun getSystem(): Path? {
        return system
    }

    fun getProcessorPath(): com.google.common.collect.ImmutableList<Path?> {
        return processorPath
    }

    fun getOutputJar(): Path? {
        return outputJar
    }

    fun getNativeHeaderOutput(): Path? {
        return nativeHeaderOutput
    }

    fun getClassDir(): Path {
        return classDir
    }

    fun getTempDir(): Path {
        return tempDir
    }

    val nativeHeaderDir: Path
        get() = getTempDir().resolve("native_headers")

    fun getJacocoInstrumentationProcessor(): JacocoInstrumentationProcessor? {
        return jacocoInstrumentationProcessor
    }

    fun compressJar(): Boolean {
        return compressJar
    }

    fun reduceClasspathMode(): ReduceClasspathMode {
        return reduceClasspathMode
    }

    fun fullClasspathLength(): Int {
        return fullClasspathLength
    }

    fun reducedClasspathLength(): Int {
        return reducedClasspathLength
    }

    fun getDependencyModule(): DependencyModule {
        return dependencyModule
    }

    fun getProcessingModule(): AnnotationProcessingModule {
        return processingModule
    }

    fun getPlugins(): com.google.common.collect.ImmutableList<BlazeJavaCompilerPlugin?> {
        return plugins
    }

    fun getRequestId(): OptionalInt? {
        return requestId
    }

    fun toBlazeJavacArguments(classPath: com.google.common.collect.ImmutableList<Path?>?): BlazeJavacArguments? {
        val builder: com.google.devtools.build.buildjar.javac.BlazeJavacArguments.Builder =
            BlazeJavacArguments.Companion.builder()
                .classPath(classPath)
                .classOutput(getClassDir())
                .bootClassPath(getBootClassPath())
                .system(getSystem())
                .sourceFiles(com.google.common.collect.ImmutableList.copyOf<Path?>(getSourceFiles()))
                .sourcePath(getSourcePath())
                .sourceOutput(getSourceGenDir())
                .processorPath(getProcessorPath())
                .plugins(getPlugins())
                .requestId(getRequestId())
                .workDir(workDir)
        addJavacArguments(builder)
        // Performance optimization: when reduced classpaths are enabled, stop the compilation after
        // the first diagnostic that would result in fallback to the transitive classpath. The user
        // only sees diagnostics from the fallback compilation, so collecting additional diagnostics
        // from the reduced classpath compilation is a waste of time.
        // Exception: this doesn't hold if annotation processing is enabled, since diagnostics may be
        // resolved during subsequent processing rounds.
        if (reduceClasspathMode == ReduceClasspathMode.BAZEL_REDUCED
            && this.processors.isEmpty()
        ) {
            builder.failFast(this.processors.isEmpty())
        }
        if (getNativeHeaderOutput() != null) {
            builder.nativeHeaderOutput(this.nativeHeaderDir)
        }
        return builder.build()
    }

    /** Constructs a command line that can be used for a javac invocation.  */
    fun addJavacArguments(builder: com.google.devtools.build.buildjar.javac.BlazeJavacArguments.Builder) {
        val filtered: FilteredJavacopts = JavacOptions.Companion.filterJavacopts(getJavacOpts())
        builder.blazeJavacOptions(filtered.bazelJavacopts())

        val javacOpts: com.google.common.collect.ImmutableList<String> = filtered.standardJavacopts()

        val javacArguments: com.google.common.collect.ImmutableList.Builder<String?> =
            com.google.common.collect.ImmutableList.builder<String?>()

        // default to -implicit:none, but allow the user to override with -implicit:class.
        javacArguments.add("-implicit:none")
        javacArguments.addAll(javacOpts)

        if (!this.processors.isEmpty() && !getSourceFiles().isEmpty()) {
            // ImmutableSet.copyOf maintains order
            val deduplicatedProcessorNames: com.google.common.collect.ImmutableSet<String?> =
                com.google.common.collect.ImmutableSet.copyOf<String?>(
                    this.processors
                )
            javacArguments.add("-processor")
            javacArguments.add(com.google.common.base.Joiner.on(',').join(deduplicatedProcessorNames))
        } else {
            // This is necessary because some jars contain discoverable annotation processors that
            // previously didn't run, and they break builds if the "-proc:none" option is not passed to
            // javac.
            javacArguments.add("-proc:none")
        }

        for (option in javacOpts) {
            if (option.startsWith("-J")) { // ignore the VM options.
                continue
            }
            check(!(option == "-processor" || option == "-processorpath")) {
                ("Using "
                        + option
                        + " in javacopts is no longer supported."
                        + " Use a java_plugin() rule instead.")
            }
        }

        builder.javacOptions(javacArguments.build())
    }

    companion object {
        /**
         * Derive a temporary directory path based on the path to the output jar.
         * 
         * 
         * Care should be taken when changing the output directory format, in case other tools rely on
         * these paths. Historically the obsolete class based javahotswap implementation was an example,
         * see b/491357486.
         * 
         * 
         * The details of these paths are somewhat arbitrary, but there are some requirements:
         * 
         * 
         *  * The output directory path needs to be unique for unsandboxed local execution, since
         * JavaBuilder will delete and re-create the paths for each action.
         *  * It is helpful for the path to refer to the target label or output path of the original
         * compilation for debugging.
         * 
         */
        @com.google.common.annotations.VisibleForTesting
        fun deriveDirectory(label: String, outputJar: String, suffix: String?, workDir: Path): Path {
            com.google.common.base.Preconditions.checkArgument(label != null, "--target_label is required")
            com.google.common.base.Preconditions.checkArgument(outputJar != null, "--output is required")
            com.google.common.base.Preconditions.checkArgument(
                label.contains(":"), "--target_label must be a canonical label (containing a `:`)"
            )

            val path: Path = workDir.resolve(outputJar)
            val name: String = com.google.common.io.MoreFiles.getNameWithoutExtension(path)
            val base: String = label.substring(label.lastIndexOf(':') + 1)
            return path.resolveSibling("_javac").resolve(base).resolve(name + suffix)
        }
    }
