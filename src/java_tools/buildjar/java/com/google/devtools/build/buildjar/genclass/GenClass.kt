package com.google.devtools.build.buildjar.genclass

import com.google.common.annotations.VisibleForTesting
import com.google.common.collect.ImmutableSet
import com.google.devtools.build.buildjar.proto.JavaCompilation.CompilationUnit
import java.nio.file.Files
import java.nio.file.Path
import java.util.*
import java.util.function.Predicate
import java.util.jar.JarEntry
import java.util.stream.Stream
import kotlin.collections.MutableMap

/**
 * GenClass post-processes the output of a Java compilation, and produces a jar containing only the
 * class files for sources that were generated by annotation processors.
 */
object GenClass {
    @Throws(IOException::class)
    @kotlin.jvm.JvmStatic
    fun main(args: Array<String>) {
        val options = GenClassOptionsParser.parse(Arrays.asList<String?>(*args))
        val manifest: Manifest = readManifest(options.manifest())
        val classes = extractGeneratedClasses(options.classJar(), manifest)
        writeOutputJar(classes, options)
    }

    /** Reads the compilation manifest.  */
    @Throws(IOException::class)
    private fun readManifest(path: Path): Manifest {
        val manifest: Manifest
        Files.newInputStream(path).use { inputStream ->
            manifest = Manifest.parseFrom(inputStream)
        }
        return manifest
    }

    /**
     * For each top-level class in the compilation matching the given predicate, determine the path
     * prefix of classes corresponding to that compilation unit.
     */
    @VisibleForTesting
    fun getPrefixes(manifest: Manifest, p: Predicate<CompilationUnit?>?): ImmutableSet<String?> {
        return manifest.getCompilationUnitList().stream()
            .filter(p)
            .flatMap({ unit -> getUnitPrefixes(unit) })
            .collect(ImmutableSet.toImmutableSet<E?>())
    }

    /**
     * Prefixes are used to correctly handle inner classes, e.g. the top-level class "c.g.Foo" may
     * correspond to "c/g/Foo.class" and also "c/g/Foo$Inner.class" or "c/g/Foo$0.class".
     */
    private fun getUnitPrefixes(unit: CompilationUnit): Stream<String?> {
        val pkg: String?
        if (unit.hasPkg()) {
            pkg = unit.getPkg().replace('.', '/') + "/"
        } else {
            pkg = ""
        }
        return unit.getTopLevelList().stream().map({ toplevel -> pkg + toplevel })
    }

    /**
     * Unzip all the class files that correspond to annotation processor- generated sources into the
     * temporary directory.
     */
    @Throws(IOException::class)
    private fun extractGeneratedClasses(classJar: Path, manifest: Manifest): MutableMap<String?, ByteArray?> {
        val classes: MutableMap<String?, ByteArray?> = HashMap<String?, ByteArray?>()
        val generatedFilePrefixes =
            getPrefixes(manifest, Predicate { unit: CompilationUnit? -> unit.getGeneratedByAnnotationProcessor() })
        val userWrittenFilePrefixes =
            getPrefixes(manifest, Predicate { unit: CompilationUnit? -> !unit.getGeneratedByAnnotationProcessor() })
        JarFile(classJar.toFile()).use { jar ->
            jar.stream()
                .filter { entry: JarEntry? -> entry!!.getName().endsWith(".class") }
                .forEach { entry: JarEntry? ->
                    val name = entry!!.getName()
                    val className: String = name.substring(0, name.length - ".class".length)
                    if (prefixesContains(
                            generatedFilePrefixes,
                            className
                        ) // Assume that prefixes that don't correspond to a known hand-written source are
                        // generated.
                        || !prefixesContains(userWrittenFilePrefixes, className)
                    ) {
                        try {
                            jar.getInputStream(entry).use { `is` ->
                                classes.put(name, `is`.readAllBytes())
                            }
                        } catch (e: IOException) {
                            throw UncheckedIOException(e)
                        }
                    }
                }
        }
        return classes
    }

    /**
     * We want to include inner classes for generated source files, but a class whose name contains
     * '$' isn't necessarily an inner class. Check whether any prefix of the class name that ends with
     * '$' matches one of the top-level class names.
     */
    private fun prefixesContains(prefixes: ImmutableSet<String?>, className: String): Boolean {
        if (prefixes.contains(className)) {
            return true
        }
        var i: Int = className.indexOf('$')
        while (i != -1) {
            if (prefixes.contains(className.substring(0, i))) {
                return true
            }
            i = className.indexOf('$', i + 1)
        }
        return false
    }

    /** Writes the generated class files to the output jar.  */
    @Throws(IOException::class)
    private fun writeOutputJar(classes: MutableMap<String?, ByteArray?>, options: GenClassOptions) {
        val output: JarCreator = JarCreator(options.outputJar())
        output.setCompression(true)
        classes.forEach { (name: String?, content: ByteArray?) -> output.addEntry(name, content) }
        output.execute()
    }
}
